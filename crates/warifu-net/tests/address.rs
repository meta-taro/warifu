//! **宛先に載せる番地を選ぶ**（**#34**・2026-09-16）。
//!
//! Windows で WSL / Docker を入れていると、**その仮想 NIC の番地が宛先に載る。**
//! ASUS ——「**外から到達する経路はありません。届かない候補が、鍵の半分を占めます。**」
//!
//! 鍵は**人の手を渡る**ので、**短いほうが安全**である（2026-09-15 に 2 回壊れた ——
//! 94 文字の重複で弾かれた 1 本と、貼ったのに見落とされた 1 本）。
//!
//! **落とすのはループバックだけ。**帯で決め打ちして落とすと、
//! **その帯を正当に使っている人が繋がらなくなる**（社内網の `172.16/12`）。

use std::net::SocketAddr;
use warifu_net::{宛先に載せる, 載せる本数};

fn 番(文: &str) -> SocketAddr {
    文.parse().expect("読める")
}

#[test]
fn ループバックは落とす() {
    // **相手からは絶対に届かない**
    let 出た = 宛先に載せる(vec![番("127.0.0.1:1"), 番("192.168.1.5:1")]);
    assert_eq!(出た, vec![番("192.168.1.5:1")]);
}

#[test]
fn 家庭の網が先で仮想は後ろ() {
    // **落とさずに後ろへ回す** —— 172.16/12 を社内網で正当に使う人が居る
    let 出た = 宛先に載せる(vec![
        番("172.26.224.1:1"),  // WSL
        番("192.168.24.11:1"), // 本物の LAN
        番("10.1.2.3:1"),      // 社内網
    ]);
    assert_eq!(
        出た,
        vec![
            番("192.168.24.11:1"),
            番("10.1.2.3:1"),
            番("172.26.224.1:1")
        ]
    );
}

#[test]
fn dockerの橋はさらに後ろ() {
    let 出た = 宛先に載せる(vec![番("172.17.0.1:1"), 番("172.20.0.1:1")]);
    assert_eq!(出た, vec![番("172.20.0.1:1"), 番("172.17.0.1:1")]);
}

#[test]
fn dhcpが取れなかった印はいちばん後ろ() {
    // 169.254/16（APIPA）。**相手から届く見込みは無い**が、落とさない
    let 出た = 宛先に載せる(vec![番("169.254.1.2:1"), 番("192.168.1.5:1")]);
    assert_eq!(出た, vec![番("192.168.1.5:1"), 番("169.254.1.2:1")]);
}

#[test]
fn 本数を切る理由は人が手で運ぶから() {
    let 番地たち: Vec<SocketAddr> = (1..=8).map(|i| 番(&format!("192.168.1.{i}:1"))).collect();
    assert_eq!(宛先に載せる(番地たち).len(), 載せる本数);
}

#[test]
fn 同じ機械は同じ並びを出す() {
    // **突き合わせができるように、並びは 1 通り**
    let a = 宛先に載せる(vec![番("10.0.0.1:1"), 番("192.168.1.5:1")]);
    let b = 宛先に載せる(vec![番("192.168.1.5:1"), 番("10.0.0.1:1")]);
    assert_eq!(a, b);
}

#[test]
fn 重なったものは一つにする() {
    let 出た = 宛先に載せる(vec![番("192.168.1.5:1"), 番("192.168.1.5:1")]);
    assert_eq!(出た.len(), 1);
}
