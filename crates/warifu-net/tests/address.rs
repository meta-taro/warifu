//! **宛先に載せる番地を選ぶ**（**#34**・2026-09-16）。
//!
//! Windows で WSL / Docker を入れていると、**その仮想 NIC の番地が宛先に載る。**
//! ASUS ——「**外から到達する経路はありません。届かない候補が、鍵の半分を占めます。**」
//!
//! 鍵は**人の手を渡る**ので、**短いほうが安全**である（2026-09-15 に 2 回壊れた ——
//! 94 文字の重複で弾かれた 1 本と、貼ったのに見落とされた 1 本）。
//!
//! **落とすのはループバックだけ。**帯で決め打ちして落とすと、
//! **その帯を正当に使っている人が繋がらなくなる**（社内網の `172.16/12`）。

use std::net::SocketAddr;
use warifu_net::{宛先に載せる, 載せる本数};

fn 番(文: &str) -> SocketAddr {
    文.parse().expect("読める")
}

#[test]
fn ループバックは落とす() {
    // **相手からは絶対に届かない**
    let 出た = 宛先に載せる(vec![番("127.0.0.1:1"), 番("192.168.1.5:1")]);
    assert_eq!(出た, vec![番("192.168.1.5:1")]);
}

#[test]
fn 家庭の網が先で仮想は後ろ() {
    // **落とさずに後ろへ回す** —— 172.16/12 を社内網で正当に使う人が居る
    let 出た = 宛先に載せる(vec![
        番("172.26.224.1:1"),  // WSL
        番("192.168.24.11:1"), // 本物の LAN
        番("10.1.2.3:1"),      // 社内網
    ]);
    assert_eq!(
        出た,
        vec![
            番("192.168.24.11:1"),
            番("10.1.2.3:1"),
            番("172.26.224.1:1")
        ]
    );
}

#[test]
fn dockerの橋はさらに後ろ() {
    let 出た = 宛先に載せる(vec![番("172.17.0.1:1"), 番("172.20.0.1:1")]);
    assert_eq!(出た, vec![番("172.20.0.1:1"), 番("172.17.0.1:1")]);
}

#[test]
fn dhcpが取れなかった印はいちばん後ろ() {
    // 169.254/16（APIPA）。**相手から届く見込みは無い**が、落とさない
    let 出た = 宛先に載せる(vec![番("169.254.1.2:1"), 番("192.168.1.5:1")]);
    assert_eq!(出た, vec![番("192.168.1.5:1"), 番("169.254.1.2:1")]);
}

#[test]
fn 本数を切る理由は人が手で運ぶから() {
    let 番地たち: Vec<SocketAddr> = (1..=8).map(|i| 番(&format!("192.168.1.{i}:1"))).collect();
    assert_eq!(宛先に載せる(番地たち).len(), 載せる本数);
}

#[test]
fn 同じ機械は同じ並びを出す() {
    // **突き合わせができるように、並びは 1 通り**
    let a = 宛先に載せる(vec![番("10.0.0.1:1"), 番("192.168.1.5:1")]);
    let b = 宛先に載せる(vec![番("192.168.1.5:1"), 番("10.0.0.1:1")]);
    assert_eq!(a, b);
}

#[test]
fn 重なったものは一つにする() {
    let 出た = 宛先に載せる(vec![番("192.168.1.5:1"), 番("192.168.1.5:1")]);
    assert_eq!(出た.len(), 1);
}

// ---------------------------------------------------------------------------
// **口の種類が分かるとき**（#34 の 3 番目・2026-09-18）
//
// 並べ替えは**上限を超えたときにだけ効く。**ASUS の機械は口が 2 つで上限は 4 本 ——
// **並べ替えても両方載るので、「この人は WSL を入れている」は今も鍵から読める。**
// ---------------------------------------------------------------------------

use warifu_net::{口の種類, 宛先に載せる_口の種類つき};

/// WSL の番地だけを「仮想」と答える口見（ASUS の実測に合わせた）
fn asus_の口(ip: std::net::IpAddr) -> 口の種類 {
    if ip.to_string() == "172.26.224.1" {
        口の種類::仮想
    } else {
        口の種類::分からない
    }
}

#[test]
fn 仮想だと分かっている口は落とす() {
    // **ASUS の実測**（#34）—— 段1 に 2 本載っていて、片方が WSL だった
    let 出た = 宛先に載せる_口の種類つき(
        vec![番("172.26.224.1:54143"), 番("192.168.24.11:54143")],
        asus_の口,
    );
    assert_eq!(出た, vec![番("192.168.24.11:54143")]);
}

#[test]
fn 分からない口は落とさない() {
    // **「分からない」を「仮想」に倒さない。**倒すと本物の網を落とす
    let 出た = 宛先に載せる_口の種類つき(
        vec![番("172.26.224.1:1"), 番("192.168.1.5:1")],
        |_| 口の種類::分からない,
    );
    assert_eq!(出た.len(), 2);
}

#[test]
fn 全部が仮想なら落とさない() {
    // **WSL の中で動かしている機械は、仮想の口しか持っていない。**
    // 落とすと宛先が空になって、**誰にも届かなくなる**
    let 出た = 宛先に載せる_口の種類つき(
        vec![番("172.26.224.1:1"), 番("172.17.0.1:1")],
        |_| 口の種類::仮想,
    );
    assert_eq!(出た.len(), 2, "全部落ちるなら落とさない");
}

#[test]
fn 口を見ないときは前と同じ() {
    // **既にある呼び出しの挙動を変えない**（`宛先に載せる` は「分からない」で通す）
    let 番地たち = vec![番("172.26.224.1:1"), 番("192.168.1.5:1"), 番("127.0.0.1:1")];
    assert_eq!(
        宛先に載せる(番地たち.clone()),
        宛先に載せる_口の種類つき(番地たち, |_| 口の種類::分からない)
    );
}

#[test]
fn 落としたあとも_届きそうな順のまま() {
    let 出た = 宛先に載せる_口の種類つき(
        vec![番("10.0.0.1:1"), 番("172.26.224.1:1"), 番("192.168.1.5:1")],
        asus_の口,
    );
    // WSL が消えて、192.168 → 10 の順
    assert_eq!(出た, vec![番("192.168.1.5:1"), 番("10.0.0.1:1")]);
}

/// **宛先そのものが、届きそうな順を保つ**（2026-09-24・ASUS の実測）。
///
/// `宛先に載せる` が並べても、`Address` が番地の数値順に並べ直していたので、
/// **WSL の口が先頭に戻っていた**（`172.26.224.1 < 192.168.24.11`）。
mod 宛先の並び {
    use super::番;
    use warifu_core::Seed;
    use warifu_net::Address;

    fn 鍵() -> warifu_core::PublicKey {
        Seed::from_bytes([7u8; 32])
            .profile("Personal")
            .device("mini")
            .public_key()
    }

    #[test]
    fn 数値順に並べ直さない() {
        // **ASUS が実際に出していた 2 件**
        let 宛先 =
            Address::from_ip_addrs(鍵(), [番("172.26.224.1:62602"), 番("192.168.24.11:62602")]);
        let 並び: Vec<_> = 宛先.ip_addrs().collect();
        assert_eq!(
            並び,
            vec![番("192.168.24.11:62602"), 番("172.26.224.1:62602")],
            "家庭の網が先。**数値順だと WSL が先頭に戻る**"
        );
    }

    #[test]
    fn 文字にして戻しても_並びが変わらない() {
        // **相手が読み直したときも同じ順である**（先頭から当てにいく）
        let 宛先 =
            Address::from_ip_addrs(鍵(), [番("172.26.224.1:62602"), 番("192.168.24.11:62602")]);
        let 戻り: Address = 宛先.to_string().parse().expect("読める");
        assert_eq!(
            戻り.ip_addrs().collect::<Vec<_>>(),
            宛先.ip_addrs().collect::<Vec<_>>()
        );
    }

    #[test]
    fn 同じ番地は_1回だけ載る() {
        // **並べ替えを変えても、重なりを落とす所は変えていない**
        let 宛先 = Address::from_ip_addrs(
            鍵(),
            [番("192.168.1.5:1"), 番("192.168.1.5:1"), 番("10.0.0.2:1")],
        );
        assert_eq!(
            宛先.ip_addrs().collect::<Vec<_>>(),
            vec![番("192.168.1.5:1"), 番("10.0.0.2:1")]
        );
    }
}
