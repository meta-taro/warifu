//! **待つ口を、立ち上げ直しても同じにする**（**#38 の残り半分**・2026-09-17）。
//!
//! **鍵は「出したときの口」を焼き込む。**だから口が変わると、
//! **配った鍵は全部死ぬ** —— 割符を控えても、相手が来る場所が無い。
//!
//! ASUS の実測（2026-09-17）——
//!
//! ```text
//! 鍵が指す口   51728   ← 09-16 10:32 に出した
//! 待っている口 57155   ← 入れ替えて立ち上げ直したあと
//! ```
//!
//! **ここで固定するのは 2 つ。**
//!
//! 1. **同じ口を取りに行けること**（案 A）
//! 2. **取れなかったことが、黙って消えないこと**（案 C）
//!
//! **1 だけでは嘘になる。**取れなかったのに黙って空きへ落ちると、
//! **人は鍵が死んだことを知らないまま待つ**（2026-09-16 に Mac Air が 6 時間待った）。
//!
//! 中継は使わない（外に出ないので、回線が無くても走る）。

use warifu_net::{Node, 中継の使い方, 口の様子, 口の決め方};

fn 端末(seed: u8, label: &str) -> warifu_core::Device {
    warifu_core::Seed::from_bytes([seed; 32])
        .profile("Personal")
        .device(label)
}

async fn 結ぶ(device: &warifu_core::Device, 決め方: 口の決め方) -> Node {
    Node::bind_at(device, 中継の使い方::使わない, 決め方)
        .await
        .expect("結べる")
}

// ── 言い表し（**数を数えずに確かめられる所**） ─────────────────────

#[test]
fn 取り直せたときだけ_前の鍵が生きていると言う() {
    // **「分からない」を「使える」と言わない。**
    // `まかせた` は前が無いので、**生きているとは言えない**
    assert!(口の様子::取り直せた(57155).前の鍵が生きているか());
    assert!(!口の様子::まかせた(57155).前の鍵が生きているか());
    assert!(
        !口の様子::取れなかった {
            望んだ: 51728,
            代わり: 57155,
        }
        .前の鍵が生きているか()
    );
}

#[test]
fn いま待っている口を_どの言い表しからも取れる() {
    // **取れなかったときに返すのは「代わり」のほう。**
    // 望んだ口を返すと、**鍵に死んだ口を焼き込む**ことになる
    assert_eq!(口の様子::まかせた(1).口(), 1);
    assert_eq!(口の様子::取り直せた(2).口(), 2);
    assert_eq!(
        口の様子::取れなかった {
            望んだ: 51728,
            代わり: 57155,
        }
        .口(),
        57155
    );
}

// ── 実物の口（**iroh に本当に取らせる**） ──────────────────────────

#[tokio::test]
async fn 任せると_口は決まるが_同じとは限らない() {
    let node = 結ぶ(&端末(1, "PC"), 口の決め方::まかせる).await;
    let 様子 = node.口の様子();

    assert!(matches!(様子, 口の様子::まかせた(_)));
    assert_ne!(様子.口(), 0, "口が決まっていない");
    // **任せた口は、次の起動で変わる。**だから鍵は死ぬ、というのが #38
    assert!(!様子.前の鍵が生きているか());
}

#[tokio::test]
async fn 前と同じ口を_取り直せる() {
    // **これが #38 の狙いそのもの。**
    // 1 度目で決まった口を控え、閉じて、同じ口で立ち上げ直す
    let device = 端末(2, "PC");

    let 一度目 = 結ぶ(&device, 口の決め方::まかせる).await;
    let 控えた口 = 一度目.口の様子().口();
    drop(一度目);
    // **閉じ切るのを待つ。**OS が口を返すまでに間がある
    tokio::time::sleep(std::time::Duration::from_millis(200)).await;

    let 二度目 = 結ぶ(&device, 口の決め方::同じ口(控えた口)).await;

    assert_eq!(
        二度目.口の様子(),
        口の様子::取り直せた(控えた口),
        "同じ口を取り直せていない（配った鍵が死ぬ）"
    );
    assert!(二度目.口の様子().前の鍵が生きているか());
}

#[tokio::test]
async fn 取れなかったら_黙って落ちずに_そう言う() {
    // **案 C の所。**取れなかったこと自体は避けられない ——
    // **避けられないなら、せめて黙らない**
    let 先客 = 結ぶ(&端末(3, "先客"), 口の決め方::まかせる).await;
    let 塞がった口 = 先客.口の様子().口();

    let 後から = 結ぶ(&端末(4, "後から"), 口の決め方::同じ口(塞がった口)).await;
    let 様子 = 後から.口の様子();

    match 様子 {
        口の様子::取れなかった {
            望んだ, 代わり
        } => {
            assert_eq!(望んだ, 塞がった口);
            assert_ne!(代わり, 0, "代わりの口が決まっていない");
            assert_ne!(代わり, 塞がった口, "塞がっている口を取れたことになっている");
        }
        ほか => panic!("塞がった口を取れたことになっている: {ほか:?}"),
    }

    // **取れなかったのだから、前の鍵は死んでいる。**ここを取り違えない
    assert!(!様子.前の鍵が生きているか());
    // **結び目そのものは立っている。**口が取れないだけで落ちない
    assert_ne!(様子.口(), 0);

    drop(先客);
}
