//! **宛先に載せる番地を選ぶ**（**#34**・2026-09-16）。
//!
//! # 何に困っていたか
//!
//! Windows で WSL / Docker / VirtualBox を入れていると、
//! **その仮想 NIC の番地がそのまま宛先に載る。**ASUS の実測（#34）——
//!
//! > **外から到達する経路はありません。**相手は届かない先へ当てにいきます。
//! > **届かない候補が、鍵の半分を占めます。**
//!
//! 鍵は**人の手を渡る**（368 文字）。今日それで 2 回壊れた（貼り間違い・重複）。
//! **短いほうが安全である。**
//!
//! # なぜ「名前で外す」をやらないか
//!
//! `vEthernet (WSL)` のような**NIC の名前は、この層まで来ない**（番地だけ来る）。
//! **帯で外すのも危ない** —— WSL は `172.16/12` を使うが、
//! **社内網で正当に使っている所がある。**落とすと、その人は繋がらなくなる。
//!
//! # 代わりに：**届きそうな順に並べて、本数を切る**
//!
//! 落とすのではなく**後ろへ回す。**誤って落とす危険が小さく、鍵も短くなる。

use std::net::{IpAddr, SocketAddr};

/// 宛先に載せる本数の上限。
///
/// **人が手で運ぶ**ので、長さがそのまま事故になる。
/// 4 本あれば、ふつうの機械（有線・無線・IPv6）は載る。
pub const 載せる本数: usize = 4;

/// その番地の「届きそうさ」。**小さいほど先に載る。**
///
/// **`Address` からも使う。**あちらが番地の数値順に並べ直していたので、
/// **ここで並べた順が消えていた**（2026-09-24・ASUS の実測）——
/// **順を決める規則は 1 つにする。**
pub(crate) fn 見込み(ip: IpAddr) -> u8 {
    match ip {
        IpAddr::V4(v4) => {
            let [a, b, ..] = v4.octets();
            match (a, b) {
                // **家庭・小規模の網でいちばん多い**
                (192, 168) => 0,
                // 社内網に多い
                (10, _) => 1,
                // **Docker の既定の橋**（`172.17/16`）。仮想がここに集まる
                (172, 17) => 4,
                // `172.16/12` —— **WSL / Hyper-V もここを使うが、社内網も使う。**
                // だから**落とさずに、後ろへ回す**
                (172, 16..=31) => 3,
                // APIPA（DHCP が取れなかった印）。**相手から届く見込みは無い**
                (169, 254) => 5,
                _ => 2,
            }
        }
        IpAddr::V6(v6) => {
            if v6.is_loopback() {
                5
            } else if v6.segments()[0] & 0xffc0 == 0xfe80 {
                // リンクローカル。**範囲の印が要るので、宛先としては当てにしにくい**
                4
            } else {
                2
            }
        }
    }
}

/// **その番地が乗っている口は、外へ出るのか。**
///
/// **番地の数字だけでは決まらない**（`172.16/12` は社内網でも正当に使われる）。
/// **口の種類は、機械ごとの仕組みでしか分からない** ——
/// Windows なら `Get-NetAdapter` の `InterfaceDescription`
/// （`Hyper-V Virtual Ethernet Adapter` など）。
///
/// **分からないときは [`口の種類::分からない`]。**
/// **「分からない」を「仮想」に倒さない** —— 倒すと、本物の網を落とす。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 口の種類 {
    /// **仮想の口だと分かっている**（WSL / Hyper-V / Docker / VirtualBox / VMware）。
    仮想,
    /// **分からない。**——**本物として扱う。**
    分からない,
}

/// **宛先に載せる番地を選ぶ。**
///
/// - **ループバックは落とす**（相手からは絶対に届かない）
/// - **残りは「届きそうな順」に並べる**（仮想 NIC は後ろへ回る）
/// - **上限 [`載せる本数`] で切る**（人が運ぶので、長さが事故になる）
///
/// **落とすのはループバックだけ。**帯で決め打ちして落とすと、
/// **その帯を正当に使っている人が繋がらなくなる。**
///
/// **口の種類が分かるなら [`宛先に載せる_口の種類つき`] を使う。**
#[must_use]
pub fn 宛先に載せる(番地たち: impl IntoIterator<Item = SocketAddr>) -> Vec<SocketAddr> {
    宛先に載せる_口の種類つき(番地たち, |_| 口の種類::分からない)
}

/// **口の種類が分かるとき。仮想だと分かっている口の番地を落とす。**
///
/// # なぜ並べ替えだけでは足りないか（**2026-09-18**）
///
/// 並べ替えは**上限を超えたときにだけ効く。**ASUS の機械は口が 2 つ
/// （WSL と Wi-Fi）で、上限は 4 本 —— **並べ替えても両方載る。**
///
/// **#34 の 3 番目が残っていた** ——
///
/// > **その PC の中の網の構成が、鍵を渡した相手全員に見えます。**
/// > `172.26.224.1` は「この人は WSL を入れている」と言っています。
///
/// **渡す必要のない事実である。**落とさないと消えない。
///
/// # 落とし過ぎない 2 つの歯止め
///
/// 1. **「分からない」は落とさない**（[`口の種類::分からない`]）——
///    本物の網を落とす事故のほうが重い
/// 2. **全部落ちるなら、落とさない** —— WSL の中で動かしている機械は、
///    **仮想の口しか持っていない。**落とすと宛先が空になって、誰にも届かなくなる
#[must_use]
pub fn 宛先に載せる_口の種類つき(
    番地たち: impl IntoIterator<Item = SocketAddr>,
    口を見る: impl Fn(IpAddr) -> 口の種類,
) -> Vec<SocketAddr> {
    let mut 並び: Vec<SocketAddr> = 番地たち
        .into_iter()
        .filter(|a| !a.ip().is_loopback())
        .collect();
    並び.sort_unstable();
    並び.dedup();
    // **仮想だと分かっている口を落とす。**ただし**全部落ちるなら落とさない**
    let 残り: Vec<SocketAddr> = 並び
        .iter()
        .copied()
        .filter(|a| 口を見る(a.ip()) != 口の種類::仮想)
        .collect();
    if !残り.is_empty() {
        並び = 残り;
    }
    // **安定な並び**（同じ機械が同じ宛先を出す）。見込みが同じなら番地の順
    並び.sort_by_key(|a| (見込み(a.ip()), *a));
    並び.truncate(載せる本数);
    並び
}
