//! この機械とやり取りする 1 行の形。**JSON を 1 行に 1 つ。**

use serde::{Deserialize, Serialize};

/// 本文の上限（バイト）。
///
/// **一度にどれだけ流すかを、繋いできた側に決めさせない。**
/// 会話の 1 発言としては十分で、貼り付けた丸ごとのログは通らない大きさにする。
pub const 本文の上限: usize = 4096;

/// エージェント → この機械。
///
/// **差出人を書く場所が無いのは意図。**誰が言ったかはこの機械が刻む。
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(tag = "型", rename_all = "snake_case", deny_unknown_fields)]
pub enum ToDesk {
    /// 会話へ 1 行流す。
    Say {
        /// 本文。空は送れない。[`本文の上限`] を超えたら受けない。
        body: String,
    },
    /// **ルームキーを出す**（**#32 の段 2**・2026-09-21）。
    ///
    /// # なぜエージェントから出せるようにしたのか
    ///
    /// オーナー（2026-09-21）——
    ///
    /// > **人を介すときというのは、UI/UX とかのテスト以外は、
    /// > 基本エージェントが動かせることの方が重要になります。**
    ///
    /// **鍵を出すのに人を介す意味が無かった。**人が押しても判断していない
    /// （数字の `1` とボタンがあるだけ）。**そして主張と矛盾していた** ——
    /// シート 24 は「**最初の 1 回だけ人が許し、以後は人抜きで往復する**」なのに、
    /// **招くたびに人が押していた。**
    ///
    /// **人の 1 回は札に置く**（`room.invite`・**D119**）。**鍵はエージェントが出す。**
    ///
    /// **返る鍵は割符の片割れである**（持参人式・**D31 の追記**）——
    /// **渡した相手だけに渡す。公開の場に貼らない。**
    招く {
        /// 何本出すか。**1 本＝1 人**（**D12**）。上限は [`招ける本数`]。
        何本: u8,
        /// いつまで使えるか（秒）。`None` なら既定（24 時間）。
        #[serde(default)]
        秒: Option<u64>,
    },
    /// これまでの会話をもらってから、以後を聞く。
    ///
    /// **どこで起動しているエージェントかを名乗る。**
    /// 1 台の PC で複数のエージェントが同じこの機械につながるので、
    /// まとめて 1 人に見せると**どれが喋ったのか分からない**
    /// （2026-09-08 オーナー指摘）。
    ///
    /// **これは差出人の名乗りではない。**名乗れるのは「どこで動いているか」だけで、
    /// 誰が言ったかを刻むのはこの機械である（[`ToDesk::Say`] に `from` が無いのと同じ約束）。
    /// この機械はこれを「◯◯ のエージェント」という形に**包んで**出す。
    Listen {
        /// どこで動いているか（フォルダ名など）。名乗らなければ `None`。
        場所: Option<String>,
        /// **どこから聞くか。**この番号より後の発言をもらう（`None` なら新しい分だけ）。
        ///
        /// **「どこから」は読み手が言う。**この機械は「誰がどこまで読んだか」を
        /// 覚えない —— 覚えると**既読を作ることになる**（**D94** で作らないと決めた）。
        ///
        /// **これが無いと、繋ぎ直したエージェントは、切れている間の言葉を
        /// 永久に聞けない**（`.claude/issues/019`）。人は画面で過去を読めるが、
        /// エージェントは読めない。**しかも落ちたことが誰にも見えない。**
        ///
        /// **古いエージェントは書いてこない。**書いてこなければ `None`（今までと同じ）。
        #[serde(default)]
        どこから: Option<u64>,
    },
    /// **そこまで読んだ**と告げる（**既読**・**D76**）。
    ///
    /// オーナー指示（2026-09-08）——
    /// 「**既読　既読 1　既読 2 みたいな LINE の仕様は必要かもですね。
    ///   それも MCP で確認できないと、エージェントも読んでもらったかわからない。**」
    ///
    /// **読んだのは、渡された時点である。**`chat_read` / `chat_wait` が
    /// 発言を呼び手へ渡したときに、この行を送る。
    /// **中身を理解したかは誰にも分からない**ので、そこは名乗らない。
    Read {
        /// ここまで読んだ、という番号（この番号を含む）。
        まで: u64,
    },
    /// **その発言が、いま誰に届いていて、誰が読んだか**を尋ねる（**D76**）。
    Status {
        /// どの発言か。
        id: u64,
    },
    /// **いまの様子を尋ねる**（ルーム・名簿・経路・待っているリンク）。
    ///
    /// オーナー指示（2026-09-11）——
    /// 「**押したのを検知できたりする MCP いれてください。**」
    /// リンクを押して人がルームへ入った瞬間を、エージェントから見たい。
    ///
    /// **画面が既に持っている値を返すだけ。**ここで数え直さない ——
    /// 数える所が 2 つになると、必ずずれる。
    Status様子,
    /// **自分のエージェントのプロフィールを書く。**
    ///
    /// オーナー指示（2026-09-08）——
    /// 「**エージェントが MCP で接続できたらエージェント自身に
    /// プロフィールをかけるようにしておくと、楽だとおもいます。**」
    ///
    /// **書けるのは自分のエージェントだけ。**どのエージェントかは**繋いできた口で決まる**ので、
    /// ここに「誰の」は書けない —— 書けると、**同じ機械の別のエージェントに化けられる。**
    ///
    /// **名乗り（どこで動いているか）はここでは変えられない。**
    /// あれは立ち上げるときに人が決める（`--as`）。**変えられると、エージェントそのものを偽れる。**
    Profile {
        /// 表に出す名前。**空にすると消える。**
        名前: String,
        /// 短い紹介。**空にすると消える。**
        紹介: String,
    },
    /// **札を頼む**（**D119** / **#26** / **#12**）。
    ///
    /// **頼みは部屋へ流さない。**この機械（同じ PC の中）を通る ——
    /// **だから頼みが外へ出ることがない。**
    ///
    /// 2026-09-15、ASUS の画面にこれが届いた（#26）——
    ///
    /// ```text
    /// 18:44  I3ILQUUJQHVS…  #19 にメッセージを送信するための許可が必要です。…
    /// ```
    ///
    /// **エージェントが人に聞く言葉が、部屋の全員に流れていた。**
    /// **聞く口と流す口が同じだった**からである。**ここで分ける。**
    ///
    /// # 返りは 1 通で足りる
    ///
    /// [`FromDesk::Asked`] が**いまの答え**を返すので、
    /// **頼むのと様子を聞くのが同じ口になる。**
    /// まだなら `まだ` が返るので、**間を置いてもう一度頼めばよい。**
    Ask {
        /// 何をしたいか（`chat.send` など）。
        動作: String,
        /// **なぜ要るか。**人が一言で読める長さにする。
        ///
        /// **これが無い頼みは、人に見せる前に落とす** ——
        /// **何を許すかが一言で読めなければ、「OK」は同意ではない。**
        訳: String,
    },
    /// **人が答えるのを待つ**（2026-09-24・Mac Air の席の提案）。
    ///
    /// # なぜ要るか —— **押されたことは、こちらへ届かない**
    ///
    /// オーナー（Mac Air の席ごしに・2026-09-24）——
    ///
    /// > **押した時点であなたが検知できないということでしょう。
    /// > ずーっと前から指摘しています。**
    ///
    /// **[`ToDesk::Ask`] は「いまの答え」を返すだけである。**
    /// 人が押しても、**エージェントには何も届かない** ——
    /// だから毎回「押しましたか」「押しました」の往復が要る。
    /// **人が、エージェントの目の代わりをしている。**
    ///
    /// ```text
    /// いま   頼む → 人が押す → **こちらは知らない** → 人が言う → 覗きに行く
    /// これから 頼んで**待つ** → 人が押す → **その場で動き出す**
    /// ```
    ///
    /// **`chat_wait` と同じ形である**（`warifu-mcp` の説明 ——
    /// 「**覗きに行く口しか無いと、エージェントは自分から気づけない**」）。
    /// **同じ理屈が札にも当たっていた。**
    ///
    /// # 待つだけで、押させる力は持たない
    ///
    /// **札を出すのは人である**（**D56**）。この口は**待つ**だけで、
    /// **答えを作らない。**時間切れなら [`頼みの返り::まだ`] が返る。
    札を待つ {
        /// 何をしたいか（`chat.send` など）。
        動作: String,
        /// **なぜ要るか。**[`ToDesk::Ask`] と同じ ——
        /// **待つ口でも、人が読む言葉は要る**（帯に出るのはこれである）。
        訳: String,
        /// 何秒まで待つか。省くと 30 秒。**上限は [`札を待てる秒`]。**
        ///
        /// **永遠には待たない。**待っている間、そのエージェントは何もできない。
        秒: Option<u64>,
    },
}

/// 名乗れる長さ（文字）。
///
/// **画面の 1 行に収まる長さに切る。**長いものを通すと、連絡帳の並びが崩れる。
pub const 名乗りの上限: usize = 32;

/// **一度に出せるルームキーの本数**（**#32 の段 2**・2026-09-21）。
///
/// **1 本＝1 人**（**D12**）なので、部屋の定員と同じでよい。
/// **上限を置くのは、無限に出させないため** ——
/// 鍵は持参人式（**D31 の追記**）で、出した分だけ入り口が増える。
pub const 招ける本数: u8 = 12;

/// **札を待てる秒**（2026-09-24）。
///
/// **`chat_wait` と同じ 60 秒**にしてある ——
/// **2 か所で違う上限を持つと、どちらが本当か分からなくなる。**
pub const 札を待てる秒: u64 = 60;

/// 待つ秒を検める。**上限を超えるものは、この機械まで運ばない。**
fn 待つ秒を検める(秒: Option<u64>) -> Result<(), Error> {
    match 秒 {
        // **0 は「待たない」ではなく、書き間違いとして扱う** ——
        // 待たないなら `Ask` を使えばよい
        Some(0) => Err(Error::Empty),
        Some(秒) if 秒 > 札を待てる秒 => Err(Error::TooLong(秒 as usize)),
        _ => Ok(()),
    }
}

/// 札を頼むときの訳の上限（バイト・**D119**）。
///
/// **人が一言で読める長さに収める。**
/// **読めない長さの訳は、「OK」を押させるための飾りになる。**
pub const 訳の上限: usize = 140;

/// 札の頼みへの答え（**D119**）。
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(tag = "答え", rename_all = "snake_case", deny_unknown_fields)]
pub enum 頼みの返り {
    /// **まだ人が答えていない。**間を置いてもう一度頼めばよい。
    まだ,
    /// 人が許した。**次の呼びで通る。**
    許した,
    /// **人が断った。**
    ///
    /// **もう一度頼んでも、また `断った` が返る** ——
    /// 聞き直すと**同じ札を何度も頼む**ことになり、
    /// **読まれなくなった許可の口は、無いのと同じ**になる（#33 / #35 で踏んだ形）。
    /// **取り消すのは人である**（**D58**）。
    断った,
    /// **受け付けなかった。****人に見せてもいない。**
    ///
    /// **「どうすれば通るか」は書かない**（`Decision::Deny` と同じ構え）——
    /// 書くと、断られた側が総当たりで札の形を探れる。
    受け付けない {
        /// 何が悪かったか（`訳がありません` など）。**直し方は書かない。**
        訳: String,
    },
}

/// この機械 → エージェント。
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(tag = "型", rename_all = "snake_case", deny_unknown_fields)]
pub enum FromDesk {
    /// 誰かが喋った。
    Heard {
        /// **通し番号。**この機械が刻む。既読を数えるのに使う（**D76**）
        ///
        /// **古いこの機械は 0 を返す。**0 は「番号が無い」と読む
        #[serde(default)]
        id: u64,
        /// 誰が。**この機械が刻む。**繋いできた側は書けない
        from: String,
        /// 本文
        body: String,
        /// いつ（`HH:MM`）。**無いと、あとから読み返せない**
        at: String,
    },
    /// 誰かが入った。
    Joined {
        /// 誰が
        who: String,
    },
    /// 誰かが出た（または落ちた）。
    Left {
        /// 誰が
        who: String,
    },
    /// 流した。**何人へ届けたかを返す。**
    ///
    /// **「送った」と言うなら、何人へかまで言う。**
    /// 言わないと、0 人へ流したことと区別が付かない（**D49**）。
    Sent {
        /// 何人へ流したか。**0 にはならない**（0 なら [`FromDesk::Nobody`]）
        to: usize,
        /// **この発言の通し番号。**あとで既読を尋ねるのに使う（**D76**）
        #[serde(default)]
        id: u64,
        /// **どのエージェントへ届けたか。**「3 人」だけでは、誰に届いたか分からない
        /// （`issues/4`）。**画面（人）も 1 つとして並ぶ**
        #[serde(default)]
        届いた: Vec<String>,
    },
    /// **いまの様子**（[`ToDesk::Status様子`] の返り）。
    ///
    /// **分からないものは `None` / 空で返す。**
    /// 「不明」を「直接」に倒さない（DESIGN §2 原則 7）。
    様子 {
        /// いま見ているルームの id。居なければ `None`
        ルーム: Option<String>,
        /// ルームに居る相手の鍵（**自分は入らない**）
        名簿: Vec<String>,
        /// 経路（`direct` / `relayed` / `unknown`）。分からなければ `None`
        経路: Option<String>,
        /// この機械につながっているエージェントの呼び名
        エージェント: Vec<String>,
        /// **押されて、まだ人が答えていないリンクの数。**
        /// 「入りますか？」が画面に出たままの状態である
        待っているリンク: usize,
        /// **どのルームについて待っているか**（古い順・`gh issue 12`）。
        ///
        /// 本数だけでは「**誰に声をかければいいか**」が分からない。
        /// **ルームキーそのものは入れない** —— あれは割符の片割れであり、
        /// この返りは札（`chat.read`）さえあれば読める。
        ///
        /// **古いこの機械は空で返す**（`serde(default)`）。
        #[serde(default)]
        待っているルーム: Vec<String>,
        /// **いま画面に映っているもの**（**#32**・2026-09-18）。
        ///
        /// ASUS のエージェント ——
        ///
        /// > **自分の枠に映像が出ているか** —— 今日いちばん要った
        /// > **相手の枠に映像が出ているか** —— **本題そのもの**
        ///
        /// **これが無いので、測るたびに人のマウスを奪って画面を撮っていた。**
        ///
        /// **`None` は「まだ言ってきていない」であって「出ていない」ではない**
        /// （DESIGN §2 原則 7 —— 分からないものを倒さない）。
        /// **古い画面は言ってこない**ので `None` のままになる。
        #[serde(default)]
        送っている: Option<bool>,
        /// 相手の枠に映像が出ているか。`None` は「まだ言ってきていない」。
        #[serde(default)]
        受けている: Option<bool>,
        /// **カメラかマイクを掴んでいるか**（明かりが点いているか）。
        ///
        /// **「送っていない」と「掴んでいない」は別のこと**（**D116**）——
        /// パケットが 0 でも、**明かりが点いていれば人は気にする。**
        #[serde(default)]
        掴んでいる: Option<bool>,
        /// **画面に出ている題字そのもの**（訳したあとの文字）。
        ///
        /// ASUS ——「**`経路` は在るが、画面の文言と一致する保証が無い**」。
        /// **だから札ではなく、出ている文字をそのまま渡す。**
        #[serde(default)]
        題字: Option<String>,
    },
    /// **出したルームキー**（[`ToDesk::招く`] の返り）。
    ///
    /// **中身は割符の片割れである。**記録に書かない・公開の場に貼らない。
    招いた {
        /// 出した鍵。**1 本＝1 人。**
        鍵たち: Vec<String>,
        /// いつまで使えるか（人が読める形）。
        ///
        /// **渡す相手が期限を計算しなくてよいように**（2026-09-18・ASUS の求め）——
        /// 「**それは、渡された側がやる作業ではないと思います**」。
        いつまで: String,
    },
    /// まだ会話の相手が居ない。**「送った」と嘘をつかない。**
    Nobody,
    /// **止まれ。**人が画面から押した。
    ///
    /// 常駐（`warifu agent`）が、人が居ない間に動き続けることがある。
    /// **落とすしか止め方が無い状態にしない** ——
    /// この機械ごしに「止まれ」と言えるようにする（`issues/014`）。
    ///
    /// **これは命令ではない。**受けた側が自分で止まる。
    /// 割符は相手のプロセスを殺さない。
    Stop,
    /// **札の頼みへの答え**（**D119**）。
    ///
    /// **「断り」と「受け付けない」を分けてある** ——
    /// 断りは**人が見て断った**、受け付けないは**人に見せてもいない**（形が悪い）。
    /// **混ぜると、エージェントは「人が断った」と誤解して諦める。**
    Asked {
        /// どの動作についてか。
        動作: String,
        /// いまの答え。
        答え: 頼みの返り,
    },
    /// 断った。
    Denied {
        /// 何を断ったか。**どうすれば通るかは書かない**
        why: String,
    },
    /// **その発言の届き方**（**D76**）。
    ///
    /// **「届いた」と「読んだ」を分ける。**
    /// 届いたのはこの機械が配った先、読んだのは**渡された**ことが確かなエージェントだけである。
    /// **人の画面は「出した」までしか言わない** —— 見たかどうかは分からない。
    Status {
        /// どの発言か。
        id: u64,
        /// 届けたエージェントの名。
        届いた: Vec<String>,
        /// 読んだエージェントの名。**渡したことが確かなものだけ。**
        読んだ: Vec<String>,
    },
    /// **エージェントにつながった。**いつつながったかを返す（**`issues/4`** の 1 番）。
    ///
    /// **「届いていない」と「つながる前だった」を、エージェントから見分けられるようにする。**
    /// 画面を入れ替えるとこの機械のエージェントは全部外れる（`issues/2`）ので、
    /// **黙って繋ぎ直すと、切れている間の発言が無いことに気づけない。**
    Seated {
        /// つながった時刻（`HH:MM`）。**この時刻より前の発言は取れない。**
        at: String,
        /// 何と呼ばれているか（画面に出る呼び方）。
        who: String,
    },
    /// **プロフィールを書いた。**どのエージェントのものとして書いたかを返す。
    ///
    /// **「書いた」と言うなら、誰として書いたかまで言う** ——
    /// 名乗っていないエージェントはエージェントが決まらないので、そもそも書けない（`Denied` が返る）。
    Wrote {
        /// 誰として書いたか（画面に出る呼び方）
        who: String,
    },
}

/// 行が読めなかった理由。
#[derive(Debug, Clone, PartialEq, Eq)]
#[non_exhaustive]
pub enum Error {
    /// JSON として読めない・知らない鍵が付いている・知らない型。
    Malformed,
    /// 本文が空。
    Empty,
    /// 本文が [`本文の上限`] を超えた。
    TooLong(usize),
}

impl core::fmt::Display for Error {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        match self {
            Self::Malformed => f.write_str("行の形が壊れています"),
            Self::Empty => f.write_str("本文が空です"),
            Self::TooLong(n) => write!(f, "本文が長すぎます（{n} バイト / 上限 {本文の上限}）"),
        }
    }
}

impl core::error::Error for Error {}

/// **訳を検める**（**D119**）。
///
/// **行と欄を壊すものを通さない** —— 通すと、受け取った側の画面が崩れる
/// （`名乗りを検める` と同じ扱い）。
///
/// **空は弾かない。**空は「受け付けない」として**答えを返す**必要がある ——
/// 黙って落とすと、エージェントは
/// **「届いていない」と「形が悪い」を見分けられない**（D102 で踏んだのと同じ形）。
fn 訳を検める(訳: &str) -> Result<(), Error> {
    if 訳.len() > 訳の上限 {
        return Err(Error::TooLong(訳.len()));
    }
    if 訳.chars().any(|c| c.is_control() || c == '\t') {
        return Err(Error::Malformed);
    }
    Ok(())
}

impl ToDesk {
    /// 本文から [`ToDesk::Say`] を作る。**ここで長さと空を弾く。**
    pub fn say(body: impl Into<String>) -> Result<Self, Error> {
        let body = body.into();
        検める(&body)?;
        Ok(Self::Say { body })
    }

    /// 1 行の JSON を読む。
    ///
    /// **知らない鍵が付いていたら受けない。**受けると、そこが差出人を騙る入口になる。
    pub fn 読む(行: &str) -> Result<Self, Error> {
        let 中身: Self = serde_json::from_str(行.trim()).map_err(|_| Error::Malformed)?;
        match &中身 {
            Self::Say { body } => 検める(body)?,
            Self::Listen {
                場所: Some(名), ..
            } => 名乗りを検める(名)?,
            Self::Listen { 場所: None, .. } => {}
            // **上限は書き手の側でも見る。**長すぎるものをこの機械まで運ばない
            Self::Profile { 名前, 紹介 } => プロフィールを検める(名前, 紹介)?,
            // **訳は書き手の側でも検める**（**D119**）。
            // 行と欄を壊すものを、この機械まで運ばない。
            // **空かどうかは、ここで弾かない** —— あちらは
            // 「受け付けない」として**答えを返す**必要があるので（黙って落とすと、
            // エージェントは「届いていない」と「形が悪い」を見分けられない）
            Self::Ask { 訳, .. } => 訳を検める(訳)?,
            // **待つ口も、訳と秒を書き手の側で検める**（2026-09-24）
            Self::札を待つ { 訳, 秒, .. } => {
                訳を検める(訳)?;
                待つ秒を検める(*秒)?;
            }
            // **本数は書き手の側でも見る**（**#32 の段 2**）。
            // **無限に出させない** —— 鍵は持参人式で、出した分だけ入り口が増える
            Self::招く { 何本, .. } => 招く本数を検める(*何本)?,
            // 番号だけの行と、尋ねるだけの行。**中身が無いので検めるものが無い**
            Self::Read { .. } | Self::Status { .. } | Self::Status様子 => {}
        }
        Ok(中身)
    }

    /// 1 行の JSON にする。**改行は JSON が包むので、行は割れない。**
    pub fn 書く(&self) -> String {
        serde_json::to_string(self).expect("固定の形なので必ず通る")
    }
}

impl FromDesk {
    /// 1 行の JSON を読む。
    pub fn 読む(行: &str) -> Result<Self, Error> {
        serde_json::from_str(行.trim()).map_err(|_| Error::Malformed)
    }

    /// 1 行の JSON にする。
    pub fn 書く(&self) -> String {
        serde_json::to_string(self).expect("固定の形なので必ず通る")
    }
}

/// 名前の上限（文字）。**画面の 1 行に収まる長さ**（`warifu-vault` と揃える）。
pub const 名前の上限: usize = 32;
/// 紹介の上限（文字）。**プロフィールであって、文書ではない。**
pub const 紹介の上限: usize = 140;

/// プロフィールが**置ける形か**を見る。
///
/// **黙って切り詰めない。**削ると、書いた人（エージェント）は削られたことに気づかない。
fn プロフィールを検める(名前: &str, 紹介: &str) -> Result<(), Error> {
    if 名前.contains(['\n', '\r', '\t']) || 紹介.contains(['\n', '\r', '\t']) {
        return Err(Error::Malformed);
    }
    if 名前.chars().count() > 名前の上限 {
        return Err(Error::TooLong(名前.chars().count()));
    }
    if 紹介.chars().count() > 紹介の上限 {
        return Err(Error::TooLong(紹介.chars().count()));
    }
    Ok(())
}

/// 名乗りが**置ける形か**を見る。
///
/// **中身が本当かは見ない。**同じこの機械につなげるのは同じ人のプロセスだけなので、
/// ここは「画面が崩れないか」だけを見る。
fn 名乗りを検める(名: &str) -> Result<(), Error> {
    let 名 = 名.trim();
    if 名.is_empty() {
        return Err(Error::Empty);
    }
    // **区切りと見た目を壊すものを通さない**
    if 名.chars().any(|c| c.is_control() || c == '\t') {
        return Err(Error::Malformed);
    }
    if 名.chars().count() > 名乗りの上限 {
        return Err(Error::TooLong(名.len()));
    }
    Ok(())
}

/// **出せる本数か**（**#32 の段 2**）。
///
/// **0 本は頼みではない**（何も起きないのに口を使わせない）。
/// **上限を置くのは、無限に出させないため** —— 鍵は持参人式（**D31 の追記**）で、
/// **出した分だけ入り口が増える。**
fn 招く本数を検める(何本: u8) -> Result<(), Error> {
    if 何本 == 0 {
        return Err(Error::Empty);
    }
    if 何本 > 招ける本数 {
        return Err(Error::TooLong(何本 as usize));
    }
    Ok(())
}

fn 検める(body: &str) -> Result<(), Error> {
    if body.trim().is_empty() {
        return Err(Error::Empty);
    }
    let 長さ = body.len();
    if 長さ > 本文の上限 {
        return Err(Error::TooLong(長さ));
    }
    Ok(())
}

