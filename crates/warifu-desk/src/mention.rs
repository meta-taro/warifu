//! **`@名前` で呼ばれたか**（0.1.35・メンション）。
//!
//! 人数が多いと、誰に話しかけたのかが分からない。呼ばれた側（人の画面とエージェント）が
//! 同じ決め方で見分けられるよう、**規則をここに 1 か所だけ置く**（画面の `chat/mention.ts` も同じ規則）。

/// **全員を呼ぶ印**（0.1.45）。`@all`（大文字小文字を問わない）と `@全員`。
///
/// 全席へ向けた発言が、どの席にも「呼ばれた」と見えず、知らせで起きない席が出た。
/// 届く先は変わらない（もともとルームの全員へ届く）。**呼ばれたことにするだけ。**
pub const 全員の呼び: [&str; 2] = ["all", "全員"];

/// 本文に `@名前` があれば真。**`@all` / `@全員` は誰にも当たる。**
///
/// 名前のすぐ後ろが英数字なら別の名前とみなす（`@docs` は `@docs2` に当たらない）。
/// 1 文字の名前は見ない —— 当たりすぎる。
#[must_use]
pub fn 宛てられたか(本文: &str, 名前たち: &[String]) -> bool {
    // ASCII だけを小さくする（字の位置が動かない）。`@ALL` も `@all` として読む
    let 小さく = 本文.to_ascii_lowercase();
    全員の呼び.iter().any(|名| 呼んだか(&小さく, 名))
        || 名前たち
            .iter()
            .map(|n| n.trim())
            .filter(|n| n.chars().count() >= 2)
            .any(|名| 呼んだか(本文, 名))
}

/// その位置が `` ` `` で囲んだ所（コード）の中か。前にある `` ` `` の数が奇数なら中（0.1.46）。
///
/// 説明の中で `` `@all` `` と書いただけで全席が呼ばれ、呼ばれていない席が起きた。
/// コードの中の `@` は呼びとして数えない（```` ``` ```` の囲みも 3 つで奇数なので同じ読み）。
fn コードの中か(本文: &str, i: usize) -> bool {
    本文[..i].matches('`').count() % 2 == 1
}

/// 本文のどこかで `@名`（全角の `＠` も）と呼び、すぐ後ろが名前の続きでないか。
fn 呼んだか(本文: &str, 名: &str) -> bool {
    // **日本語入力では `@` が全角の `＠` で入る。**どちらも呼びとして読む
    ['@', '＠'].iter().any(|印| {
        let 印 = format!("{印}{名}");
        本文.match_indices(&印).any(|(i, _)| {
            !コードの中か(本文, i)
                && 本文[i + 印.len()..]
                    .chars()
                    .next()
                    .is_none_or(|c| !(c.is_ascii_alphanumeric() || c == '_'))
        })
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn 呼ばれた名前を見分ける() {
        let 名 = vec!["連動".to_owned(), "docs".to_owned()];
        assert!(宛てられたか("@連動 これ見て", &名));
        assert!(宛てられたか("確認お願い @docs", &名));
        assert!(宛てられたか("@連動（docs）へ", &名));
        // 名前の続きが英数字なら別の名前
        assert!(!宛てられたか("@docs2 へ", &名));
        // @ が無ければ呼んでいない
        assert!(!宛てられたか("連動 はどう？", &名));
        // 1 文字の名前は見ない
        assert!(!宛てられたか("@a", &["a".to_owned()]));
        // 日本語入力の全角 ＠ でも呼べる
        assert!(宛てられたか("＠連動 見て", &名));
        // 名前が無ければ誰も呼ばれていない
        assert!(!宛てられたか("@連動", &[]));
    }

    #[test]
    fn 全員を呼ぶ印は_誰にも当たる() {
        let 名 = vec!["連動".to_owned()];
        assert!(宛てられたか("@all 版を上げてください", &名));
        assert!(宛てられたか("【全席へ】@全員 確認を", &名));
        assert!(宛てられたか("＠全員 見て", &名));
        assert!(宛てられたか("@ALL 見て", &名));
        // 名前を持たない読み手でも、全員あては当たる
        assert!(宛てられたか("@all", &[]));
        // 続きが英数字なら別の名前
        assert!(!宛てられたか("@allow を付ける", &名));
        // @ が無ければ呼んでいない
        assert!(!宛てられたか("all の人へ", &名));
    }

    #[test]
    fn コードで囲んだ所の呼びは数えない() {
        let 名 = vec!["連動".to_owned()];
        // 説明の中で触れただけ
        assert!(!宛てられたか(
            "PdM の `@all`（#675）では起きました",
            &名
        ));
        assert!(!宛てられたか("`@連動` で呼ぶと当たります", &名));
        assert!(!宛てられたか("```\n@all\n```", &名));
        // 囲みの外なら呼んでいる
        assert!(宛てられたか("@連動 `@all` の件です", &名));
        assert!(宛てられたか("`コード` のあとで @all", &名));
    }
}
