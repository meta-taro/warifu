//! **`@名前` で呼ばれたか**（0.1.35・メンション）。
//!
//! 人数が多いと、誰に話しかけたのかが分からない。呼ばれた側（人の画面とエージェント）が
//! 同じ決め方で見分けられるよう、**規則をここに 1 か所だけ置く**（画面の `chat/mention.ts` も同じ規則）。

/// **全員を呼ぶ印**（0.1.45）。`@all`（大文字小文字を問わない）と `@全員`。
///
/// 全席へ向けた発言が、どの席にも「呼ばれた」と見えず、知らせで起きない席が出た。
/// 届く先は変わらない（もともとルームの全員へ届く）。**呼ばれたことにするだけ。**
pub const 全員の呼び: [&str; 2] = ["all", "全員"];

/// **呼ばれうる名前を広げる**（11-12）。画面の `chat/mention.ts` の `呼べる名に広げる` と同じ規則。
///
/// - 末尾が `（…）` の名前は、括弧の前だけでも呼べる（`見積くん（PC-A）` → `見積くん`）
/// - `◯◯ のエージェント` は `◯◯` でも呼べる
/// - 英数字の語で始まる名前は、その語（多くはフォルダ名）でも呼べる（`docs-site 担当AI` → `docs-site`）
///
/// 席の名前が括弧つきで、`@見積くん` と打っても誰も起きなかった。画面は括弧の前でも見分けて
/// いたので、人には呼べているように見えた。**呼ぶ側と呼ばれる側で、名前の広げ方を揃える。**
#[must_use]
pub fn 呼べる名に広げる(名前たち: &[String]) -> Vec<String> {
    let mut 広げた: Vec<String> = Vec::new();
    let mut 足す = |n: &str| {
        let n = n.trim();
        if !n.is_empty() && !広げた.iter().any(|m| m == n) {
            広げた.push(n.to_owned());
        }
    };
    for 名 in 名前たち {
        let 名 = 名.trim();
        足す(名);
        let 頭 = 括弧の前(名);
        if let Some(頭) = 頭 {
            足す(頭);
        }
        if let Some(札) = 頭.unwrap_or(名).strip_suffix(" のエージェント") {
            足す(札);
        }
        if let Some(語) = 頭の英数字の語(名) {
            足す(語);
        }
        // **括弧の中（機械の名前・フォルダ名）でも呼べる**（11-12・機械ごとのメンション）。
        // `dbboard（mac mini）` は `@mac mini` でも起きる。同じ機械の席が全部起きる
        for 中 in 括弧の中たち(名) {
            足す(中);
        }
    }
    広げた
}

/// 名前の中の `（…）` の中身を、出てきた順に。
fn 括弧の中たち(名: &str) -> Vec<&str> {
    let mut 中たち = Vec::new();
    let mut 残り = 名;
    while let Some(開き) = 残り.find('（') {
        let 後 = &残り[開き + '（'.len_utf8()..];
        let Some(閉じ) = 後.find('）') else { break };
        let 中 = &後[..閉じ];
        if !中.contains('（') && !中.trim().is_empty() {
            中たち.push(中.trim());
        }
        残り = &後[閉じ + '）'.len_utf8()..];
    }
    中たち
}

/// 末尾が `（…）`（中に括弧を含まない）なら、その前。
fn 括弧の前(名: &str) -> Option<&str> {
    let 中 = 名.strip_suffix('）')?;
    let 開き = 中.rfind('（')?;
    let 頭 = &名[..開き];
    (!頭.is_empty() && !中[開き + '（'.len_utf8()..].contains(['（', '）'])).then_some(頭)
}

/// 英数字（と `._-`）の 2 字以上の語で始まり、空白が続くなら、その語。
fn 頭の英数字の語(名: &str) -> Option<&str> {
    let (語, 残り) = 名.split_once(' ')?;
    let 字 = |c: char| c.is_ascii_alphanumeric() || matches!(c, '.' | '_' | '-');
    let ok = 語.chars().count() >= 2
        && 語.chars().next().is_some_and(|c| c.is_ascii_alphanumeric())
        && 語.chars().all(字)
        && !残り.trim().is_empty();
    ok.then_some(語)
}

/// 本文に `@名前` があれば真。**`@all` / `@全員` は誰にも当たる。**
///
/// 名前のすぐ後ろが英数字なら別の名前とみなす（`@docs` は `@docs2` に当たらない）。
/// 1 文字の名前は見ない —— 当たりすぎる。**`cc@名前` は写しなので、宛て先に数えない**（0.1.47）。
#[must_use]
pub fn 宛てられたか(本文: &str, 名前たち: &[String]) -> bool {
    呼ばれ方(本文, 名前たち).is_some_and(|写し| !写し)
}

/// **`cc@名前` で写しとして呼ばれたか**（0.1.47）。宛て先（`@名前`）にも書かれていれば偽（宛て先が勝つ）。
///
/// メールの CC と同じ扱い：知らせはするが、起こさない・返事は要らない。
#[must_use]
pub fn 写しか(本文: &str, 名前たち: &[String]) -> bool {
    呼ばれ方(本文, 名前たち).is_some_and(|写し| 写し)
}

/// 呼ばれていなければ `None`。宛て先として 1 か所でも呼ばれていれば `Some(false)`、写しだけなら `Some(true)`。
fn 呼ばれ方(本文: &str, 名前たち: &[String]) -> Option<bool> {
    // ASCII だけを小さくする（字の位置が動かない）。`@ALL` も `@all` として読む
    let 小さく = 本文.to_ascii_lowercase();
    let 名たち = 名前たち
        .iter()
        .map(|n| n.trim())
        .filter(|n| n.chars().count() >= 2);
    let 位置たち: Vec<(usize, bool)> = 全員の呼び
        .iter()
        .flat_map(|名| 呼んだ位置(&小さく, 名))
        // **英字の大文字・小文字は問わない**（11-12）。`@Mac mini` も `@mac mini` として読む。
        // ASCII だけを小さくするので、字の位置は動かない
        .chain(名たち.flat_map(|名| 呼んだ位置(&小さく, &名.to_ascii_lowercase())))
        .collect();
    if 位置たち.is_empty() {
        return None;
    }
    Some(位置たち.iter().all(|&(_, 写し)| 写し))
}

/// その位置が `` ` `` で囲んだ所（コード）の中か。前にある `` ` `` の数が奇数なら中（0.1.46）。
///
/// 説明の中で `` `@all` `` と書いただけで全席が呼ばれ、呼ばれていない席が起きた。
/// コードの中の `@` は呼びとして数えない（```` ``` ```` の囲みも 3 つで奇数なので同じ読み）。
fn コードの中か(本文: &str, i: usize) -> bool {
    本文[..i].matches('`').count() % 2 == 1
}

/// `@` の直前が `cc`（大文字小文字を問わない）で、その前が英数字でないか（0.1.47）。
fn 写しの印か(本文: &str, i: usize) -> bool {
    let 前 = &本文.as_bytes()[..i];
    let n = 前.len();
    n >= 2
        && 前[n - 2..].eq_ignore_ascii_case(b"cc")
        && (n == 2 || !前[n - 3].is_ascii_alphanumeric())
}

/// 本文のどこで `@名`（全角の `＠` も）と呼んだか。すぐ後ろが名前の続きなら数えない。
/// 返りは（位置, 写しか）。
fn 呼んだ位置(本文: &str, 名: &str) -> Vec<(usize, bool)> {
    // **日本語入力では `@` が全角の `＠` で入る。**どちらも呼びとして読む
    ['@', '＠']
        .iter()
        .flat_map(|印| {
            let 印 = format!("{印}{名}");
            本文
                .match_indices(&印)
                .filter(|&(i, _)| {
                    !コードの中か(本文, i)
                        && 本文[i + 印.len()..]
                            .chars()
                            .next()
                            .is_none_or(|c| !(c.is_ascii_alphanumeric() || c == '_'))
                })
                .map(|(i, _)| (i, 写しの印か(本文, i)))
                .collect::<Vec<_>>()
        })
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn 括弧つきの名前は_括弧の前だけでも呼べる() {
        // 11-12、席の名前が「見積くん（PC-A）」で、`@見積くん` と打っても誰も起きなかった。
        // 画面は括弧の前でも見分けていたので、見た目では呼べているのに、席の口は見分けなかった
        let 名 = 呼べる名に広げる(&["見積くん（PC-A）".to_owned()]);
        assert!(宛てられたか("@見積くん 版を教えて", &名));
        assert!(宛てられたか("@見積くん（PC-A） 版を教えて", &名));
        assert!(
            !宛てられたか("@連動 版を教えて", &名),
            "短い名には当たらない"
        );
    }

    #[test]
    fn 機械の名前で呼ぶと_その機械の席が全部起きる() {
        // 11-12、機械ごとのメンションを足した。
        // 席の名前の括弧の中（機械の名前）でも呼べる。英字の大文字・小文字は問わない
        let 席a = 呼べる名に広げる(&["dbboard（mac mini）".to_owned()]);
        let 席b = 呼べる名に広げる(&["割符（mac mini）（warifu）".to_owned()]);
        let ほか = 呼べる名に広げる(&["sshboard（mac air）".to_owned()]);
        for 本文 in ["@mac mini 網を見て", "@Mac mini 網を見て"] {
            assert!(宛てられたか(本文, &席a), "{本文}");
            assert!(宛てられたか(本文, &席b), "{本文}");
            assert!(!宛てられたか(本文, &ほか), "{本文}");
        }
        assert!(
            宛てられたか("@warifu 版は", &席b),
            "後ろの括弧の中でも呼べる"
        );
    }

    #[test]
    fn 名乗りの形は_画面と同じに広げる() {
        let 名 = 呼べる名に広げる(&[
            "docs のエージェント".to_owned(),
            "docs-site 担当AI".to_owned(),
            "PdM（ドスパラ）".to_owned(),
        ]);
        for 呼び in [
            "docs のエージェント",
            "docs",
            "docs-site 担当AI",
            "docs-site",
            "PdM（ドスパラ）",
            "PdM",
        ] {
            assert!(名.iter().any(|n| n == 呼び), "{呼び} が無い: {名:?}");
        }
        assert_eq!(
            名.len(),
            名.iter().collect::<std::collections::BTreeSet<_>>().len(),
            "重ねない"
        );
    }

    #[test]
    fn 呼ばれた名前を見分ける() {
        let 名 = vec!["連動".to_owned(), "docs".to_owned()];
        assert!(宛てられたか("@連動 これ見て", &名));
        assert!(宛てられたか("確認お願い @docs", &名));
        assert!(宛てられたか("@連動（docs）へ", &名));
        // 名前の続きが英数字なら別の名前
        assert!(!宛てられたか("@docs2 へ", &名));
        // @ が無ければ呼んでいない
        assert!(!宛てられたか("連動 はどう？", &名));
        // 1 文字の名前は見ない
        assert!(!宛てられたか("@a", &["a".to_owned()]));
        // 日本語入力の全角 ＠ でも呼べる
        assert!(宛てられたか("＠連動 見て", &名));
        // 名前が無ければ誰も呼ばれていない
        assert!(!宛てられたか("@連動", &[]));
    }

    #[test]
    fn 全員を呼ぶ印は_誰にも当たる() {
        let 名 = vec!["連動".to_owned()];
        assert!(宛てられたか("@all 版を上げてください", &名));
        assert!(宛てられたか("【全席へ】@全員 確認を", &名));
        assert!(宛てられたか("＠全員 見て", &名));
        assert!(宛てられたか("@ALL 見て", &名));
        // 名前を持たない読み手でも、全員あては当たる
        assert!(宛てられたか("@all", &[]));
        // 続きが英数字なら別の名前
        assert!(!宛てられたか("@allow を付ける", &名));
        // @ が無ければ呼んでいない
        assert!(!宛てられたか("all の人へ", &名));
    }

    #[test]
    fn コードで囲んだ所の呼びは数えない() {
        let 名 = vec!["連動".to_owned()];
        // 説明の中で触れただけ
        assert!(!宛てられたか(
            "PdM の `@all`（#675）では起きました",
            &名
        ));
        assert!(!宛てられたか("`@連動` で呼ぶと当たります", &名));
        assert!(!宛てられたか("```\n@all\n```", &名));
        // 囲みの外なら呼んでいる
        assert!(宛てられたか("@連動 `@all` の件です", &名));
        assert!(宛てられたか("`コード` のあとで @all", &名));
    }

    #[test]
    fn cc_で呼んだ相手は宛て先でなく写し() {
        let 名 = vec!["PdM".to_owned()];
        // cc@ は写し。宛て先（起こす・返事が要る）にはしない
        assert!(!宛てられたか("@連動 直して cc@PdM", &名));
        assert!(写しか("@連動 直して cc@PdM", &名));
        // 大文字・全角の ＠ も写し
        assert!(写しか("CC@PdM 念のため", &名));
        assert!(写しか("Cc＠PdM 念のため", &名));
        // 宛て先と写しの両方に書かれたら、宛て先が勝つ
        assert!(宛てられたか("@PdM 見て cc@PdM", &名));
        assert!(!写しか("@PdM 見て cc@PdM", &名));
        // cc の前が英数字なら cc の印ではない（acc@PdM は宛て先として読む）
        assert!(宛てられたか("acc@PdM", &名));
        assert!(!写しか("acc@PdM", &名));
        // 呼ばれていなければ写しでもない
        assert!(!写しか("@連動 直して", &名));
        // コードの中の cc@ は数えない
        assert!(!写しか("`cc@PdM` と書きます", &名));
    }

    #[test]
    fn cc_で全員を呼ぶと_全員が写し() {
        let 名 = vec!["連動".to_owned()];
        assert!(!宛てられたか("版を上げました cc@all", &名));
        assert!(写しか("版を上げました cc@all", &名));
        assert!(写しか("cc@全員", &[]));
    }
}
