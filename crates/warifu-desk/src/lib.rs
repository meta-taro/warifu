//! この機械。**同じ PC の人の画面とエージェントが、1 つの会話を囲む口。**
//!
//! ```text
//!   人（GUI）──┐
//!              ├── 同じ会話 ──── iroh P2P ──── 相手の PC
//!   AI（MCP）──┘
//!        ↑ ここがこの機械。**同じ機械の中だけ。**
//! ```
//!
//! **なぜ要るか。**エージェントに `warifu join` を bash で叩かせる形は、
//! 実際に許可プロンプトで止まった（2026-09-06・Mac Air の報告で 3 回とも）。
//! MCP の道具なら止まらない。そして会話の親を GUI に置けば、
//! **エージェントが喋った瞬間に人の画面へ出る。**
//! 「エージェント同士のチャット」と「人が見て入る」が別の作業にならない。
//!
//! # ここで守ること
//!
//! - **エージェントは差出人を名乗れない。**[`ToDesk::Say`] に差出人の場所が無い。
//!   誰が言ったかはこの機械が刻む。名乗れる形にすると、届いた文字が
//!   「人の発言」を騙れる（PRD §12-2 の、モデルの言い分を信じない、と同じ話）
//! - **知らない鍵の付いた行は受けない。**`deny_unknown_fields`。
//!   後から場所を増やす余地を残すと、そこが名乗りの入口になる
//! - **本文に上限を置く。**相手（＝手元の AI）に一度の量を決めさせない
//!
//! 口をどこに開けるか（Unix ドメインソケットの権限など）は**この層に無い**。
//! ここは行の形だけを決める。

