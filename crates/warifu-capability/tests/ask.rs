//! **エージェントが札を頼み、人が一言で出す**（**D119** / **#26** / **#12**）。
//!
//! オーナー（2026-09-17）——「**許可をください。OK って言えば始まる。**」
//!
//! ここで固定するのは 4 つ。
//!
//! 1. **もう答えが出ているものは、人に聞き直さない**（断りも含む）
//! 2. **訳の無い頼みは、人に見せる前に落とす**（**「OK」が同意にならない**）
//! 3. **動作の名が読めないものは受け付けない**
//! 4. **「断り」と「受け付けない」を混ぜない**

use std::collections::HashMap;

use warifu_capability::{
    Action, 受け付けない訳, 札の控え, 札の答え, 訳の上限, 訳を検める, 頼みの行き先,
    頼みをどうするか,
};

/// 試験用の控え。**置き場所は関係ない**（引ける形だけ求めている）。
#[derive(Default)]
struct 覚え(HashMap<String, 札の答え>);

impl 覚え {
    fn 入れる(mut self, 動作: &str, 答え: 札の答え) -> Self {
        self.0.insert(動作.to_owned(), 答え);
        self
    }
}

impl 札の控え for 覚え {
    fn 答え(&self, 動作: &Action) -> Option<札の答え> {
        self.0.get(動作.as_str()).copied()
    }
}

#[test]
fn 初めての頼みは_人に聞く() {
    let 出た = 頼みをどうするか(&覚え::default(), "chat.send", "部屋へ 1 行流したい");
    assert_eq!(出た, 頼みの行き先::人に聞く);
}

#[test]
fn もう許してあるなら_聞き直さない() {
    // **一度頼んでおけば、以後は聞かれない。**
    // オーナー ——「**人がエージェントに頼んでおくだけで動くのが理想**」
    let 控え = 覚え::default().入れる("chat.send", 札の答え::許した);
    assert_eq!(
        頼みをどうするか(&控え, "chat.send", "部屋へ 1 行流したい"),
        頼みの行き先::答えが出ている(札の答え::許した)
    );
}

#[test]
fn 一度断られたら_聞き直さない() {
    // **ここが D119 の芯。**聞き直すと、**エージェントが同じ札を何度も頼む。**
    // 「いつも出ている警告は読まれなくなる」（#33 / #35 で踏んだ形）——
    // **読まれなくなった許可の口は、無いのと同じ。**
    let 控え = 覚え::default().入れる("chat.send", 札の答え::断った);
    assert_eq!(
        頼みをどうするか(&控え, "chat.send", "どうしても要る"),
        頼みの行き先::答えが出ている(札の答え::断った)
    );
}

#[test]
fn 訳が無ければ_人に見せない() {
    // **何を許すかが一言で読めなければ、「OK」は同意ではない。**
    for 訳 in ["", " ", "\u{3000}", "\n"] {
        assert_eq!(
            頼みをどうするか(&覚え::default(), "chat.send", 訳),
            頼みの行き先::受け付けない(受け付けない訳::訳が無い),
            "訳 {訳:?} で人に見せた"
        );
    }
}

#[test]
fn 訳が長すぎれば_受け付けない() {
    // **読めない長さの訳は、「OK」を押させるための飾りになる**
    let 長い = "あ".repeat(訳の上限);
    assert!(長い.len() > 訳の上限, "上限はバイト数で見る");
    assert_eq!(
        頼みをどうするか(&覚え::default(), "chat.send", &長い),
        頼みの行き先::受け付けない(受け付けない訳::訳が長い)
    );
}

#[test]
fn 動作の名が読めなければ_受け付けない() {
    // **綴り違いを通すと、「許したのに動かない」を人が延々と探すことになる**（D56）
    for 動作 in [
        "",
        "Chat.Send",
        "chat send",
        "..",
        ".chat",
        "chat.",
        "chat/send",
    ] {
        assert_eq!(
            頼みをどうするか(&覚え::default(), 動作, "要るから"),
            頼みの行き先::受け付けない(受け付けない訳::動作が読めない),
            "動作 {動作:?} を受け付けた"
        );
    }
}

#[test]
fn もう答えが出ているなら_訳を求めない() {
    // **すでに許してあるものに訳を求めると、
    // 「一度頼んでおけば動く」が崩れる**（毎回訳を書かせることになる）
    let 控え = 覚え::default().入れる("chat.read", 札の答え::許した);
    assert_eq!(
        頼みをどうするか(&控え, "chat.read", ""),
        頼みの行き先::答えが出ている(札の答え::許した)
    );
}

#[test]
fn 断りと_受け付けないを混ぜない() {
    // **別の話である。**
    //   断り        —— **人が見て、断った**
    //   受け付けない —— **人に見せてもいない**（形が悪い）
    // 混ぜると、エージェントは「人が断った」と誤解して諦める
    let 断られた = 頼みをどうするか(
        &覚え::default().入れる("chat.send", 札の答え::断った),
        "chat.send",
        "訳あり",
    );
    let 形が悪い = 頼みをどうするか(&覚え::default(), "chat.send", "");

    assert!(matches!(
        断られた,
        頼みの行き先::答えが出ている(札の答え::断った)
    ));
    assert!(matches!(形が悪い, 頼みの行き先::受け付けない(_)));
    assert_ne!(断られた, 形が悪い);
}

#[test]
fn 訳に行や欄を壊すものを通さない() {
    // **通すと、受け取った側の画面が崩れる**（`Notice::Text` の札と同じ扱い）
    assert!(訳を検める("部屋へ 1 行流したい").is_ok());
    for 悪い in ["改\n行", "欄\tを壊す", "制御\u{0007}文字"] {
        assert!(訳を検める(悪い).is_err(), "{悪い:?} を通した");
    }
}
