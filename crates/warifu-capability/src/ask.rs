//! **エージェントが札を頼み、人が一言で出す**（**D119** / **#26** / **#12**）。
//!
//! # なぜ要るか
//!
//! **D56 は「札を出すのは人である」と決めた。それは正しい。**
//! **ずれていたのは「どうやって人に頼むか」である。**
//!
//! ```text
//! いまの形   人が ~/.claude.json を開いて --allow を書く
//!            → **画面とキーボードが前提**
//! ```
//!
//! オーナー（2026-09-17）——
//!
//! > **未来は Google グラスみたいに、もうソフトとエージェントは目と耳のなかにいるみたいな。**
//! > **許可をください。OK って言えば始まる。**
//!
//! **目と耳の中に居るなら、JSON は開けない。**
//! **「人が行う」は保つ。「人が JSON を書く」をやめる。**
//!
//! # ここが決めるのは「人に聞くかどうか」だけ
//!
//! **札を出すのはここではない。**この層は
//! **「もう答えが出ているか／人に聞くべきか／そもそも受け付けないか」**を返すだけである。
//! **出すのは人が画面で押したときだけ。**

use crate::{Action, Error};

/// 訳（なぜ要るか）の上限。
///
/// **人が一言で読める長さに収める。**読めない長さの訳は、
/// **「OK」を押させるための飾り**になる。
pub const 訳の上限: usize = 140;

/// 頼みに対する答え。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 札の答え {
    /// まだ人が答えていない。
    まだ,
    /// 人が許した。
    許した,
    /// 人が断った。
    断った,
}

/// 頼みを受けたときに、何をするか。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 頼みの行き先 {
    /// **もう答えが出ている。**人に聞き直さない。
    答えが出ている(札の答え),
    /// **人に聞く。**画面に出して、押してもらう。
    人に聞く,
    /// **受け付けない。**画面にも出さない。
    受け付けない(受け付けない訳),
}

/// 受け付けない理由。
///
/// **「どうすれば通るか」は書かない**（`Decision::Deny` と同じ構え）——
/// 書くと、断られた側が総当たりで札の形を探れる。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 受け付けない訳 {
    /// 動作の名が読めない。
    動作が読めない,
    /// **訳が無い。**
    ///
    /// **何を許すかが一言で読めなければ、「OK」は同意ではない。**
    /// だから**訳の無い頼みは、人に見せる前に落とす。**
    訳が無い,
    /// 訳が長すぎる（[`訳の上限`]）。
    訳が長い,
}

/// **すでに人が答えたことの控え。**
///
/// **持ち方はここで決めない**（置き場所は外の層・baseline §9）。
/// ここは**引ける形**だけを求める。
pub trait 札の控え {
    /// その動作について、人がもう答えているか。
    fn 答え(&self, 動作: &Action) -> Option<札の答え>;
}

/// **頼みをどうするか。**
///
/// # 一度断られたら、聞き直さない
///
/// **これが無いと、エージェントが同じ札を何度も頼む。**
/// **「いつも出ている警告は読まれなくなる」**（#33 の黒い枠・#35 で踏んだ形）——
/// **読まれなくなった許可の口は、無いのと同じである。**
///
/// **人が取り消したいときは、人が控えから落とす**（**D58** の「持ち越すなら取り消す口も要る」）。
///
/// # Errors
/// 返さない。**受け付けないものは [`頼みの行き先::受け付けない`] で返す** ——
/// 呼ぶ側が「断り」と「受け付けない」を混ぜないようにするため。
pub fn 頼みをどうするか(
    控え: &impl 札の控え, 動作: &str, 訳: &str
) -> 頼みの行き先 {
    let Ok(動作) = Action::new(動作) else {
        return 頼みの行き先::受け付けない(受け付けない訳::動作が読めない);
    };
    // **すでに答えが出ているかを先に見る。**
    // **訳の検めより先**である —— もう許してあるものに、訳を求める意味が無い
    if let Some(答え) = 控え.答え(&動作) {
        return 頼みの行き先::答えが出ている(答え);
    }
    if 訳.trim().is_empty() {
        return 頼みの行き先::受け付けない(受け付けない訳::訳が無い);
    }
    if 訳.len() > 訳の上限 {
        return 頼みの行き先::受け付けない(受け付けない訳::訳が長い);
    }
    頼みの行き先::人に聞く
}

/// 訳を、人に見せられる形に整える。
///
/// **行と欄を壊すものを通さない** —— 通すと、受け取った側の画面が崩れる
/// （`Notice::Text` の札と同じ扱い）。
///
/// # Errors
/// 制御文字・タブ・改行が入っていれば [`Error::Malformed`]。
pub fn 訳を検める(訳: &str) -> Result<&str, Error> {
    if 訳.chars().any(|c| c.is_control() || c == '\t') {
        return Err(Error::Malformed);
    }
    Ok(訳)
}
