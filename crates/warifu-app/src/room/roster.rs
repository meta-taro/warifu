//! 名簿の規則（0.1.39 に画面側 `roster_sync.rs` で始めたもの。0.1.40 でここへ移した）。
//!
//! ルームは星形で、ゲストどうしは主催を介して話す。ゲストの名簿は直接つながった相手しか増えず、
//! 網を越えて直接つながれない相手は、**発言は主催ごしに届くのに名簿に居なかった**。
//! 主催は名簿が動いたら配り、ゲストは**主催から来た名簿だけ**を信じて差を足し引きする。

/// 主催の名簿と自分の名簿の差。**（足す, 外す）**を返す。
///
/// - 足す …… 主催の名簿に居て、自分の名簿に居ない相手（自分は除く）
/// - 外す …… 自分の名簿に居て、主催の名簿に居ない相手（自分と主催は除く。先頭は外せない）
#[must_use]
pub fn 名簿の差<T: PartialEq + Copy>(
    自分の名簿: &[T],
    主催の名簿: &[T],
    自分: &T,
    主催: &T,
) -> (Vec<T>, Vec<T>) {
    let 足す = 主催の名簿
        .iter()
        .copied()
        .filter(|k| k != 自分 && !自分の名簿.contains(k))
        .collect();
    let 外す = 自分の名簿
        .iter()
        .copied()
        .filter(|k| k != 自分 && k != 主催 && !主催の名簿.contains(k))
        .collect();
    (足す, 外す)
}

/// **線の相手と差出人が違う発言を通すか。**
///
/// 主催は聞いた発言をほかの客へそのまま配る（差出人は書き換えない・D48）。
/// 通すのは**線の相手がその部屋の主催のときだけ**。自分を名乗る発言は通さない。
#[must_use]
pub fn 配られた発言を通すか<T: PartialEq>(
    差出人: &T,
    線の相手: &T,
    自分: &T,
    主催: Option<&T>,
) -> bool {
    if 差出人 == 線の相手 {
        return true;
    }
    差出人 != 自分 && 主催 == Some(線の相手)
}

/// **その部屋の主催は自分か。**覚えていない部屋は自分が建てたもの。
///
/// `members().first() == me` では決められない。ゲストも自分を先頭に名簿を組むので、
/// その判定は**ゲストでも常に真**になり、主催が配った名簿を全部捨てていた（0.1.39 → 0.1.40）。
#[must_use]
pub fn 主催か<T: PartialEq>(覚えた主催: Option<&T>, 自分: &T) -> bool {
    覚えた主催.is_none_or(|h| h == 自分)
}

/// 主催が、名簿をゲストへ配り直すか。**名簿が動いたときだけ**（入った・抜けた）。
#[must_use]
pub fn 名簿を配るか(主催か: bool, events: &[crate::Event]) -> bool {
    主催か
        && events
            .iter()
            .any(|e| matches!(e, crate::Event::Joined(_) | crate::Event::Left(_)))
}

/// **入った（入り直した）本人へ、主催がいまの名簿を渡すか**（0.1.60）。
///
/// 会議キーや部屋の証しで入ったゲストは、名簿を「自分と主催」だけで組む。主催は名簿が動いたとき
/// **ほかの客へは**配っていたが、入った本人へは「入るときに渡している」として配らなかった。
/// 実際には鍵なしで招いた相手にしか渡しておらず、鍵で入ったゲストは次に誰かが出入りするまで
/// 主催ごしに届く発言の差出人を知らず、「名簿に居ない相手から」の食い違いを出していた。
///
/// 渡すのは**主催が、入った知らせを受けたとき**で、名簿に主催と本人のほかに誰か居るときだけ
/// （2 人なら本人の名簿と同じなので、送っても何も変わらない）。
#[must_use]
pub fn 入った本人へ名簿を渡すか(
    主催か: bool,
    入った知らせか: bool,
    名簿の人数: usize,
) -> bool {
    主催か && 入った知らせか && 名簿の人数 > 2
}

/// 入った直後に、主催の名簿を待つ長さ（秒）。
pub const 名簿を待つ秒: u64 = 30;

/// **名簿に居ない相手の発言を、いま食い違いとして言うか**（0.1.60）。
///
/// 主催は聞いた発言を線のある全員へ配るので、入った直後のゲストには、主催の名簿より先に
/// ほかの客の発言が届くことがある。そのあいだは食い違いではなく、名簿の届く順の問題。
///
/// - `入ってからの秒` …… ゲストとしてその部屋に入ってからの秒。覚えていなければ `None`（主催の部屋など）
/// - `名簿が届いた` …… 入ってから、主催の名簿を一度でも受けたか
///
/// 待つのは、**ゲストで、まだ名簿が届いておらず、入ってから [`名簿を待つ秒`] 未満**のときだけ。
/// 待った分は捨てずに控え、名簿が届いたとき（か待ちが明けたとき）に照らし直す。
#[must_use]
pub fn 食い違いをいま言うか(
    入ってからの秒: Option<u64>, 名簿が届いた: bool
) -> bool {
    match 入ってからの秒 {
        Some(秒) => 名簿が届いた || 秒 >= 名簿を待つ秒,
        None => true,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    const 主催: u8 = 1;
    const 自分: u8 = 2;
    const 直接: u8 = 3;
    const 遠い: u8 = 4;

    #[test]
    fn 主催の名簿に居て_自分の名簿に居ない相手を足す() {
        let (足す, 外す) =
            名簿の差(&[自分, 主催, 直接], &[主催, 自分, 直接, 遠い], &自分, &主催);
        assert_eq!(足す, vec![遠い]);
        assert!(外す.is_empty());
    }

    #[test]
    fn 主催の名簿から消えた相手を外す_自分と主催は外さない() {
        let (足す, 外す) = 名簿の差(&[自分, 主催, 直接, 遠い], &[主催, 自分], &自分, &主催);
        assert!(足す.is_empty());
        assert_eq!(外す, vec![直接, 遠い]);
    }

    #[test]
    fn 主催ごしの発言は通し_それ以外の名乗りは通さない() {
        assert!(配られた発言を通すか(
            &直接,
            &直接,
            &自分,
            Some(&主催)
        ));
        assert!(配られた発言を通すか(
            &遠い,
            &主催,
            &自分,
            Some(&主催)
        ));
        assert!(!配られた発言を通すか(
            &遠い,
            &直接,
            &自分,
            Some(&主催)
        ));
        assert!(!配られた発言を通すか(&遠い, &主催, &自分, None));
        assert!(!配られた発言を通すか(
            &自分,
            &主催,
            &自分,
            Some(&主催)
        ));
    }

    #[test]
    fn 主催かは_覚えた主催で決める_名簿の先頭では決めない() {
        assert!(主催か(None, &自分));
        assert!(主催か(Some(&自分), &自分));
        assert!(!主催か(Some(&主催), &自分));
    }

    #[test]
    fn 主催は_入った本人にも_3_人目からは名簿を渡す() {
        assert!(入った本人へ名簿を渡すか(true, true, 3));
        assert!(
            !入った本人へ名簿を渡すか(true, true, 2),
            "主催と本人だけなら同じ名簿"
        );
        assert!(
            !入った本人へ名簿を渡すか(false, true, 5),
            "ゲストは渡さない"
        );
        assert!(
            !入った本人へ名簿を渡すか(true, false, 5),
            "入った知らせのときだけ"
        );
    }

    #[test]
    fn 入った直後で名簿がまだなら_食い違いを待つ() {
        assert!(!食い違いをいま言うか(Some(0), false));
        assert!(!食い違いをいま言うか(
            Some(名簿を待つ秒 - 1),
            false
        ));
        assert!(
            食い違いをいま言うか(Some(名簿を待つ秒), false),
            "待ちが明けたら言う"
        );
        assert!(
            食い違いをいま言うか(Some(1), true),
            "名簿が届いたあとは、すぐ言う"
        );
        assert!(
            食い違いをいま言うか(None, false),
            "入った覚えのない部屋は、すぐ言う"
        );
    }
}
