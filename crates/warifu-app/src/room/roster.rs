//! 名簿の規則（0.1.39 に画面側 `roster_sync.rs` で始めたもの。0.1.40 でここへ移した）。
//!
//! ルームは星形で、ゲストどうしは主催を介して話す。ゲストの名簿は直接つながった相手しか増えず、
//! 網を越えて直接つながれない相手は、**発言は主催ごしに届くのに名簿に居なかった**。
//! 主催は名簿が動いたら配り、ゲストは**主催から来た名簿だけ**を信じて差を足し引きする。

/// 主催の名簿と自分の名簿の差。**（足す, 外す）**を返す。
///
/// - 足す …… 主催の名簿に居て、自分の名簿に居ない相手（自分は除く）
/// - 外す …… 自分の名簿に居て、主催の名簿に居ない相手（自分と主催は除く。先頭は外せない）
#[must_use]
pub fn 名簿の差<T: PartialEq + Copy>(
    自分の名簿: &[T],
    主催の名簿: &[T],
    自分: &T,
    主催: &T,
) -> (Vec<T>, Vec<T>) {
    let 足す = 主催の名簿
        .iter()
        .copied()
        .filter(|k| k != 自分 && !自分の名簿.contains(k))
        .collect();
    let 外す = 自分の名簿
        .iter()
        .copied()
        .filter(|k| k != 自分 && k != 主催 && !主催の名簿.contains(k))
        .collect();
    (足す, 外す)
}

/// **線の相手と差出人が違う発言を通すか。**
///
/// 主催は聞いた発言をほかの客へそのまま配る（差出人は書き換えない・D48）。
/// 通すのは**線の相手がその部屋の主催のときだけ**。自分を名乗る発言は通さない。
#[must_use]
pub fn 配られた発言を通すか<T: PartialEq>(
    差出人: &T,
    線の相手: &T,
    自分: &T,
    主催: Option<&T>,
) -> bool {
    if 差出人 == 線の相手 {
        return true;
    }
    差出人 != 自分 && 主催 == Some(線の相手)
}

/// **その部屋の主催は自分か。**覚えていない部屋は自分が建てたもの。
///
/// `members().first() == me` では決められない。ゲストも自分を先頭に名簿を組むので、
/// その判定は**ゲストでも常に真**になり、主催が配った名簿を全部捨てていた（0.1.39 → 0.1.40）。
#[must_use]
pub fn 主催か<T: PartialEq>(覚えた主催: Option<&T>, 自分: &T) -> bool {
    覚えた主催.is_none_or(|h| h == 自分)
}

/// 主催が、名簿をゲストへ配り直すか。**名簿が動いたときだけ**（入った・抜けた）。
#[must_use]
pub fn 名簿を配るか(主催か: bool, events: &[crate::Event]) -> bool {
    主催か
        && events
            .iter()
            .any(|e| matches!(e, crate::Event::Joined(_) | crate::Event::Left(_)))
}

#[cfg(test)]
mod tests {
    use super::*;

    const 主催: u8 = 1;
    const 自分: u8 = 2;
    const 直接: u8 = 3;
    const 遠い: u8 = 4;

    #[test]
    fn 主催の名簿に居て_自分の名簿に居ない相手を足す() {
        let (足す, 外す) =
            名簿の差(&[自分, 主催, 直接], &[主催, 自分, 直接, 遠い], &自分, &主催);
        assert_eq!(足す, vec![遠い]);
        assert!(外す.is_empty());
    }

    #[test]
    fn 主催の名簿から消えた相手を外す_自分と主催は外さない() {
        let (足す, 外す) = 名簿の差(&[自分, 主催, 直接, 遠い], &[主催, 自分], &自分, &主催);
        assert!(足す.is_empty());
        assert_eq!(外す, vec![直接, 遠い]);
    }

    #[test]
    fn 主催ごしの発言は通し_それ以外の名乗りは通さない() {
        assert!(配られた発言を通すか(
            &直接,
            &直接,
            &自分,
            Some(&主催)
        ));
        assert!(配られた発言を通すか(
            &遠い,
            &主催,
            &自分,
            Some(&主催)
        ));
        assert!(!配られた発言を通すか(
            &遠い,
            &直接,
            &自分,
            Some(&主催)
        ));
        assert!(!配られた発言を通すか(&遠い, &主催, &自分, None));
        assert!(!配られた発言を通すか(
            &自分,
            &主催,
            &自分,
            Some(&主催)
        ));
    }

    #[test]
    fn 主催かは_覚えた主催で決める_名簿の先頭では決めない() {
        assert!(主催か(None, &自分));
        assert!(主催か(Some(&自分), &自分));
        assert!(!主催か(Some(&主催), &自分));
    }
}
