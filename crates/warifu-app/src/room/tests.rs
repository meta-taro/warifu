//! `部屋たち::受ける` の規則。**経路も画面も無しで、ルームの手順を固定する。**

use super::*;
use warifu_core::Seed;

fn 鍵(n: u8) -> PublicKey {
    Seed::from_bytes([n; 32])
        .profile("Personal")
        .device("PC")
        .public_key()
}

fn 送った先(手配: &[手配]) -> Vec<(PublicKey, &'static str)> {
    手配
        .iter()
        .filter_map(|h| match h {
            手配::送る { 宛先, 知らせ } => Some((*宛先, 知らせの名(知らせ))),
            _ => None,
        })
        .collect()
}

fn 人数(m: &部屋たち, 部屋: MeetingId) -> usize {
    m.棚()[&部屋].members().len()
}

/// 主催 1 と、線のつながった客 2 と 3 の部屋。客どうしに線は無い。
fn 星形() -> (部屋たち, 部屋たち, 部屋たち, MeetingId) {
    let mut 主催 = 部屋たち::new(鍵(1));
    主催.受ける(入り口::建てた {
        id: None, 定員: 12
    });
    let 部屋 = 主催.見ている().unwrap();
    let mut 客2 = 部屋たち::new(鍵(2));
    let mut 客3 = 部屋たち::new(鍵(3));
    for (客, k) in [(&mut 客2, 鍵(2)), (&mut 客3, 鍵(3))] {
        主催.受ける(入り口::線がついた { 相手: k });
        客.受ける(入り口::線がついた { 相手: 鍵(1) });
        let 名簿: Vec<PublicKey> = 主催.棚()[&部屋].members().to_vec();
        客.受ける(入り口::入った {
            部屋,
            主催: 鍵(1),
            名簿,
            定員: 12,
            見る: true,
        });
        主催.受ける(入り口::届いた {
            線の相手: k,
            知らせ: Notice::Join { meeting: 部屋 },
        });
    }
    (主催, 客2, 客3, 部屋)
}

#[test]
fn ゲストの名簿は自分が先頭でも_主催ではない() {
    let (_, 客2, _, 部屋) = 星形();
    assert_eq!(客2.棚()[&部屋].members().first(), Some(&鍵(2)));
    assert!(
        !客2.主催か(部屋),
        "名簿の先頭が自分でも、覚えた主催が居るならゲスト"
    );
}

#[test]
fn ゲストは_主催が配った名簿を取り込む() {
    // 0.1.39 で死んでいた所。客 2 は客 3 と線が無いので、主催の名簿でしか知れない
    let (主催, mut 客2, _, 部屋) = 星形();
    assert_eq!(人数(&客2, 部屋), 2, "入ったときは主催と自分だけ");
    let 名簿 = {
        let mut r = Roster::with_capacity(鍵(1), 12).unwrap();
        for k in 主催.棚()[&部屋].members() {
            if *k != 鍵(1) {
                r.add(*k).unwrap();
            }
        }
        r
    };
    let 出 = 客2.受ける(入り口::届いた {
        線の相手: 鍵(1),
        知らせ: Notice::Invite {
            meeting: 部屋,
            roster: 名簿,
        },
    });
    assert!(出.contains(&手配::画面へ {
        部屋,
        出来事: Event::Joined(鍵(3))
    }));
    assert!(出.contains(&手配::戸口で迎える { 相手: 鍵(3) }));
    assert_eq!(人数(&客2, 部屋), 3);
    let mut a: Vec<_> = 客2.棚()[&部屋].members().to_vec();
    let mut b: Vec<_> = 主催.棚()[&部屋].members().to_vec();
    a.sort();
    b.sort();
    assert_eq!(a, b, "客の名簿は主催の名簿と同じになる");
}

