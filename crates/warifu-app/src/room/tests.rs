#[test]
fn 主催は_入った人の名簿を_線のあるほかの客へ配る_本人には配らない() {
    let mut 主催 = 部屋たち::new(鍵(1));
    主催.受ける(入り口::建てた {
        id: None, 定員: 12
    });
    let 部屋 = 主催.見ている().unwrap();
    主催.受ける(入り口::線がついた { 相手: 鍵(2) });
    let 出 = 主催.受ける(入り口::届いた {
        線の相手: 鍵(2),
        知らせ: Notice::Join { meeting: 部屋 },
    });
    // 画面へ出してから配る。1 人目には配る先が無い
    assert_eq!(
        出,
        vec![手配::画面へ {
            部屋,
            出来事: Event::Joined(鍵(2))
        }]
    );
    主催.受ける(入り口::線がついた { 相手: 鍵(3) });
    let 出 = 主催.受ける(入り口::届いた {
        線の相手: 鍵(3),
        知らせ: Notice::Join { meeting: 部屋 },
    });
    assert_eq!(
        出[0],
        手配::画面へ {
            部屋,
            出来事: Event::Joined(鍵(3))
        }
    );
    assert_eq!(送った先(&出), vec![(鍵(2), "名簿")]);
}

#[test]
fn 主催は_別の部屋の線には配らない() {
    let (mut 主催, _, _, 部屋) = 星形();
    // 別の部屋の客 4（この部屋には居ない）
    主催.受ける(入り口::建てた {
        id: None, 定員: 12
    });
    主催.受ける(入り口::線がついた { 相手: 鍵(4) });
    let 出 = 主催.受ける(入り口::届いた {
        線の相手: 鍵(2),
        知らせ: Notice::Text {
            meeting: 部屋,
            from: 鍵(2),
            話し手: None,
            body: "やあ".into(),
        },
    });
    assert_eq!(
        送った先(&出),
        vec![(鍵(3), "文字")],
        "この部屋の客 3 にだけ配る。客 4 と言った本人には配らない"
    );
}

#[test]
fn 主催ごしの文字は通し_主催でない相手の名乗りは捨てる() {
    let (_, mut 客2, _, 部屋) = 星形();
    let 文字 = |from: PublicKey| Notice::Text {
        meeting: 部屋,
        from,
        話し手: None,
        body: "やあ".into(),
    };
    // 主催が配った、客 3 の文字（客 3 とは線が無い）
    let 出 = 客2.受ける(入り口::届いた {
        線の相手: 鍵(1),
        知らせ: 文字(鍵(3)),
    });
    assert!(
        出.iter()
            .any(|h| matches!(h, 手配::文字が届いた { 差出人, .. } if *差出人 == 鍵(3)))
    );
    assert!(送った先(&出).is_empty(), "ゲストは配らない");
    // 主催でない相手が、他人を名乗って送ってきた
    客2.受ける(入り口::線がついた { 相手: 鍵(4) });
    let 出 = 客2.受ける(入り口::届いた {
        線の相手: 鍵(4),
        知らせ: 文字(鍵(3)),
    });
    assert_eq!(
        出,
        vec![手配::捨てた {
            知らせ: "文字",
            訳: 捨てた訳::差出人が線の相手と違う
        }]
    );
}

#[test]
