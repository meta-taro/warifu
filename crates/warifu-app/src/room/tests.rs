#[test]
fn 主催は_線の切れた客あての文字を預かり_上限を超えたら古い分から落とす() {
    let (mut 主催, _客2, _客3, 部屋) = 星形();
    主催.受ける(入り口::線が切れた { 相手: 鍵(3) });
    for n in 0..(預かる上限 + 5) {
        主催.受ける(入り口::言う {
            部屋,
            本文: format!("{n}"),
            話し手: None,
        });
    }
    assert_eq!(主催.預かっている数(部屋), 預かる上限);
    // 客 3 が入り直したら、残っている分を順に渡して消す
    主催.受ける(入り口::線がついた { 相手: 鍵(3) });
    let 手配 = 主催.受ける(入り口::届いた {
        線の相手: 鍵(3),
        知らせ: Notice::Join { meeting: 部屋 },
    });
    let 渡した: Vec<String> = 手配
        .iter()
        .filter_map(|h| match h {
            手配::送る {
                宛先,
                知らせ: Notice::Text { body, .. },
            } if *宛先 == 鍵(3) => Some(body.clone()),
            _ => None,
        })
        .collect();
    assert_eq!(渡した.len(), 預かる上限);
    assert_eq!(渡した[0], "5", "古い 5 件は落ちている");
    assert_eq!(主催.預かっている数(部屋), 0);
}

#[test]
fn 線のある客と差出人には預けない_畳んだら預かりも消える() {
    let (mut 主催, _客2, _客3, 部屋) = 星形();
    主催.受ける(入り口::線が切れた { 相手: 鍵(3) });
    主催.受ける(入り口::届いた {
        線の相手: 鍵(2),
        知らせ: Notice::Text {
            meeting: 部屋,
            from: 鍵(2),
            話し手: None,
            body: "やあ".to_owned(),
        },
    });
    assert_eq!(主催.預かっている数(部屋), 1, "留守の客 3 の分だけ");
    主催.受ける(入り口::畳む { 部屋 });
    assert_eq!(主催.預かっている数(部屋), 0);
}
