#[test]
fn 客の線が切れたら_主催は外して名簿を配り直す() {
    let (mut 主催, _, _, 部屋) = 星形();
    let 出 = 主催.受ける(入り口::線が切れた { 相手: 鍵(3) });
    assert_eq!(人数(&主催, 部屋), 2);
    assert_eq!(送った先(&出), vec![(鍵(2), "名簿")]);
    assert_eq!(
        出.last(),
        Some(&手配::閉じた {
            相手: 鍵(3),
            居た: true
        })
    );
}

#[test]
fn 主催の線が切れたら_客も名簿から外す() {
    // **経路が落ちたら、その人は名簿にも居ない**（D83・本体と同じ規則）。
    // 外さないと、同じ相手が入り直しても Join が冪等で何も起きず、画面に戻らなかった（2026-09-10）。
    // 影がこれを外さずに残していて、本体と名簿の人数が食い違った（10-30・mac mini の記録「影:」）
    let (_, mut 客2, _, 部屋) = 星形();
    let 出 = 客2.受ける(入り口::線が切れた { 相手: 鍵(1) });
    assert_eq!(
        人数(&客2, 部屋),
        1,
        "切れた主催は名簿から外れる（戻ってきたら Join で入り直す）"
    );
    assert_eq!(
        出,
        vec![手配::閉じた {
            相手: 鍵(1),
            居た: true
        }]
    );
}

