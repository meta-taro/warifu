//! 回線を測って、相手ごとの割り当てを決める。**申告ではなく観測。**
//!
//! フルメッシュは各自が `K×(N−1)` を上下とも負う（`decisions.md` **D9** / **D27**）。
//! 12 人 720p なら 16.5 Mbps。**携帯回線では出ない。**
//!
//! # 回線の種類を当てない。測る
//!
//! 「携帯かどうか」を判定する形にすると、
//! **携帯でも速い回線と、光でも混んでいる回線**を、両方とも読み違える。
//! 見るのは実際に流れた量だけである（[`Meter`]）。
//!
//! # 相手に尋ねない
//!
//! 「あなたの回線は何 Mbps ですか」と尋ねる形にすると、
//! **多く送ってほしい側は多めに答える**
//! （`warifu-read` で送信者に優先度を申告させなかったのと同じ理屈）。
//!
//! 相手から来る値は、**送る量を下げる方向にしか効かない。**
//! 相手が「下り 1 Gbps」と言っても、出せるのは自分の上りまでである。
//!
//! # 落とすのは画質であって人ではない
//!
//! 足りなければ段を下げる。**人は減らさない。**
//! 入れないのは、音声すら通らないときだけで、そのときは
//! [`Error::TooWeak`] と言う（**黙って 0 人ぶんを返さない**）。
//!
//! 映像から先に落とす。**声が切れるくらいなら映像を捨てる。**
//!
//! # 粗さは自動で動く
//!
//! [`plan`] は**その瞬間**の割り当てを出すだけで、回線が変われば合わなくなる。
//! 時間の経過ごとに段を上げ下げするのが [`Governor`]。
//!
//! **素朴に作ると必ず振動する。**「入るなら上げる・入らないなら下げる」を毎回やると、
//! 境目で 1 秒ごとに段が変わる。見ている側には、
//! 粗い映像より**粗さが変わり続ける映像のほうが辛い。**
//!
//! # 使い方
//!
//! ```
//! use warifu_link::{Link, Meter, Quality, plan};
//!
//! let 今 = 1_756_800_000;
//!
//! // 実際に流れた量から測る（2 秒で 2.5 MB = 10 Mbps）
//! let mut 計 = Meter::new();
//! 計.observe(2_500_000, 今 - 2, 今);
//! let 下り = 計.measured(今).expect("観測がある");
//!
//! let 自分 = Link::new(10_000_000, 下り, 今);
//! let 相手 = vec![Link::new(100_000_000, 100_000_000, 今); 3];
//!
//! let 割り当て = plan(&自分, &相手, 今)?;
//! assert_eq!(割り当て.send().len(), 3);
//! # Ok::<(), warifu_link::Error>(())
//! ```

