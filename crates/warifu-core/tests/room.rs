//! **部屋の合言葉と、その証し**（**D118** / **#28** の本線 D）。
//!
//! ここで固定するのは 4 つ。
//!
//! 1. **同じ部屋・同じ 2 人なら通る**（これが目的）
//! 2. **使い回せない**（別の相手・別の部屋・別の合言葉では通らない）
//! 3. **向きがある**（A→B の証しは B→A として通らない）
//! 4. **合言葉そのものは記録へ出ない**（`Debug` に出さない）

use warifu_core::{PublicKey, Seed, 合言葉, 部屋の証し};

fn 鍵(seed: u8) -> PublicKey {
    Seed::from_bytes([seed; 32])
        .profile("Personal")
        .device("PC")
        .public_key()
}

const 部屋: &[u8] = b"4QNXPYQIHAYIOV6OE2ZYEG4MXQ";

#[test]
fn 同じ部屋の同じ二人なら通る() {
    let 言 = 合言葉::作る().expect("作れる");
    let (a, b) = (鍵(1), 鍵(2));

    let 証し = 言.証しを作る(部屋, a, b);

    assert!(言.証しが合うか(&証し, 部屋, a, b));
}

#[test]
fn 別の相手へは使い回せない() {
    // **A が B へ出した証しを、B が C へ使い回せない。**
    // これが無いと、**1 人通した相手が、その証しで別の人を通せてしまう**
    let 言 = 合言葉::作る().expect("作れる");
    let (a, b, c) = (鍵(1), 鍵(2), 鍵(3));

    let 証し = 言.証しを作る(部屋, a, b);

    assert!(!言.証しが合うか(&証し, 部屋, a, c), "別の受け手で通った");
    assert!(!言.証しが合うか(&証し, 部屋, c, b), "別の呼び手で通った");
}

#[test]
fn 向きがある() {
    // **A→B と B→A は別物。**同じにすると、
    // 受けた証しをそのまま返して「私も知っている」と言えてしまう
    let 言 = 合言葉::作る().expect("作れる");
    let (a, b) = (鍵(1), 鍵(2));

    let 証し = 言.証しを作る(部屋, a, b);

    assert!(!言.証しが合うか(&証し, 部屋, b, a), "向きが無い");
}

#[test]
fn 別の部屋へは使い回せない() {
    // **部屋ごとに別。**1 つの部屋に入れた人が、別の部屋へ入れない
    let 言 = 合言葉::作る().expect("作れる");
    let (a, b) = (鍵(1), 鍵(2));

    let 証し = 言.証しを作る(部屋, a, b);

    assert!(!言.証しが合うか(&証し, b"OTHERROOM", a, b));
}

#[test]
fn 別の合言葉では通らない() {
    let (a, b) = (鍵(1), 鍵(2));
    let 言 = 合言葉::作る().expect("作れる");
    let 別 = 合言葉::作る().expect("作れる");

    let 証し = 言.証しを作る(部屋, a, b);

    assert!(!別.証しが合うか(&証し, 部屋, a, b));
}

#[test]
fn 合言葉は毎回ちがう() {
    // **同じ合言葉を 2 つの部屋が持つと、片方の証しが他方で通る**
    let 一 = 合言葉::作る().expect("作れる");
    let 二 = 合言葉::作る().expect("作れる");
    assert_ne!(一.バイト列(), 二.バイト列());
}

#[test]
fn 渡して戻せる() {
    // **戸口を通った相手へ、経路で渡す。**渡したものから同じ証しが出ること
    let 言 = 合言葉::作る().expect("作れる");
    let (a, b) = (鍵(1), 鍵(2));

    let 渡した = 合言葉::から(言.バイト列());

    assert!(渡した.証しが合うか(&言.証しを作る(部屋, a, b), 部屋, a, b));
}

#[test]
fn 証しも渡して戻せる() {
    let 言 = 合言葉::作る().expect("作れる");
    let (a, b) = (鍵(1), 鍵(2));

    let 戻した = 部屋の証し::から(言.証しを作る(部屋, a, b).バイト列());

    assert!(言.証しが合うか(&戻した, 部屋, a, b));
}

#[test]
fn 合言葉は記録に出さない() {
    // **記録・Issue・commit に落ちる道を作らない。**
    // `{:?}` で出ると、**うっかり 1 行書いた時点で部屋が開く**
    let 言 = 合言葉::作る().expect("作れる");
    let 文 = format!("{言:?}");

    assert_eq!(文, "合言葉(出しません)");
    // **16 進でも base32 でも出ていないこと。**
    // 「決まった文だから安心」ではなく、**中身が入っていないこと**を見る
    let 十六 = 言
        .バイト列()
        .iter()
        .map(|b| format!("{b:02x}"))
        .collect::<String>();
    assert!(!文.contains(&十六[..8]), "16 進で出ている");
    assert!(
        !文.contains(&warifu_core::base32::encode(&言.バイト列())[..8]),
        "base32 で出ている"
    );
}

#[test]
fn 証しから合言葉は出せない() {
    // **証しは経路に流してよい**という前提そのもの。
    // 証しと合言葉が一致していたら、流した時点で漏れる
    let 言 = 合言葉::作る().expect("作れる");
    let 証し = 言.証しを作る(部屋, 鍵(1), 鍵(2));

    assert_ne!(証し.バイト列(), 言.バイト列());
}

// ── 差し出す 1 通（**割符の片割れと見分けられること**） ──────────────

#[test]
fn 叩きは_渡して読み戻せる() {
    let 言 = 合言葉::作る().expect("作れる");
    let (a, b) = (鍵(1), 鍵(2));
    let 叩き = warifu_core::部屋の叩き::new(部屋, 言.証しを作る(部屋, a, b));

    let 戻した = warifu_core::部屋の叩き::from_bytes(&叩き.to_bytes()).expect("読める");

    assert_eq!(戻した.部屋(), 部屋);
    assert!(言.証しが合うか(&戻した.証し(), 部屋, a, b));
}

#[test]
fn 叩きと割符の片割れは_見分けられる() {
    // **受ける側は最初の 1 通で見分ける。**種別が同じだと、
    // 片方を他方として読もうとして**理由の分からない不通**になる
    let 言 = 合言葉::作る().expect("作れる");
    let 叩き = warifu_core::部屋の叩き::new(部屋, 言.証しを作る(部屋, 鍵(1), 鍵(2)));
    let バイト = 叩き.to_bytes();

    // 片割れとしては読めない
    assert!(warifu_core::Acceptance::from_bytes(&バイト).is_err());
    // 叩きとしては読める
    assert!(warifu_core::部屋の叩き::from_bytes(&バイト).is_ok());
}

#[test]
fn 長さをごまかせない() {
    // **長さを見ないと、短い部屋 id を渡して
    // 証しの一部を部屋 id として読ませられる**
    let 言 = 合言葉::作る().expect("作れる");
    let 叩き = warifu_core::部屋の叩き::new(部屋, 言.証しを作る(部屋, 鍵(1), 鍵(2)));
    let mut バイト = 叩き.to_bytes();

    // 長さの欄だけを 1 減らす（全体の長さは変えない）
    let 元 = u16::from_be_bytes([バイト[5], バイト[6]]);
    バイト[5..7].copy_from_slice(&(元 - 1).to_be_bytes());

    assert!(warifu_core::部屋の叩き::from_bytes(&バイト).is_err());
}

#[test]
fn 短すぎるものは断る() {
    for 長 in 0..8 {
        assert!(
            warifu_core::部屋の叩き::from_bytes(&vec![0u8; 長]).is_err(),
            "{長} バイトで通った"
        );
    }
}

#[test]
fn 目印が違えば断る() {
    let 言 = 合言葉::作る().expect("作れる");
    let 叩き = warifu_core::部屋の叩き::new(部屋, 言.証しを作る(部屋, 鍵(1), 鍵(2)));
    let mut バイト = 叩き.to_bytes();
    バイト[0] = b'X';

    assert!(warifu_core::部屋の叩き::from_bytes(&バイト).is_err());
}

#[test]
fn 叩きに合言葉は入っていない() {
    // **これを見た人は、合言葉を復元できない。**
    // 入っていたら、差し出した瞬間に部屋が開く
    let 言 = 合言葉::作る().expect("作れる");
    let 叩き = warifu_core::部屋の叩き::new(部屋, 言.証しを作る(部屋, 鍵(1), 鍵(2)));
    let バイト = 叩き.to_bytes();

    // 合言葉の並びが、どこにも現れないこと
    let 中身 = 言.バイト列();
    assert!(
        !バイト.windows(中身.len()).any(|窓| 窓 == 中身),
        "合言葉が入っている"
    );
}
