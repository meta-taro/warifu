//! **この機械のエージェントの読み**を、`room_status` の行にする（0.1.43）。
//!
//! 知らせ（channels）を受けずに動いている席は、`@` で呼ばれても読みに来ない。口からは
//! 受けられるかが見分けられないので、呼ばれたのに読んでいない数を出して、人が見分ける。

use warifu_desk::読みの様子;

/// 様子の `読み` を行にする。**古い机は欄を返さない**（空）ので、そのときは行を足さない。
#[must_use]
pub fn 読みを並べる(読み: &[読みの様子]) -> Vec<String> {
    読み.iter().map(一人の行).collect()
}

fn 一人の行(一人: &読みの様子) -> String {
    let いつ = 一人.最後に読んだ.as_deref().map_or_else(
        || "まだ一度も読んでいない".to_owned(),
        |t| format!("最後に読んだ {t}"),
    );
    let 呼ばれた = if 一人.宛てで読んでいない > 0 {
        format!(
            "（うち @ で呼ばれた {} 件。呼ばれても読みに来ていません —— 知らせ（channels）なしで動いているなら、`warifu claude` で立ち上げ直すと届きます）",
            一人.宛てで読んでいない
        )
    } else {
        String::new()
    };
    format!(
        "読み: {} —— {いつ}・読んでいない {} 件{呼ばれた}",
        一人.名, 一人.読んでいない
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    fn 様子(
        最後に読んだ: Option<&str>, 読んでいない: usize, 宛て: usize
    ) -> 読みの様子 {
        読みの様子 {
            名: "docs のエージェント".to_owned(),
            最後に読んだ: 最後に読んだ.map(str::to_owned),
            読んでいない,
            宛てで読んでいない: 宛て,
        }
    }

    #[test]
    fn 古い机が欄を返さなければ_行を足さない() {
        assert!(読みを並べる(&[]).is_empty());
    }

    #[test]
    fn 読みに来ている席は_時刻と数だけ() {
        let 行 = 読みを並べる(&[様子(Some("18:25"), 0, 0)]);
        assert_eq!(
            行,
            ["読み: docs のエージェント —— 最後に読んだ 18:25・読んでいない 0 件"]
        );
    }

    #[test]
    fn 呼ばれたのに読んでいない席は_立ち上げ直し方まで言う() {
        let 行 = 読みを並べる(&[様子(None, 4, 2)]);
        assert!(行[0].contains("まだ一度も読んでいない"), "{}", 行[0]);
        assert!(行[0].contains("@ で呼ばれた 2 件"), "{}", 行[0]);
        assert!(行[0].contains("warifu claude"), "{}", 行[0]);
    }
}
