import { describe, expect, it } from 'vitest';
import { 宛先を据え置くか } from './keep';
import type { 送り方 } from './postbox';

const 封: 送り方 = { 種類: '預ける', key: 'TANAKA' };
const 部屋: 送り方 = { 種類: 'ルーム' };
const 機械: 送り方 = { 種類: 'この機械', 宛先: 'zumen' };

describe('打っている途中に宛先を変えない', () => {
  // **いま実在する privacy の穴**（2026-09-14・設計の検証で見つけた）——
  //
  // 田中と封（留守中の受け取り）でやりとり中、**打ちかけたところで田中がルームに入る**と、
  // `どう送るか` が `ルーム` に変わる。送信を押すと、**封で送るつもりだった内容が
  // ルーム全員とこの PC のエージェントに出る。**
  //
  // **見出しを出すだけでは防げない**（人は毎回読み直さない）。**据え置く。**

  it('**下書きがあるなら、封のままにする**（勝手にルームへ向けない）', () => {
    expect(宛先を据え置くか({ 下書きがある: true, いまの送り方: 封, 新しい送り方: 部屋 })).toBe(
      true
    );
  });

  it('下書きが無ければ、新しい宛先へ移ってよい', () => {
    expect(宛先を据え置くか({ 下書きがある: false, いまの送り方: 封, 新しい送り方: 部屋 })).toBe(
      false
    );
  });

  it('同じ種類なら、据え置く意味が無い', () => {
    expect(宛先を据え置くか({ 下書きがある: true, いまの送り方: 部屋, 新しい送り方: 部屋 })).toBe(
      false
    );
  });

  it('**封から別の封へも据え置く**（別人の封に付け替わったら、もっと悪い）', () => {
    const 別の封: 送り方 = { 種類: '預ける', key: 'SATO' };
    expect(宛先を据え置くか({ 下書きがある: true, いまの送り方: 封, 新しい送り方: 別の封 })).toBe(
      true
    );
  });

  it('エージェントあての下書きも、ルームへ向けない', () => {
    expect(宛先を据え置くか({ 下書きがある: true, いまの送り方: 機械, 新しい送り方: 部屋 })).toBe(
      true
    );
  });

  it('**送れない → 送れるようになったときは据え置かない**（打てない所に留めない）', () => {
    const 無理: 送り方 = { 種類: '送れない', 訳: 'send.absent' };
    expect(宛先を据え置くか({ 下書きがある: true, いまの送り方: 無理, 新しい送り方: 部屋 })).toBe(
      false
    );
  });
});
