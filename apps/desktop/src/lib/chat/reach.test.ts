import { describe, expect, it } from 'vitest';

import { 届く先の顔を並べる, 届く先を並べる, 宛先を決める, 見ているルームの相手だけ } from './reach';

const この機械 = 'マイ PC エージェント';

describe('届く先', () => {
  it('誰も居なければ空', () => {
    // **「届きます」と書いておいて誰にも届かない、をやらない**（D49）
    expect(届く先を並べる({ 会議の相手: [], この機械のAIたち: [] })).toEqual([]);
  });

  it('相手が 1 人なら、1 人だけ並ぶ（1 対 1 と読める）', () => {
    // **「1 対 1 なのか 1 対 N なのか」は最初に人が気にする**（2026-09-07）。
    // 言葉で説明するより、届く先をそのまま並べたほうが早い
    expect(届く先を並べる({ 会議の相手: ['air'], この機械のAIたち: [] })).toEqual(['air']);
  });

  it('相手が 3 人なら、3 人並ぶ（1 対 N と読める）', () => {
    expect(
      届く先を並べる({ 会議の相手: ['air', 'win', 'mini'], この機械のAIたち: [] }),
    ).toEqual(['air', 'win', 'mini']);
  });

  it('この機械につながっていれば、マイ PC エージェント も並ぶ', () => {
    expect(届く先を並べる({ 会議の相手: ['air'], この機械のAIたち: [この機械] })).toEqual([
      'air',
      この機械,
    ]);
  });

  it('つながっているエージェントを、1 つずつ並べる', () => {
    // **まとめると、どれに届くのか分からない**（2026-09-08）
    expect(
      届く先を並べる({ 会議の相手: [], この機械のAIたち: ['alpha の AI', 'beta の AI'] }),
    ).toEqual(['alpha の AI', 'beta の AI']);
  });

  it('自分は入れない', () => {
    // **自分に届くのは当たり前。**数に入れると「1 人に届く」が
    // 自分だけなのか相手 1 人なのか読めなくなる
    expect(届く先を並べる({ 会議の相手: [], この機械のAIたち: [] })).toHaveLength(0);
  });
});

describe('宛先', () => {
  const AIたち = ['alpha の AI', 'beta の AI'];

  it('この機械の AI を選ぶと、その 1 つが宛先になる', () => {
    // **3 つも 4 つもつながっていると、alpha だけに聞きたくても全員に飛ぶ。**
    // それでは 1 対 1 が成り立たない（2026-09-08）
    expect(宛先を決める('desk:alpha の AI', AIたち)).toBe('alpha の AI');
  });

  it('何も選んでいなければ、宛先は無い（全員へ）', () => {
    expect(宛先を決める(null, AIたち)).toBeNull();
  });

  it('ルームの相手は宛先にできない', () => {
    // **そちらはルームに何人居るかで決まる**（issues/015）
    expect(宛先を決める('BBBBBBBBBBBBBBBB', AIたち)).toBeNull();
  });

  it('つながっていない相手は宛先にしない', () => {
    // **居ないものへ送ったことにしない**
    expect(宛先を決める('desk:gamma の AI', AIたち)).toBeNull();
  });

  it('宛先が決まっていれば、届く先はその 1 つだけ', () => {
    expect(
      届く先を並べる({ 会議の相手: ['air'], この機械のAIたち: AIたち, 宛先: 'alpha の AI' }),
    ).toEqual(['alpha の AI']);
  });

  it('宛先が無ければ、居る全員が並ぶ', () => {
    expect(届く先を並べる({ 会議の相手: ['air'], この機械のAIたち: AIたち })).toEqual([
      'air',
      ...AIたち,
    ]);
  });
});

describe('届く先の顔', () => {
  it('名前と同じ順で、人は鍵・エージェントは desk: で並ぶ', () => {
    expect(
      届く先の顔を並べる({ 会議の相手の鍵: ['KEYA', 'KEYB'], この機械のAIたち: ['alpha'] }),
    ).toEqual(['KEYA', 'KEYB', 'desk:alpha']);
  });

  it('宛先が決まっていれば、その 1 つだけ', () => {
    expect(
      届く先の顔を並べる({ 会議の相手の鍵: ['KEYA'], 宛先: 'alpha', この機械のAIたち: ['alpha'] }),
    ).toEqual(['desk:alpha']);
  });

  it('名前の並びと数が揃う', () => {
    const 素材 = { 会議の相手: ['a', 'b'], この機械のAIたち: ['x', 'y'] };
    expect(
      届く先の顔を並べる({ 会議の相手の鍵: ['KA', 'KB'], この機械のAIたち: 素材.この機械のAIたち }),
    ).toHaveLength(届く先を並べる(素材).length);
  });
});

describe('見ているルームの相手だけ', () => {
  const 相手たち = [{ key: 'KA' }, { key: 'KB' }, { key: 'KC' }];

  it('別のルームの相手は、届く先に出さない', () => {
    expect(見ているルームの相手だけ(相手たち, ['ME', 'KB'])).toEqual([{ key: 'KB' }]);
  });

  it('ルームの顔ぶれが分からないときは、絞らない', () => {
    expect(見ているルームの相手だけ(相手たち, null)).toEqual(相手たち);
  });

  it('顔ぶれに居るのに入ってきた知らせを受けていない相手も、届く先に出す（読み込み直したあと）', () => {
    // **Ctrl+R で画面だけ読み込み直すと、入ってきた知らせは来直さない**（0.1.36 の試しで踏んだ）。
    // 機械はつながったままなのに、届く先が 0 人になり、打てなくなっていた
    const 足す = (key: string) => ({ key });
    expect(見ているルームの相手だけ([], ['ME', 'KB'], 'ME', 足す)).toEqual([{ key: 'KB' }]);
  });

  it('知らせを受けた相手は、受けたときの中身のまま出す', () => {
    const 受けた = [{ key: 'KB', 映像: true }];
    const 足す = (key: string) => ({ key, 映像: false });
    expect(見ているルームの相手だけ(受けた, ['ME', 'KB', 'KC'], 'ME', 足す)).toEqual([
      { key: 'KB', 映像: true },
      { key: 'KC', 映像: false },
    ]);
  });
});
