import { describe, expect, it } from 'vitest';

import { 届く先を並べる } from './reach';

const 机 = 'この PC の AI';

describe('届く先', () => {
  it('誰も居なければ空', () => {
    // **「届きます」と書いておいて誰にも届かない、をやらない**（D49）
    expect(届く先を並べる({ 会議の相手: [], 机の人数: 0, 机の呼び名: 机 })).toEqual([]);
  });

  it('相手が 1 人なら、1 人だけ並ぶ（1 対 1 と読める）', () => {
    // **「1 対 1 なのか 1 対 N なのか」は最初に人が気にする**（オーナー・2026-09-07）。
    // 言葉で説明するより、届く先をそのまま並べたほうが早い
    expect(届く先を並べる({ 会議の相手: ['air'], 机の人数: 0, 机の呼び名: 机 })).toEqual(['air']);
  });

  it('相手が 3 人なら、3 人並ぶ（1 対 N と読める）', () => {
    expect(
      届く先を並べる({ 会議の相手: ['air', 'win', 'mini'], 机の人数: 0, 机の呼び名: 机 }),
    ).toEqual(['air', 'win', 'mini']);
  });

  it('机に着いていれば、この PC の AI も並ぶ', () => {
    expect(届く先を並べる({ 会議の相手: ['air'], 机の人数: 1, 机の呼び名: 机 })).toEqual([
      'air',
      机,
    ]);
  });

  it('机に 2 つ着いていても、席は 1 つとして並べる', () => {
    // **同じ机に着いている。**人から見れば「この PC の AI」1 つである
    expect(届く先を並べる({ 会議の相手: [], 机の人数: 2, 机の呼び名: 机 })).toEqual([机]);
  });

  it('自分は入れない', () => {
    // **自分に届くのは当たり前。**数に入れると「1 人に届く」が
    // 自分だけなのか相手 1 人なのか読めなくなる
    expect(届く先を並べる({ 会議の相手: [], 机の人数: 0, 机の呼び名: 机 })).toHaveLength(0);
  });
});
