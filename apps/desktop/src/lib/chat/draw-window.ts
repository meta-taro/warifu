// 会話欄に**描く行の数**。
//
// 会話はルームごとに 5,000 行まで残す（`chat_keep`）。それを全部描くと、
// 人数の多いルームでは数日で 5,000 個の吹き出しになり、開くのも 1 件届くのも重くなる。
//
// 決めたこと ——
//
// 1. **新しいほうから 300 行だけ描く。**それより前は［前を読む］で 300 行ずつ足す
// 2. **底で見ている人は 300 行のまま**（行が来ると古い行から描かなくなる）
// 3. **読み返している人は、来た分だけ広げる**（描く頭を動かさない。読んでいる所が跳ばない）
// 4. 返信の元が描いていない行なら、その行まで広げる
//
// 残す行（保存）の数は変えない。描く数だけの話である。

/** 一度に描く行の数。［前を読む］もこの数ずつ足す。 */
export const 一度に描く行 = 300;

/** 描く最初の行（会話の何番目から描くか）。 */
export function 描く頭(全体: number, 描く数: number): number {
	return Math.max(0, 全体 - 描く数);
}

/** 行が増えたあとに描く数。 */
export function 行が増えたときの描く数(いまの描く数: number, 増えた: number, 底にいる: boolean): number {
	if (底にいる) return 一度に描く行;
	return いまの描く数 + Math.max(0, 増えた);
}

/** ［前を読む］を押したあとに描く数。 */
export function 前を読んだ描く数(いまの描く数: number, 全体: number): number {
	return Math.min(全体, いまの描く数 + 一度に描く行);
}

/** 会話の `番目` の行を描くのに要る描く数。もう描いていれば変えない。 */
export function 含める描く数(全体: number, 番目: number, いまの描く数: number): number {
	return Math.max(いまの描く数, 全体 - 番目);
}
