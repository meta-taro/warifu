import { describe, it, expect } from 'vitest';
import { 底にいるか, 新しい行が来たとき, 底に着いた, 底の余白 } from './scroll';

// **会話欄の位置**。上端・見えている高さ・全体の高さ
const 位置 = (上: number, 見える高さ: number, 全体: number) => ({ 上, 見える高さ, 全体 });

describe('底にいるか', () => {
  it('いちばん下まで送ってあれば、底に居る', () => {
    expect(底にいるか(位置(360, 140, 500))).toBe(true);
  });

  it('数 px 手前でも底に居るとみなす（1 px の差で札が出ると煩わしい）', () => {
    expect(底にいるか(位置(360 - 底の余白 + 1, 140, 500))).toBe(true);
  });

  it('読み返している途中なら、底に居ない', () => {
    expect(底にいるか(位置(0, 140, 500))).toBe(false);
  });

  it('全部が見えていて溢れていないなら、底に居る', () => {
    expect(底にいるか(位置(0, 500, 500))).toBe(true);
  });
});

describe('新しい行が来たとき', () => {
  it('底で見ているなら、そのまま下へ送る。札は出さない', () => {
    expect(新しい行が来たとき(位置(360, 140, 500), 1, 0, false)).toEqual({ 追う: true, 新着: 0 });
  });

  it('読み返している途中なら、下へ送らない。代わりに数を数える', () => {
    expect(新しい行が来たとき(位置(0, 140, 500), 1, 0, false)).toEqual({ 追う: false, 新着: 1 });
  });

  it('読み返している間に届いた分は、足していく', () => {
    expect(新しい行が来たとき(位置(0, 140, 500), 2, 3, false)).toEqual({ 追う: false, 新着: 5 });
  });

  it('**自分が打ったときは、読み返している途中でも下へ送る**（打った物は見せる）', () => {
    expect(新しい行が来たとき(位置(0, 140, 500), 1, 4, true)).toEqual({ 追う: true, 新着: 0 });
  });

  it('増えていないなら、何もしない（描き直しで札を出さない）', () => {
    expect(新しい行が来たとき(位置(0, 140, 500), 0, 3, false)).toEqual({ 追う: false, 新着: 3 });
  });

  it('減ったとき（ルームを移ったとき）も数を増やさない', () => {
    expect(新しい行が来たとき(位置(0, 140, 500), -5, 3, false)).toEqual({ 追う: false, 新着: 3 });
  });
});

describe('底に着いた', () => {
  it('底まで読んだら、札は消える', () => {
    expect(底に着いた(位置(360, 140, 500))).toBe(0);
  });

  it('まだ底でなければ、消さない（null で「変えない」を返す）', () => {
    expect(底に着いた(位置(0, 140, 500))).toBe(null);
  });
});
