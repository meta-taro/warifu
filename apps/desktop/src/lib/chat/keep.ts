// **打っている途中に宛先を変えない。**
//
// 2026-09-14、設計の検証で見つけた **いま実在する privacy の穴** ——
//
// 佐藤と封（留守中の受け取り）でやりとり中、**打ちかけたところで佐藤がルームに入る**と、
// `どう送るか`（`postbox.ts`）が `ルーム` に変わる。送信を押すと、
// **封で送るつもりだった内容が、ルーム全員とこの PC のエージェントに出る。**
//
// **見出しで告げるだけでは防げない** —— 人は打っている途中に見出しを読み直さない。
// **だから据え置く。**据え置いたことは画面が言い、人が選び直せるようにする。

import type { 送り方 } from './postbox';

/** 据え置くかを決めるのに要るもの。 */
export type いま = {
	/** 打ち込み欄に文字があるか。 */
	下書きがある: boolean;
	/** いま向いている宛先。 */
	いまの送り方: 送り方;
	/** 状況が変わって出てきた宛先。 */
	新しい送り方: 送り方;
	/**
	 * **人が自分で部屋を替えたか**（2026-10-23）。
	 *
	 * 据え置くのは「状況が変わって宛先が動いた」ときだけ。人がほかの部屋を押したときまで
	 * 据え置くと、**前の部屋の下書きが次の部屋の欄に残って見える**（下書きは部屋ごとに控える・`./draft`）。
	 */
	部屋を替えた?: boolean;
};

/** その宛先が「同じ所」か。**封は相手ごとに別**（付け替わったら、もっと悪い）。 */
function 同じ宛先か(a: 送り方, b: 送り方): boolean {
	if (a.種類 !== b.種類) return false;
	if (a.種類 === '預ける' && b.種類 === '預ける') return a.key === b.key;
	if (a.種類 === 'この機械' && b.種類 === 'この機械') return a.宛先 === b.宛先;
	return true;
}

/**
 * **打っている途中なら、宛先を据え置くか。**
 *
 * - 下書きが無ければ据え置かない（移ってよい）
 * - 同じ宛先なら据え置く意味が無い
 * - **`送れない` から動くときは据え置かない** —— 打てない所に人を留めない
 */
export function 宛先を据え置くか(いま: いま): boolean {
	if (!いま.下書きがある) return false;
	// **人が替えたなら、据え置かない。**勝手に動いたのではない
	if (いま.部屋を替えた) return false;
	if (同じ宛先か(いま.いまの送り方, いま.新しい送り方)) return false;
	// **打てない所には留めない。**据え置く値があるのは「送れる宛先」だけ
	if (いま.いまの送り方.種類 === '送れない') return false;
	return true;
}
