// 会話欄の**送り方**。
//
// **入っていなかった** —— `overflow-y: auto` だけで、新しい発言は
// 折り返しの下に積まれるだけだった。読んでいる人には**何も起きていないように見える。**
//
// 決めたこと 3 つ ——
//
// 1. **底で見ている人は、下へ送る**（黙って追従する）
// 2. **読み返している人は、動かさない。**代わりに**何件来たかを札で出す**
//    （下へ引っ張られると、読んでいた所を失う）
// 3. **自分が打ったものは、必ず見せる**（読み返している途中でも底へ送る）
//
// **既読ではない**（D94）。ここで数えるのは「**まだ見ていない画面の下**」であって、
// 相手が読んだかどうかではない。

/** 会話欄のいまの位置。DOM から取るのはここだけ（`scrollTop` / `clientHeight` / `scrollHeight`）。 */
export type 位置 = {
	上: number;
	見える高さ: number;
	全体: number;
};

/**
 * **底とみなす余白（px）。**
 *
 * 1 px の差で「新しい発言」の札が出ると煩わしい。行の高さより小さく、
 * 指で少し動かした程度では外れない幅にする。
 */
export const 底の余白 = 24;

/** いちばん下まで送ってあるか（数 px の手前も底とみなす）。 */
export function 底にいるか(位置: 位置, 余白: number = 底の余白): boolean {
	return 位置.上 + 位置.見える高さ >= 位置.全体 - 余白;
}

/** 新しい行が来たあとの見え方。 */
export type 見え方 = {
	/** 底まで送るか。 */
	追う: boolean;
	/** 「新しい発言 n 件」の数。**0 なら札を出さない。** */
	新着: number;
};

/**
 * 行が増えたときに、送るか・数えるかを決める。
 *
 * `増えた` が 0 以下のときは何もしない —— **描き直しやルーム移動で札を出さない。**
 */
export function 新しい行が来たとき(
	位置: 位置,
	増えた: number,
	いまの新着: number,
	自分の発言か: boolean
): 見え方 {
	// **自分が打ったものは必ず見せる。**読み返している途中でも底へ送る
	if (自分の発言か) return { 追う: true, 新着: 0 };
	if (増えた <= 0) return { 追う: false, 新着: いまの新着 };
	if (底にいるか(位置)) return { 追う: true, 新着: 0 };
	return { 追う: false, 新着: いまの新着 + 増えた };
}

/**
 * 人が動かしたときに札を消すか。
 *
 * **底に着いたときだけ 0 を返す。**まだ底でなければ `null`（「**変えない**」）——
 * 途中まで戻っただけで札を消すと、下に何件あるか分からなくなる。
 */
export function 底に着いた(位置: 位置): number | null {
	return 底にいるか(位置) ? 0 : null;
}
