import { describe, expect, it } from 'vitest';
import { 部屋を替える } from './draft';

describe('部屋ごとの下書き', () => {
  // 2026-10-23、ASUS の部屋で打ちかけた文が、開発の部屋へ移っても欄に残っていた。
  // 人は欄を見ても「どの部屋に向けて書いたか」が分からない。

  it('部屋を替えると、打ちかけの文は欄から消える', () => {
    const r = 部屋を替える({}, 'ASUS', '開発', '明日の件ですが');
    expect(r.下書き).toBe('');
  });

  it('戻ってくると、打ちかけの文が戻る', () => {
    const 一度目 = 部屋を替える({}, 'ASUS', '開発', '明日の件ですが');
    const 二度目 = 部屋を替える(一度目.控え, '開発', 'ASUS', '');
    expect(二度目.下書き).toBe('明日の件ですが');
  });

  it('欄へ戻した分は、控えに残さない（送ったあとに古い文が戻らない）', () => {
    const 一度目 = 部屋を替える({}, 'ASUS', '開発', '明日の件ですが');
    const 二度目 = 部屋を替える(一度目.控え, '開発', 'ASUS', '');
    expect(二度目.控え).toEqual({});
  });

  it('空の下書きは控えない', () => {
    const r = 部屋を替える({}, 'ASUS', '開発', '   ');
    expect(r.控え).toEqual({});
  });

  it('同じ部屋なら何も変えない', () => {
    const r = 部屋を替える({ 開発: '古い' }, 'ASUS', 'ASUS', '書きかけ');
    expect(r.下書き).toBe('書きかけ');
    expect(r.控え).toEqual({ 開発: '古い' });
  });

  it('部屋を選んでいない状態（null）も 1 つの部屋として扱う', () => {
    const 一度目 = 部屋を替える({}, null, 'ASUS', 'まだ誰にも');
    const 二度目 = 部屋を替える(一度目.控え, 'ASUS', null, '');
    expect(二度目.下書き).toBe('まだ誰にも');
  });
});
