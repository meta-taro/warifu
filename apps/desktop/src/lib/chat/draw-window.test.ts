import { describe, expect, it } from 'vitest';
import { 一度に描く行, 描く頭, 行が増えたときの描く数, 前を読んだ描く数, 含める描く数 } from './draw-window';

describe('会話欄は新しいほうから決まった数だけ描く', () => {
	it('行が少なければ全部描く', () => {
		expect(描く頭(120, 一度に描く行)).toBe(0);
	});

	it('多ければ新しい 300 行だけ描く', () => {
		expect(描く頭(5000, 一度に描く行)).toBe(4700);
	});

	it('底で見ている人には、行が増えても 300 行のまま（古い行を描かなくなる）', () => {
		expect(行が増えたときの描く数(一度に描く行, 3, true)).toBe(一度に描く行);
	});

	it('前を読んで広げていても、底に戻って行が来たら 300 行に戻す', () => {
		expect(行が増えたときの描く数(900, 1, true)).toBe(一度に描く行);
	});

	it('読み返している人には、増えた分だけ広げる（いま見ている行が動かない）', () => {
		expect(行が増えたときの描く数(一度に描く行, 3, false)).toBe(一度に描く行 + 3);
	});

	it('［前を読む］で 300 行ずつ足し、全体を超えない', () => {
		expect(前を読んだ描く数(一度に描く行, 5000)).toBe(600);
		expect(前を読んだ描く数(4900, 5000)).toBe(5000);
	});

	it('返信の元が描いていない古い行なら、その行まで広げる', () => {
		expect(含める描く数(5000, 100, 一度に描く行)).toBe(4900);
		expect(含める描く数(5000, 4900, 一度に描く行)).toBe(一度に描く行);
	});
});
