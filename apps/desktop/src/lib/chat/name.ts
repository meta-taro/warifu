// **同じ鍵の相手は、いつも同じ顔で出す。**
//
// 2026-09-15、実機で**同じ人が 1 通目は名前・2 通目は鍵**で出た（#19・ASUS の報告）——
//
//   18:44  めたたろ（mac mini）   …
//   18:44  I3ILQUUJQHVS…          …   ← 同じ鍵。11 秒後
//
// **人からは 2 人居るように見える。**3 人以上の部屋では、そのまま
// 「**誰が喋ったか分からない**」になる。
//
// 原因は**行に名前を焼き付けていたこと。**届いた瞬間に引いた名前を持つので、
// **名乗りが後から来た回・引けなかった回だけ鍵になる。**
//
// **描くときに引き直す。**行は `顔の種`（公開鍵の全桁、または `desk:<名>`）を
// 既に持っているので、名簿があれば引ける。

import type { 会話行 } from '$lib/meeting/announce';

/**
 * その行の差出人を、いまの名簿で呼ぶ。
 *
 * **名簿に無ければ、行が持っている名前をそのまま出す** ——
 * 引けないことを理由に、**人を消さない。**
 */
export function 行の差出人名(行: 会話行, 名簿: Readonly<Record<string, string>>): string {
  const 種 = 行.顔の種;
  if (!種) return 行.who;
  const 引いた = 名簿[種];
  return 引いた && 引いた.length > 0 ? 引いた : 行.who;
}
