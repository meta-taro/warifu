// **同じ鍵の相手は、いつも同じ顔で出す。**
//
// 2026-09-15、実機で**同じ人が 1 通目は名前・2 通目は鍵**で出た（#19）——
//
//   18:44  佐藤（mac mini）   …
//   18:44  PEERAAAAAAAA…          …   ← 同じ鍵。11 秒後
//
// **人からは 2 人居るように見える。**3 人以上の部屋では、そのまま
// 「**誰が喋ったか分からない**」になる。
//
// 原因は**行に名前を焼き付けていたこと。**届いた瞬間に引いた名前を持つので、
// **名乗りが後から来た回・引けなかった回だけ鍵になる。**
//
// **描くときに引き直す。**行は `顔の種`（公開鍵の全桁、または `desk:<名>`）を
// 既に持っているので、名簿があれば引ける。

import type { 会話行 } from '$lib/meeting/announce';

/**
 * その行の差出人を、いまの名簿で呼ぶ。
 *
 * **名簿に無ければ、行が持っている名前をそのまま出す** ——
 * 引けないことを理由に、**人を消さない。**
 */
export function 行の差出人名(行: 会話行, 名簿: Readonly<Record<string, string>>): string {
  const 種 = 行.顔の種;
  if (!種) return 行.who;
  // **相手の機械のエージェント**は `短く(鍵)（札）` で届く（2026-10-27・内部の Issue 026 の #49）。
  // 名簿は鍵の全桁で引くので、この形のままでは引けず**鍵の頭だけ**が出ていた ——
  // 連絡先に名前を付けていても、席が名乗っていても、人には誰の発言か分からなかった。
  // **名乗り（席）を先に、連絡先の名前（機械）を添える。**1 台に席が複数あっても見分けられる
  const 分けた = 相手の機械の名札を分ける(種);
  if (分けた) {
    const 機械 = 鍵の頭から引く(名簿, 分けた.頭) ?? `${分けた.頭}…`;
    return `${分けた.札}・${機械}`;
  }
  const 引いた = 名簿[種];
  return 引いた && 引いた.length > 0 ? 引いた : 行.who;
}

/** 相手の機械のエージェントの名札（`短く(鍵)（札）`）を、鍵の頭と札に分ける。公開鍵は `（` を含まない。 */
function 相手の機械の名札を分ける(種: string): { 頭: string; 札: string } | null {
  const 位置 = 種.indexOf('（');
  if (位置 <= 0 || !種.endsWith('）')) return null;
  return { 頭: 種.slice(0, 位置).replace(/…$/, ''), 札: 種.slice(位置 + 1, -1) };
}

/** 鍵の頭から、名簿（鍵の全桁 → 名前）を引く。1 つに決まらなければ引かない。 */
function 鍵の頭から引く(名簿: Readonly<Record<string, string>>, 頭: string): string | undefined {
  if (頭 === '') return undefined;
  const 当たり = Object.keys(名簿).filter((k) => k.startsWith(頭) && 名簿[k].length > 0);
  return 当たり.length === 1 ? 名簿[当たり[0]] : undefined;
}

/** 机が組むエージェントの名札の後ろ（`desk.rs` の `{名} のエージェント`）。 */
const エージェントの印 = ' のエージェント';

/**
 * **エージェントの名札を、見ている人の言葉で言い直す。**
 *
 * 名札は机が日本語で組み、相手へもその形で届く（会話を引く鍵にも使う）ので、**元は変えない。**
 * 英語の画面に「note-taker のエージェント」と出ていたので、**出すときだけ**言い直す。
 * 名乗りが付いた名札（`X のエージェント（名乗り）`）も同じに扱う。
 */
export function エージェントの名を言い換える(名: string, 言い方: (名: string) => string): string {
  const 位置 = 名.indexOf(エージェントの印);
  if (位置 <= 0) return 名;
  const 後ろ = 名.slice(位置 + エージェントの印.length);
  if (後ろ !== '' && !後ろ.startsWith('（')) return 名;
  return 言い方(名.slice(0, 位置)) + 後ろ;
}
