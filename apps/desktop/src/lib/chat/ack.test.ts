import { describe, expect, it } from 'vitest';

import type { 会話行 } from '$lib/meeting/announce';
import { 受けたことにする, 受けたを足す, 受けを見る, 受ける押し所を出すか, 返事で受けたことにする } from './ack';

const 私の行 = (印: string, 時 = 0): 会話行 => ({ who: 'わたし', body: '@営業 見て', mine: true, 印, 時 });
const 相手の行 = (印?: string): 会話行 => ({ who: '山田さん', body: '@わたし 見て', mine: false, 印 });

describe('受けた（D130）', () => {
  it('印の合う自分の行にだけ足し、同じ相手の 2 度目は足さない', () => {
    const 会話 = { A: [私の行('x'), 私の行('y'), { ...相手の行('x') }] };
    const 一度 = 受けたを足す(会話, 'A', 'x', '営業', '押した', 100);
    expect(一度.A[0].受け).toEqual([{ 誰: '営業', 方: '押した', 時: 100 }]);
    expect(一度.A[1].受け).toBeUndefined();
    expect(一度.A[2].受け).toBeUndefined();
    expect(受けたを足す(一度, 'A', 'x', '営業', '返事', 200)).toBe(一度);
    // 別の部屋の印では足さない
    expect(受けたを足す(会話, 'B', 'x', '営業', '押した', 100)).toBe(会話);
  });

  it('呼ばれた行だけに［受けました］を出し、受けたら消す', () => {
    expect(受ける押し所を出すか(相手の行('x'), true)).toBe(true);
    expect(受ける押し所を出すか(相手の行('x'), false)).toBe(false);
    // 印の無い行（古い版から届いた・この機械の中だけの行）には出さない
    expect(受ける押し所を出すか(相手の行(), true)).toBe(false);
    const 受けた = 受けたことにする({ A: [相手の行('x')] }, 'A', 'x');
    expect(受ける押し所を出すか(受けた.A[0], true)).toBe(false);
  });

  it('その部屋で返事を書いたら、自分が呼ばれた行だけを受けたにする', () => {
    const 会話 = {
      A: [相手の行('x'), { ...相手の行('y'), body: 'みなさんへ' }],
      B: [相手の行('z')],
    };
    const 次 = 返事で受けたことにする(会話, 'A', ['わたし']);
    expect(次.A[0].受けた).toBe(true);
    expect(次.A[1].受けた).toBeUndefined();
    expect(次.B[0].受けた).toBeUndefined();
  });

  it('呼んだ行は、受けるまで経った分を出し、30 分で知らせる', () => {
    const 分 = 60_000;
    expect(受けを見る(私の行('x', 0), ['営業'], 15 * 分)).toEqual({ 種: 'まだ', 分: 15, 知らせる: false });
    expect(受けを見る(私の行('x', 0), ['営業'], 30 * 分)).toEqual({ 種: 'まだ', 分: 30, 知らせる: true });
    const 受けた = { ...私の行('x'), 受け: [{ 誰: '営業', 方: '読んだ', 時: 5 }] };
    expect(受けを見る(受けた, ['営業'], 99 * 分)).toEqual({ 種: '受けた', 誰たち: 受けた.受け });
    // 誰も呼んでいない行・相手の行には何も出さない
    expect(受けを見る(私の行('x'), [], 0)).toBeNull();
    expect(受けを見る(相手の行('x'), ['営業'], 0)).toBeNull();
  });

  it('受けたが届いていれば、画面が呼んだ名を見分けられなくても「受けた」と出す', () => {
    const 行 = { ...私の行('x', 0), 受け: [{ 誰: 'probe-b', 方: '読んだ', 時: 1 }] };
    expect(受けを見る(行, [], 2)?.種).toBe('受けた');
    // 届いていなければ、呼んだ名が無いときは何も出さない
    expect(受けを見る(私の行('x', 0), [], 2)).toBeNull();
  });

  it('同じ文を 2 回言ったら、受けたは新しい行から 1 つずつ埋める', () => {
    const 会話 = { A: [私の行('x', 1), 私の行('x', 2)] };
    const 一度 = 受けたを足す(会話, 'A', 'x', '営業', '押した', 100);
    expect(一度.A[0].受け).toBeUndefined();
    expect(一度.A[1].受け).toHaveLength(1);
    const 二度 = 受けたを足す(一度, 'A', 'x', '営業', '押した', 200);
    expect(二度.A[0].受け).toHaveLength(1);
  });

  it('同じ文で 2 回呼ばれたら、［受けました］は押した行だけが消える', () => {
    const 会話 = { A: [{ ...相手の行('x'), 時: 1 }, { ...相手の行('x'), 時: 2 }] };
    const 一度 = 受けたことにする(会話, 'A', 'x', 1);
    expect(一度.A[0].受けた).toBe(true);
    expect(一度.A[1].受けた).toBeUndefined();
  });
});
