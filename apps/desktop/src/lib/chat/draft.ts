/**
 * **部屋ごとの下書き**（2026-10-23）。
 *
 * 打ち込み欄は 1 つなので、部屋を替えても打ちかけの文がそのまま残っていた。
 * ASUS の部屋に書きかけた文が、開発の部屋の欄に出る。**人は「どの部屋に向けて書いたか」を
 * 欄の見た目から読めない**ので、そのまま送ると別の部屋へ流れる。
 *
 * 部屋を替えるとき、いまの下書きを前の部屋の分として控え、新しい部屋の分を欄に出す。
 * 控えは画面の中だけ（立て直すと消える。下書きは秘密になりうるので、どこにも書かない）。
 */

/** 部屋の鍵 → 打ちかけの文。 */
export type 下書きの控え = Readonly<Record<string, string>>;

/** 部屋が無いとき（誰も選んでいない）の控え先。 */
const 部屋なし = '';

function 鍵にする(部屋: string | null): string {
  return 部屋 ?? 部屋なし;
}

/**
 * 部屋を替える。**いまの下書きは前の部屋に控え、新しい部屋の分を返す。**
 *
 * 空の下書きは控えない（控えを膨らませない）。同じ部屋なら何も変えない。
 */
export function 部屋を替える(
  控え: 下書きの控え,
  前の部屋: string | null,
  新しい部屋: string | null,
  いまの下書き: string,
): { 控え: 下書きの控え; 下書き: string } {
  if (前の部屋 === 新しい部屋) return { 控え, 下書き: いまの下書き };
  const 次: Record<string, string> = { ...控え };
  const 前 = 鍵にする(前の部屋);
  if (いまの下書き.trim() === '') {
    delete 次[前];
  } else {
    次[前] = いまの下書き;
  }
  const 新 = 鍵にする(新しい部屋);
  const 下書き = 次[新] ?? '';
  // 欄へ出した分は控えから外す（送ったあとに古い文が戻らないように）
  delete 次[新];
  return { 控え: 次, 下書き };
}
