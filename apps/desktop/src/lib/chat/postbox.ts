// 相手が起動していないときに、打ったものをどうするか。
//
// **これが LINE との本当の差だった**（オーナー・2026-09-07
// 「プッシュできないと、LINE の連絡みたいに。そうじゃないとチャットとしてはあまり機能しない」）。
// 割符はサーバーを 1 台も立てないので、**相手が起動していなければ消えていた。**
//
// **預かり所は任意である**（`docs/relay.md`）。置いていなければ、
// 打った人には「いま居ません」と**理由まで**出す —— 黙って捨てない。

import { いま時刻, type 会話行 } from '$lib/meeting/announce';
import { 机の印, 部屋の印 } from '$lib/contacts/list';

/** どこへ送るかを決めるのに要るもの。 */
export interface 送り先の素材 {
  /** 机の席（`desk:`）から決まった宛先。決まっていなければ `null`。 */
  宛先: string | null;
  /** 連絡帳でいま選んでいる行の key。 */
  選んでいる: string | null;
  /** その人が、いま同じ部屋に居るか。 */
  その人は部屋に居る: boolean;
  /** 預かり所を置いているか。 */
  預かり所がある: boolean;
}

/** 打ったものの行き先。 */
export type 送り方 =
  | { 種類: '机'; 宛先: string }
  | { 種類: '部屋' }
  | { 種類: '預ける'; key: string }
  /** 送れない。`訳` は文言の鍵。 */
  | { 種類: '送れない'; 訳: string };

/**
 * 打ったものが、どこへ行くか。
 *
 * **相手が居ないことと、預かり所が無いことを混ぜない。**
 * 預かり所があれば預けられるし、無ければ「いま居ません」で終わる。
 */
export function どう送るか(素材: 送り先の素材): 送り方 {
  if (素材.宛先) return { 種類: '机', 宛先: 素材.宛先 };

  const 選 = 素材.選んでいる;
  // 誰も選んでいない／机の行／部屋の行は、いまの部屋へ（これまでどおり）
  if (!選 || 選.startsWith(机の印) || 選.startsWith(部屋の印)) return { 種類: '部屋' };

  // 同じ部屋に居るなら、もう繋がっている。**預かり所を通す理由が無い**
  if (素材.その人は部屋に居る) return { 種類: '部屋' };

  if (素材.預かり所がある) return { 種類: '預ける', key: 選 };
  return { 種類: '送れない', 訳: 'send.absent' };
}

/**
 * 留守中に届いた分を、会話の 1 行にする。
 *
 * **いま届いたように見せない。**3 日前の言葉が、たったいま言われたように読める。
 * 時刻は**出した側の時計**である（`warifu-postbox` の手紙が持っている）。
 */
export function 留守中の行(who: string, body: string, 秒: number): 会話行 {
  return { who, body, mine: false, at: いま時刻(new Date(秒 * 1000)), 留守中: true };
}
