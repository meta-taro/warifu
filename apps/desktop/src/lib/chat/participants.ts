// **この部屋に誰が居るか**（0.1.38）。
//
// 見出しは「（2 人）」と数だけを出していて、**その 2 人が誰か**は画面のどこにも無かった。
// 届く先（`Reach.svelte`）は文字が届く相手の機械だけで、自分も、相手の機械に乗っている
// エージェントも出ない。数と、見えている顔が合わなかった。
//
// 機械（公開鍵）ごとに 1 行。その下に、その機械のエージェントを添える ——
// 自分の機械は机の席、相手の機械は**この部屋で話した**名札から拾う
// （相手の機械のエージェントの一覧は線に載っていないので、話した分しか分からない）。

import type { 会話行 } from '$lib/meeting/announce';
import { 今のエージェントの札, type 場所の帳 } from './name';

export interface 参加者 {
  /** 機械の公開鍵（全桁）。 */
  key: string;
  主催: boolean;
  自分: boolean;
  /** その機械のエージェントの名札。 */
  エージェントたち: string[];
}

/** その機械のエージェントを、今の名札で 1 人ずつ（名乗り直した前の名札は出さない・#6）。 */
function 話したエージェント(会話: readonly 会話行[], 鍵: string, 帳: 場所の帳): string[] {
  const 拾った: string[] = [];
  for (const { 頭, 札 } of 今のエージェントの札(会話, 帳)) {
    if (鍵.startsWith(頭) && !拾った.includes(札)) 拾った.push(札);
  }
  return 拾った;
}

/**
 * 部屋の名簿（自分を含む）から、出す順に並べる。主催 → 自分 → 名簿の順。
 */
export function 参加者を並べる(
  名簿: readonly string[],
  主催の鍵: string | null,
  自分の鍵: string | null,
  この機械のエージェント: readonly string[],
  会話: readonly 会話行[],
  帳: 場所の帳 = {},
): 参加者[] {
  const 並び = 名簿.map(
    (key): 参加者 => ({
      key,
      主催: key === 主催の鍵,
      自分: key === 自分の鍵,
      エージェントたち: key === 自分の鍵 ? [...この機械のエージェント] : 話したエージェント(会話, key, 帳),
    }),
  );
  const 順 = (p: 参加者) => (p.主催 ? 0 : p.自分 ? 1 : 2);
  // `sort` は安定なので、同じ順位は名簿の順のまま
  return 並び.sort((a, b) => 順(a) - 順(b));
}
