import { describe, expect, it } from 'vitest';

import { 届きを見る, 打てない訳 } from './delivery';

describe('打った行が、どこまで行ったか', () => {
  it('席へ送ったなら、渡した', () => {
    expect(届きを見る({ 種類: '机', 宛先: 'zumen' }, 0).届き).toBe('渡した');
  });

  it('部屋に人が居れば、渡した', () => {
    expect(届きを見る({ 種類: '部屋' }, 2).届き).toBe('渡した');
  });

  it('誰も居ない部屋へ打ったなら、渡っていない', () => {
    // **「送信しました」と書かない。**誰にも渡っていない
    const 札 = 届きを見る({ 種類: '部屋' }, 0);
    expect(札.届き).toBe('届かない');
    expect(札.札).toBe('mark.none');
  });

  it('預けたなら、預けた（届いたとは書かない）', () => {
    // **相手にはまだ届いていない**（次に起動したときに届く・D71）
    const 札 = 届きを見る({ 種類: '預ける', key: 'K' }, 0);
    expect(札.届き).toBe('預けた');
    expect(札.札).toBe('mark.kept');
  });

  it('送れないなら、届かない', () => {
    expect(届きを見る({ 種類: '送れない', 訳: 'send.absent' }, 0).届き).toBe('届かない');
  });

  it('どの札にも、説明の鍵が付く', () => {
    // **読んだかどうかは分からない**、をどの札でも読めるようにする
    for (const 送り方 of [
      { 種類: '机', 宛先: 'z' } as const,
      { 種類: '部屋' } as const,
      { 種類: '預ける', key: 'K' } as const,
      { 種類: '送れない', 訳: 'send.absent' } as const,
    ]) {
      expect(届きを見る(送り方, 1).訳).toBeTruthy();
    }
  });
});

describe('打てないときの訳', () => {
  it('席が切れているなら、その席の話をする', () => {
    // **ルームの話をしない**（オーナー・2026-09-10 に実物で出た）——
    // 相手は繋がっていないエージェントなのに「鍵を渡して、入ってもらうと送れます」
    // と出ていた
    expect(打てない訳({ 種類: '机', 宛先: 'zumen' }, { 席が着いている: false, 届く先の数: 0 })).toBe(
      'act.chat.desk.none',
    );
  });

  it('席が着いているなら、打てる（訳は無い）', () => {
    expect(打てない訳({ 種類: '机', 宛先: 'zumen' }, { 席が着いている: true, 届く先の数: 0 })).toBeNull();
  });

  it('預かり所へ預けられるなら、打てる', () => {
    expect(打てない訳({ 種類: '預ける', key: 'K' }, { 席が着いている: false, 届く先の数: 0 })).toBeNull();
  });

  it('送れないなら、その訳をそのまま返す', () => {
    expect(
      打てない訳({ 種類: '送れない', 訳: 'send.absent' }, { 席が着いている: false, 届く先の数: 0 }),
    ).toBe('send.absent');
  });

  it('ルームに誰も入っていないなら、ルームの話をする', () => {
    expect(打てない訳({ 種類: '部屋' }, { 席が着いている: false, 届く先の数: 0 })).toBe('chat.nobody');
    expect(打てない訳({ 種類: '部屋' }, { 席が着いている: false, 届く先の数: 2 })).toBeNull();
  });
});
