import { describe, expect, it } from 'vitest';

import { 塊に分ける, 字に分ける } from './markdown';

describe('塊に分ける', () => {
  it('ふつうの文は、打った改行ごと 1 つの段落', () => {
    // マークダウンの無い発言の見え方を変えない
    expect(塊に分ける('1 行目\n2 行目')).toEqual([{ 種: '段', 字: [{ 種: '文', 文: '1 行目\n2 行目' }] }]);
  });

  it('空の行で段落を分ける', () => {
    expect(塊に分ける('上\n\n下').map((b) => b.種)).toEqual(['段', '段']);
  });

  it('見出し・罫・符の囲い', () => {
    const 塊 = 塊に分ける('## 題\n---\n```text\na | b\n**c**\n```\n後');
    expect(塊.map((b) => b.種)).toEqual(['見出し', '罫', '符', '段']);
    expect(塊[0]).toMatchObject({ 深さ: 2 });
    // 囲いの中は読まない（表にも太字にもしない）
    expect(塊[2]).toEqual({ 種: '符', 文: 'a | b\n**c**' });
  });

  it('閉じていない囲いは、最後まで符', () => {
    expect(塊に分ける('```\nx\ny')).toEqual([{ 種: '符', 文: 'x\ny' }]);
  });

  it('表は頭・区切り・体', () => {
    const [表] = 塊に分ける('| 問い | 場所 |\n|---|---|\n| 仕様 | 試験書 |\n| 旧版 | `src` |');
    expect(表.種).toBe('表');
    if (表.種 !== '表') return;
    expect(表.頭.map((升) => 升[0].文)).toEqual(['問い', '場所']);
    expect(表.体).toHaveLength(2);
    expect(表.体[1][1]).toEqual([{ 種: '符', 文: 'src' }]);
  });

  it('区切りの無い | は表にしない', () => {
    expect(塊に分ける('a | b\nc | d')[0].種).toBe('段');
  });

  it('箇条書きは深さと印を持つ', () => {
    const [箇条] = 塊に分ける('- 一\n  - 二\n- 三');
    expect(箇条).toMatchObject({ 種: '箇条', 番号つき: false });
    if (箇条.種 !== '箇条') return;
    expect(箇条.項.map((項) => [項.深さ, 項.字[0].文])).toEqual([
      [0, '一'],
      [1, '二'],
      [0, '三'],
    ]);
  });

  it('番号の箇条書きは、書かれた番号のまま', () => {
    const [箇条] = 塊に分ける('1. 一\n2. 二');
    expect(箇条).toMatchObject({ 種: '箇条', 番号つき: true });
    if (箇条.種 === '箇条') expect(箇条.項.map((項) => 項.印)).toEqual(['1.', '2.']);
  });

  it('引用の中も読む', () => {
    const [引] = 塊に分ける('> **叩き**。\n> 続き');
    expect(引.種).toBe('引用');
    if (引.種 === '引用') expect(引.中[0]).toMatchObject({ 種: '段' });
  });

  it('段落の途中に箇条が来たら、そこで分ける', () => {
    expect(塊に分ける('前置き\n- 一').map((b) => b.種)).toEqual(['段', '箇条']);
  });

  it('# のすぐ後に字が続くもの（#729 など）は見出しにしない', () => {
    expect(塊に分ける('#729 を見て')[0].種).toBe('段');
  });
});

describe('字に分ける', () => {
  it('太字・符・繋ぎ', () => {
    expect(字に分ける('a **b** `c` [d](https://x.example)')).toEqual([
      { 種: '文', 文: 'a ' },
      { 種: '太', 文: 'b' },
      { 種: '文', 文: ' ' },
      { 種: '符', 文: 'c' },
      { 種: '文', 文: ' ' },
      { 種: '繋', 文: 'd', 先: 'https://x.example' },
    ]);
  });

  it('タグはただの字のまま', () => {
    // HTML にしないので、届いた文で画面を書き換えられない
    expect(字に分ける('<img src=x onerror=alert(1)>')).toEqual([
      { 種: '文', 文: '<img src=x onerror=alert(1)>' },
    ]);
  });

  it('符の中の ** は太字にしない', () => {
    expect(字に分ける('`**x**`')).toEqual([{ 種: '符', 文: '**x**' }]);
  });
});

describe('日本語の書き方（0.1.45）', () => {
  it('「・」「•」で始まる行は箇条書き（後ろに空白が無くても）', () => {
    const 塊 = 塊に分ける('対応しました\n・原因：検索が重い\n・対策：表を分けた\n• 確認済み');
    expect(塊.map((b) => b.種)).toEqual(['段', '箇条']);
    const 箇条 = 塊[1];
    if (箇条.種 !== '箇条') throw new Error('箇条でない');
    expect(箇条.番号つき).toBe(false);
    expect(箇条.項.map((p) => p.字)).toEqual([
      [{ 種: '文', 文: '原因：検索が重い' }],
      [{ 種: '文', 文: '対策：表を分けた' }],
      [{ 種: '文', 文: '確認済み' }]
    ]);
  });
  it('行の途中の「・」は箇条にしない', () => {
    expect(塊に分ける('A・B・C の 3 つ').map((b) => b.種)).toEqual(['段']);
  });
  it('【見出し】は太字にする（括弧は残す）', () => {
    expect(字に分ける('【障害報告】13:00 に止まった')).toEqual([
      { 種: '太', 文: '【障害報告】' },
      { 種: '文', 文: '13:00 に止まった' }
    ]);
  });
});
