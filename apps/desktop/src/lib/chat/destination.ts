//   「連絡帳で対話できつつルームがある点。**ここらへんが現状人は混乱します。**
//     ビデオ会議なのか、グループチャットなのか。」
//
// **判断（`postbox.ts` の `どう送るか`）は正しい。**変えない。
// **見えないことだけを直す** —— 決まった宛先を、会話欄のいちばん上で名乗る。
//
// ここは純ロジック。**文言は持たない**（鍵と置き換えの値だけを返す）。

import type { 送り方 } from './postbox';

/** 見出しを組むのに要るもの。**どれも画面が既に持っている値である。** */
export interface 見出しの素材 {
  /** 見ているルームに付けた名前。付いていなければ `null`。 */
  ルーム名: string | null;
  /**
   * そのルームに居る人数（**自分を含む**）。
   *
   * `rooms`（Rust）が**ルームごとに**返している値をそのまま使う。
   * 画面で数え直さない —— **数え方が 2 つあると、必ず食い違う。**
   */
  人数: number;
  /** 相手 1 人へ送るときの呼び名。覚えていなければ鍵の頭（画面が決める）。 */
  相手の呼び名: string | null;
  /** 名前の無いルームを「ルーム n」と呼ぶときの n。 */
  何番目?: number;
}

/** 画面へ渡す見出し。**文言そのものは i18n が持つ。** */
export interface 見出し {
  鍵: string;
  値?: Record<string, string | number>;
  /** 送れないときの理由（文言の鍵）。**言い換えずにそのまま運ぶ。** */
  訳?: string;
}

/**
 * いまの送り方から、会話欄の見出しを決める。
 *
 * **「へ」と言えるのは、届く先があるときだけ。**
 * 自分しか居ないルームで「〇〇へ」と出すと、**届いたように読める**（原則 7）。
 */
export function 宛先の見出し(送り方: 送り方, 素材: 見出しの素材): 見出し {
  switch (送り方.種類) {
    case 'この機械':
      return { 鍵: 'chat.to.desk', 値: { name: 素材.相手の呼び名 ?? 送り方.宛先 } };

    case '預ける':
      // **ルームと混ぜない。**預けるのは「その人だけ」への 1 通である
      return { 鍵: 'chat.to.sealed', 値: { name: 素材.相手の呼び名 ?? 送り方.key } };

    case '送れない':
      return { 鍵: 'chat.to.none', 訳: 送り方.訳 };

    case 'ルーム': {
      // **自分だけなら、宛先を名乗らない。**呼ぶ導線は画面が別に出す
      if (素材.人数 <= 1) return { 鍵: 'chat.to.alone' };
      if (素材.ルーム名) return { 鍵: 'chat.to.room', 値: { name: 素材.ルーム名, n: 素材.人数 } };
      return { 鍵: 'chat.to.room.nth', 値: { n: 素材.人数, nth: 素材.何番目 ?? 1 } };
    }
  }
}
