// **画面の写し**（0.1.34）。エージェントの `app_view` に返す文字を書く。
//
// 本体の知っていること（`room_status`）と、人の画面に出ていることは食い違うことがある ——
// 10-22、届いた文字が別のルームの欄に積まれていた。**人が見ているものを、そのまま字にする。**
// 席どうしで見比べるので、並びと書き方は毎回同じにする。

import type { 会話行 } from '$lib/meeting/announce';
import { 行の差出人名 } from './name';

/** 写しの 1 ルーム分。 */
export interface 写しのルーム {
  名前: string;
  /** 人数（自分を含む）。分からなければ `null`。 */
  人数: number | null;
  行たち: readonly 会話行[];
}

/**
 * 写しの［メール］の欄（11-10）。**本文・差出人・件名は持たない** —— 人が見ている欄の様子だけ。
 * Windows の通しの試験で、画面の受信箱に出ているかを人の目に頼らずに確かめるため。
 */
export interface 写しのメール {
  /** いま［メール］の面を開いているか。 */
  開いている: boolean;
  口たち: readonly { user: string; kind: string; 秘密がある: boolean }[];
  /** 受信箱に並んでいる通数。まだ読めていなければ `null`。 */
  件数: number | null;
  /** 欄に出ている知らせ・失敗の文言。 */
  文言: readonly string[];
}

/** 写しに要るもの。 */
export interface 写しの素材 {
  版: string;
  /** 題字（窓の上に出ている文字）。 */
  題字: string;
  /** 上に出ている知らせ。無ければ `null`。 */
  知らせ: string | null;
  /** 左で選んでいるもの（エージェントなど）。ルームを見ていれば `null`。 */
  選んでいる: string | null;
  /** 開いているルーム。無ければ `null`。 */
  見ている: (写しのルーム & { 見出し: string; 届く先: readonly string[] }) | null;
  /** ほかのルーム。 */
  ほか: readonly 写しのルーム[];
  /** ［メール］の欄。まだ一度も開いていなければ省く。 */
  メール?: 写しのメール | null;
  /** 画面での名簿（鍵 → 名）。**差出人を会話の欄と同じ名で書く**ために使う。省けば行の `who`。 */
  名簿?: Readonly<Record<string, string>>;
  /** 名前の無い人の呼び方（「名無しさん」）。 */
  名無し?: string;
  /**
   * **打つ欄**（11-12）。欄の名前と字数だけ。**中身は書かない**（人の下書きに秘密が入りうる）。
   * エージェントがカーソルで打つ欄を当てるのと、打った字が残っていないかを確かめるのに使う
   */
  打つ欄?: { 名: string; 字数: number } | null;
  /**
   * **いま持っている通話の数と、その相手の数**（11-12）。通話は相手ごとに 1 つのはずで、
   * 多ければ閉じ忘れ（UDP の口が溜まる）。網が途切れる原因を確かめるために出す
   */
  通話?: { 数: number; 相手の数: number } | null;
}

function メールを書く(m: 写しのメール): string[] {
  const 文 = [`メール（${m.開いている ? '開いている' : '開いていない'}）`];
  const 口 = m.口たち.map((c) => `${c.user}（${c.kind}・秘密 ${c.秘密がある ? '入っている' : 'まだ'}）`);
  文.push(`控えた口 ${m.口たち.length} 件${口.length ? `: ${口.join('、')}` : ''}`);
  文.push(`受信箱 ${m.件数 === null ? 'まだ読めていない' : `${m.件数} 通`}`);
  for (const 一つ of m.文言) 文.push(`文言 ${一つ}`);
  return 文;
}

/** 写しの上限（バイト）。本体の `写しの上限` と同じ。 */
export const 写しの上限 = 3500;

const バイト数 = (文: string) => new TextEncoder().encode(文).length;

function 行を書く(
  行: 会話行,
  本文の字数: number,
  名簿?: 写しの素材['名簿'],
  名無し?: string,
  同じ部屋の行: readonly 会話行[] = [],
): string {
  const 本文 = 行.画像 ? '［画像］' : 行.body.replace(/\s+/g, ' ').trim();
  const 詰めた = 本文.length > 本文の字数 ? `${本文.slice(0, 本文の字数)}…` : 本文;
  if (行.system) return `  ${行.at ?? ''} （${詰めた}）`;
  // **会話の欄と同じ引き方**（11-11）。`who` は届いた瞬間の名で、相手の機械のエージェントでは名無しさんになっていた
  const 誰 = 行.mine ? '自分' : 名簿 ? 行の差出人名(行, 名簿, 名無し) : 行.who;
  // **返信なら、元の発言の差出人と頭を添える**（11-12・欄の添えと同じもの）
  const 添え = 行.返信先 ? 返信の添え(行.返信先, 同じ部屋の行, 名簿, 名無し) : '';
  return `  ${行.at ?? ''} ${誰}${添え}「${詰めた}」`;
}

function 返信の添え(
  先: string,
  同じ部屋の行: readonly 会話行[],
  名簿?: 写しの素材['名簿'],
  名無し?: string,
): string {
  const 元 = 同じ部屋の行.find((l) => l.印 === 先);
  if (!元) return '（↩ 前の発言への返信）';
  const 誰 = 元.mine ? '自分' : 名簿 ? 行の差出人名(元, 名簿, 名無し) : 元.who;
  const 一行 = 元.body.replace(/\s+/g, ' ').trim();
  const 頭 = 一行.length > 20 ? `${一行.slice(0, 20)}…` : 一行;
  return `（↩ ${誰}「${頭}」への返信）`;
}

function 書く(素材: 写しの素材, 見る行数: number, ほかの行数: number, 本文の字数: number): string {
  const 文: string[] = [`版 ${素材.版}`, `題字 ${素材.題字 || 'なし'}`];
  if (素材.通話) 文.push(`通話 ${素材.通話.数} 本（相手 ${素材.通話.相手の数} 人）`);
  if (素材.知らせ) 文.push(`知らせ ${素材.知らせ}`);
  if (素材.選んでいる) 文.push(`選んでいる ${素材.選んでいる}`);
  const 見る = 素材.見ている;
  if (見る) {
    文.push(`開いているルーム ${見る.名前}（${見る.人数 ?? '?'} 人）`);
    文.push(`見出し ${見る.見出し}`);
    文.push(`届く先 ${見る.届く先.join('・') || 'なし'}`);
    const 欄 = 素材.打つ欄;
    if (欄) 文.push(`打つ欄 「${欄.名}」（${欄.字数 > 0 ? `${欄.字数} 文字` : '空'}）`);
    const 行たち = 見る.行たち.slice(-見る行数);
    文.push(`チャット欄（最後の ${行たち.length} 行 / 全 ${見る.行たち.length} 行）`);
    for (const 行 of 行たち) 文.push(行を書く(行, 本文の字数, 素材.名簿, 素材.名無し, 見る.行たち));
  } else {
    文.push('開いているルーム なし');
  }
  for (const 部屋 of 素材.ほか) {
    const 行たち = 部屋.行たち.slice(-ほかの行数);
    文.push(`ほかのルーム ${部屋.名前}（${部屋.人数 ?? '?'} 人・全 ${部屋.行たち.length} 行）`);
    for (const 行 of 行たち) 文.push(行を書く(行, 本文の字数, 素材.名簿, 素材.名無し, 部屋.行たち));
  }
  if (素材.メール) 文.push(...メールを書く(素材.メール));
  return 文.join('\n');
}

/**
 * **写しを書く。**上限に収まるまで、行数と本文の長さを詰めていく。
 * 詰めても収まらなければ、本体が最後に切る。
 */
export function 画面の写しを書く(素材: 写しの素材): string {
  const 詰め方: readonly [number, number, number][] = [
    [20, 3, 80],
    [12, 2, 60],
    [8, 1, 40],
    [5, 0, 30],
  ];
  let 文 = '';
  for (const [見る, ほか, 字数] of 詰め方) {
    文 = 書く(素材, 見る, ほか, 字数);
    if (バイト数(文) <= 写しの上限) return 文;
  }
  return 文;
}
