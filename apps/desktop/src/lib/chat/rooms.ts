// ルームごとの会話。**混ぜない。**
//
// 会話が 1 本しか無いと、**相手ごとの会話に見えない** ——
// 「1 対 1 と 1 対 N がはっきりしない」（オーナー・2026-09-08）の本体である。
//
// **ルーム = 会議 ID。**割符では「1 対 1」は別の仕組みではなく、2 人のルームである。

import type { 会話行 } from '$lib/meeting/announce';

/** ルームごとの会話。**鍵はルームの id。** */
export type ルームの会話 = Readonly<Record<string, readonly 会話行[]>>;

/**
 * このPCの相手との会話に使う、画面の中だけのルームの名前。**ルーム id ではない。**
 *
 * **エージェントを渡すと、そのエージェントとの 1 対 1 になる**（**D86**・オーナー指示 2026-09-10
 * 「通常ここは、私めたたろと、zumen だけの 1 対 1 チャットでなければ
 * バグっていると思います」）。
 *
 * 渡さなければ、このPCぜんぶ（誰も選んでいないとき）。
 */
export const このPCのルーム = (エージェント?: string) => (エージェント ? `desk:${エージェント}` : 'desk');

/**
 * そのルームの会話を取り出す。**無ければ空。**
 *
 * **空を「まだ無い」と区別しない。**どちらも「何も無い」で同じである。
 */
export function そのルームの会話(会話: ルームの会話, ルーム: string | null): readonly 会話行[] {
  if (!ルーム) return [];
  return 会話[ルーム] ?? [];
}

/**
 * **このPCと、いま居るルームの両方へ積む。**
 *
 * **このPCとルームは、この PC から見れば同じ会話である**（画面にも
 * 「マイ PC エージェントは、はじめから同じルームに居ます」と出している）。
 * 片方にしか積まないと、**もう片方を見ている人には何も見えない** ——
 * 2026-09-08 の `issues/1`「ルームの画面にエージェントの発言が出ない」がこれである。
 *
 * > **人が置き去りになったことに、人が気づけません。**
 *
 * 預かり所ごしの 1 対 1（`contact:`）はここを通さない。**そこは本当に別の相手である。**
 */
export function このPCとルームへ足す(
  会話: ルームの会話,
  いまのルーム: string | null,
  行: 会話行,
): ルームの会話 {
  const 次 = 足す(会話, このPCのルーム(), 行);
  // **同じ行を 2 つの入れ物へ入れる。**どちらの入口から見ても同じ話が見える
  return いまのルーム ? 足す(次, いまのルーム, 行) : 次;
}

/**
 * **そのエージェントとの 1 対 1 に積む**（**D86**・オーナー指示 2026-09-10）。
 *
 * > 通常ここは、私めたたろと、zumen だけの 1 対 1 チャットでなければ
 * > バグっていると思います
 *
 * **入るのは 2 種類だけ** —— 自分がそのエージェントへ送った行と、そのエージェントが言った行。
 *
 * **ほかのエージェントの行も、ルームの行も入れない。**
 * 「そのエージェントが見ているもの」にすると、**zumen の欄に git-qa の行が並ぶ**
 * （エージェントどうしは同じPCの会話を見ているので）。それは 1 対 1 ではない。
 */
export function エージェントへ足す(会話: ルームの会話, エージェント: string, 行: 会話行): ルームの会話 {
  return 足す(会話, このPCのルーム(エージェント), 行);
}

/**
 * そのルームに 1 行足す。
 *
 * **他のルームを触らない。**触ると、見ていないルームの会話が壊れる。
 */
export function 足す(会話: ルームの会話, ルーム: string, 行: 会話行): ルームの会話 {
  return { ...会話, [ルーム]: [...(会話[ルーム] ?? []), 行] };
}

/**
 * そのルームを畳む（会話ごと捨てる）。
 *
 * **閉じれば消える。**履歴を持たないと決めてある（`issues/010`）。
 */
export function 畳む(会話: ルームの会話, ルーム: string): ルームの会話 {
  const 残り = { ...会話 };
  delete 残り[ルーム];
  return 残り;
}

/** その人との会話に使う、画面の中だけのルームの名前。**ルーム id ではない。** */
export const 人のルーム = (key: string) => `contact:${key}`;

/**
 * いま見るルームを決める。
 *
 * **選んだ相手が同じ PC の AI なら、このPCのルーム。**
 * **ルームに居ない人を選んだなら、その人との会話**（預かり所ごしの 1 対 1・D71）。
 * そうでなければ、いま居るルーム。
 */
export function 見るルーム(
  選んでいる: string | null,
  いまのルーム: string | null,
  その人はルームに居る = true,
): string | null {
  // **エージェントを選んだら、そのエージェントとの 1 対 1**（**D86**）。
  // このPCぜんぶを出していたので、**zumen を選んでも git-qa の行が並んでいた**
  if (選んでいる?.startsWith('desk:')) return このPCのルーム(選んでいる.slice('desk:'.length));
  // **ルームを選んだら、そのルーム。**見ていないルームも生きている
  if (選んでいる?.startsWith('room:')) return 選んでいる.slice('room:'.length);
  // **ルームに居ない人との会話を、ルームの会話と混ぜない。**
  // 混ぜると、留守中に届いた分が「いまのルームで言われたこと」として並ぶ
  if (選んでいる && !その人はルームに居る) return 人のルーム(選んでいる);
  return いまのルーム;
}
