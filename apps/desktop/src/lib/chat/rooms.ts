// 部屋ごとの会話。**混ぜない。**
//
// 会話が 1 本しか無いと、**相手ごとの会話に見えない** ——
// 「1 対 1 と 1 対 N がはっきりしない」（オーナー・2026-09-08）の本体である。
//
// **部屋 = 会議 ID。**割符では「1 対 1」は別の仕組みではなく、2 人の部屋である。

import type { 会話行 } from '$lib/meeting/announce';

/** 部屋ごとの会話。**鍵は部屋の id。** */
export type 部屋の会話 = Readonly<Record<string, readonly 会話行[]>>;

/**
 * 机の相手との会話に使う、画面の中だけの部屋の名前。**部屋 id ではない。**
 *
 * **席を渡すと、その席との 1 対 1 になる**（**D86**・オーナー指示 2026-09-10
 * 「通常ここは、私めたたろと、zumen だけの 1 対 1 チャットでなければ
 * バグっていると思います」）。
 *
 * 渡さなければ、机ぜんぶ（誰も選んでいないとき）。
 */
export const 机の部屋 = (席?: string) => (席 ? `desk:${席}` : 'desk');

/**
 * その部屋の会話を取り出す。**無ければ空。**
 *
 * **空を「まだ無い」と区別しない。**どちらも「何も無い」で同じである。
 */
export function その部屋の会話(会話: 部屋の会話, 部屋: string | null): readonly 会話行[] {
  if (!部屋) return [];
  return 会話[部屋] ?? [];
}

/**
 * **机と、いま居る部屋の両方へ積む。**
 *
 * **机と部屋は、この PC から見れば同じ会話である**（画面にも
 * 「マイ PC エージェントは、はじめから同じ部屋に居ます」と出している）。
 * 片方にしか積まないと、**もう片方を見ている人には何も見えない** ——
 * 2026-09-08 の `issues/1`「部屋の画面にエージェントの発言が出ない」がこれである。
 *
 * > **人が置き去りになったことに、人が気づけません。**
 *
 * 預かり所ごしの 1 対 1（`contact:`）はここを通さない。**そこは本当に別の相手である。**
 */
export function 机と部屋へ足す(
  会話: 部屋の会話,
  いまの部屋: string | null,
  行: 会話行,
): 部屋の会話 {
  const 次 = 足す(会話, 机の部屋(), 行);
  // **同じ行を 2 つの入れ物へ入れる。**どちらの入口から見ても同じ話が見える
  return いまの部屋 ? 足す(次, いまの部屋, 行) : 次;
}

/**
 * **その席との 1 対 1 に積む**（**D86**・オーナー指示 2026-09-10）。
 *
 * > 通常ここは、私めたたろと、zumen だけの 1 対 1 チャットでなければ
 * > バグっていると思います
 *
 * **入るのは 2 種類だけ** —— 自分がその席へ送った行と、その席が言った行。
 *
 * **ほかの席の行も、部屋の行も入れない。**
 * 「その席が見ているもの」にすると、**zumen の欄に git-qa の行が並ぶ**
 * （席どうしは同じ机の会話を見ているので）。それは 1 対 1 ではない。
 */
export function 席へ足す(会話: 部屋の会話, 席: string, 行: 会話行): 部屋の会話 {
  return 足す(会話, 机の部屋(席), 行);
}

/**
 * その部屋に 1 行足す。
 *
 * **他の部屋を触らない。**触ると、見ていない部屋の会話が壊れる。
 */
export function 足す(会話: 部屋の会話, 部屋: string, 行: 会話行): 部屋の会話 {
  return { ...会話, [部屋]: [...(会話[部屋] ?? []), 行] };
}

/**
 * その部屋を畳む（会話ごと捨てる）。
 *
 * **閉じれば消える。**履歴を持たないと決めてある（`issues/010`）。
 */
export function 畳む(会話: 部屋の会話, 部屋: string): 部屋の会話 {
  const 残り = { ...会話 };
  delete 残り[部屋];
  return 残り;
}

/** その人との会話に使う、画面の中だけの部屋の名前。**部屋 id ではない。** */
export const 人の部屋 = (key: string) => `contact:${key}`;

/**
 * いま見る部屋を決める。
 *
 * **選んだ相手が同じ PC の AI なら、机の部屋。**
 * **部屋に居ない人を選んだなら、その人との会話**（預かり所ごしの 1 対 1・D71）。
 * そうでなければ、いま居る部屋。
 */
export function 見る部屋(
  選んでいる: string | null,
  いまの部屋: string | null,
  その人は部屋に居る = true,
): string | null {
  // **席を選んだら、その席との 1 対 1**（**D86**）。
  // 机ぜんぶを出していたので、**zumen を選んでも git-qa の行が並んでいた**
  if (選んでいる?.startsWith('desk:')) return 机の部屋(選んでいる.slice('desk:'.length));
  // **部屋を選んだら、その部屋。**見ていない部屋も生きている
  if (選んでいる?.startsWith('room:')) return 選んでいる.slice('room:'.length);
  // **部屋に居ない人との会話を、部屋の会話と混ぜない。**
  // 混ぜると、留守中に届いた分が「いまの部屋で言われたこと」として並ぶ
  if (選んでいる && !その人は部屋に居る) return 人の部屋(選んでいる);
  return いまの部屋;
}
