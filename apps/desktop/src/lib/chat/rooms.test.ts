import { describe, expect, it } from 'vitest';

import {
  そのルームの会話,
  この機械とルームへ足す,
  エージェントへ足す,
  足す,
  畳む,
  見るルーム,
  この機械のルーム,
  入退室を書く部屋,
  type ルームの会話,
} from './rooms';
import type { 会話行 } from '$lib/meeting/announce';

const 行 = (body: string): 会話行 => ({ who: '自分', body, mine: true });

describe('ルームごとの会話', () => {
  it('ルームを分けて持てる', () => {
    // **混ぜると、相手ごとの会話に見えない**（2026-09-08）
    let 会話: ルームの会話 = {};
    会話 = 足す(会話, 'A', 行('Aへ'));
    会話 = 足す(会話, 'B', 行('Bへ'));
    expect(そのルームの会話(会話, 'A').map((r) => r.body)).toEqual(['Aへ']);
    expect(そのルームの会話(会話, 'B').map((r) => r.body)).toEqual(['Bへ']);
  });

  it('足しても、他のルームを触らない', () => {
    // **見ていないルームの会話が壊れないこと**
    let 会話: ルームの会話 = 足す({}, 'A', 行('1'));
    const 前 = そのルームの会話(会話, 'A');
    会話 = 足す(会話, 'B', 行('2'));
    expect(そのルームの会話(会話, 'A')).toEqual(前);
  });

  it('知らないルームは空', () => {
    // **空を「まだ無い」と区別しない**
    expect(そのルームの会話({}, 'どこか')).toEqual([]);
  });

  it('ルームを選んでいなければ空', () => {
    expect(そのルームの会話(足す({}, 'A', 行('x')), null)).toEqual([]);
  });

  it('畳むと会話ごと消える', () => {
    // **閉じれば消える**（履歴は持たない・issues/010）
    const 会話 = 畳む(足す({}, 'A', 行('x')), 'A');
    expect(そのルームの会話(会話, 'A')).toEqual([]);
  });

  it('畳んでも、他のルームは残る', () => {
    let 会話: ルームの会話 = 足す({}, 'A', 行('a'));
    会話 = 足す(会話, 'B', 行('b'));
    会話 = 畳む(会話, 'A');
    expect(そのルームの会話(会話, 'B').map((r) => r.body)).toEqual(['b']);
  });
});

describe('いま見るルーム', () => {
  it('エージェントを選んだら、そのエージェントとの 1 対 1', () => {
    // **この機械ぜんぶではない**（**D86**）—— alpha を選んで beta の行が並ぶのはバグ
    expect(見るルーム('desk:alpha のエージェント', 'ROOM1')).toBe(
      この機械のルーム('alpha のエージェント'),
    );
    expect(見るルーム('desk:beta のエージェント', 'ROOM1')).not.toBe(
      この機械のルーム('alpha のエージェント'),
    );
  });

  it('AI を選んでいなければ、いま居るルーム', () => {
    expect(見るルーム(null, 'ROOM1')).toBe('ROOM1');
    expect(見るルーム('BBBBBBBB', 'ROOM1')).toBe('ROOM1');
  });

  it('ルームにも居らず AI も選んでいなければ、どこも見ていない', () => {
    expect(見るルーム(null, null)).toBeNull();
  });
});

describe('ルームを選ぶ', () => {
  it('ルームを選んだら、そのルームを見る', () => {
    // **見ていないルームも生きている。**選び直すだけで経路は切れない
    expect(見るルーム('room:ROOM2', 'ROOM1')).toBe('ROOM2');
  });

  it('AI を選ぶほうが優先される（この機械はルームではない）', () => {
    expect(見るルーム('desk:alpha の AI', 'ROOM1')).toBe(この機械のルーム('alpha の AI'));
  });
});

describe('ルームに居ない人を選んだとき', () => {
  it('その人との会話を見る（預かり所ごしの 1 対 1）', () => {
    expect(見るルーム('ABC', 'room-1', false)).toBe('contact:ABC');
  });

  it('同じルームに居るなら、ルームの会話を見る', () => {
    expect(見るルーム('ABC', 'room-1', true)).toBe('room-1');
  });

  it('留守中に届いた分を、ルームの会話に混ぜない', () => {
    // 混ぜると「いまのルームで言われたこと」として並ぶ
    expect(見るルーム('ABC', null, false)).not.toBe(null);
    expect(見るルーム(null, 'room-1')).toBe('room-1');
  });
});

describe('この機械とルームの両方へ積む（issues/1）', () => {
  it('どちらの入口から見ても、同じ話が見える', () => {
    // **片方にしか積まないと、もう片方を見ている人には何も見えない**
    let 会話: ルームの会話 = {};
    会話 = この機械とルームへ足す(会話, 'room-1', 行('alpha です'));
    expect(そのルームの会話(会話, この機械のルーム()).map((l) => l.body)).toEqual(['alpha です']);
    expect(そのルームの会話(会話, 'room-1').map((l) => l.body)).toEqual(['alpha です']);
  });

  it('ルームがまだ無ければ、この機械だけに積む', () => {
    let 会話: ルームの会話 = {};
    会話 = この機械とルームへ足す(会話, null, 行('ルームはまだ無い'));
    expect(そのルームの会話(会話, この機械のルーム()).length).toBe(1);
  });

  it('相手ごとの会話（預かり所ごし）には積まない', () => {
    // **そこは本当に別の相手である**
    let 会話: ルームの会話 = {};
    会話 = この機械とルームへ足す(会話, 'room-1', 行('みんなへ'));
    expect(そのルームの会話(会話, 'contact:ABC').length).toBe(0);
  });

  it('順番が崩れない', () => {
    let 会話: ルームの会話 = {};
    会話 = この機械とルームへ足す(会話, 'room-1', 行('1 つ目'));
    会話 = この機械とルームへ足す(会話, 'room-1', 行('2 つ目'));
    expect(そのルームの会話(会話, 'room-1').map((l) => l.body)).toEqual(['1 つ目', '2 つ目']);
    expect(そのルームの会話(会話, この機械のルーム()).map((l) => l.body)).toEqual(['1 つ目', '2 つ目']);
  });
});

describe('エージェントごとの 1 対 1（D86）', () => {
  it('エージェントを選んで打った行は、そのエージェントにしか出ない', () => {
    // **届いていない所に出すのは嘘である**
    let 会話: ルームの会話 = {};
    会話 = エージェントへ足す(会話, 'alpha のエージェント', 行('alpha だけに'));
    expect(そのルームの会話(会話, この機械のルーム('alpha のエージェント')).map((l) => l.body)).toEqual([
      'alpha だけに',
    ]);
    expect(そのルームの会話(会話, この機械のルーム('beta のエージェント')).length).toBe(0);
    expect(そのルームの会話(会話, この機械のルーム()).length).toBe(0);
    expect(そのルームの会話(会話, 'room-1').length).toBe(0);
  });

  it('全員宛の行は、エージェントごとの会話に入れない', () => {
    // **1 対 1 の欄に、全員へ言ったことは並べない。**
    // 「そのエージェントが見ているもの」にすると、**alpha の欄に beta の行が並ぶ**
    let 会話: ルームの会話 = {};
    会話 = この機械とルームへ足す(会話, 'room-1', 行('みんなへ'));
    expect(そのルームの会話(会話, この機械のルーム('alpha のエージェント')).length).toBe(0);
    expect(そのルームの会話(会話, この機械のルーム()).map((l) => l.body)).toEqual(['みんなへ']);
  });

  it('ほかのエージェントの行は混ざらない', () => {
    let 会話: ルームの会話 = {};
    会話 = エージェントへ足す(会話, 'alpha のエージェント', 行('alpha の話'));
    会話 = エージェントへ足す(会話, 'beta のエージェント', 行('beta の話'));
    expect(そのルームの会話(会話, この機械のルーム('alpha のエージェント')).map((l) => l.body)).toEqual([
      'alpha の話',
    ]);
  });
});

describe('入退室を書く部屋', () => {
  const 部屋たち = [
    { id: 'A', member_keys: ['私', '甲'] },
    { id: 'B', member_keys: ['私', '甲', '乙'] },
  ];

  it('機械が部屋を言ったら、その部屋だけに書く（見ている部屋ではない）', () => {
    // 10-23、別の部屋への入り直しが、見ている部屋に「入りました」と 10 分おきに並んだ
    expect(入退室を書く部屋(部屋たち, '甲', 'B', 'A')).toEqual(['B']);
  });

  it('部屋が分からない切断は、その相手が居た部屋すべてに書く', () => {
    expect(入退室を書く部屋(部屋たち, '甲', undefined, 'A')).toEqual(['A', 'B']);
    expect(入退室を書く部屋(部屋たち, '乙', undefined, 'A')).toEqual(['B']);
  });

  it('どの部屋にも居なかった相手は、見ている部屋に書く（消さない）', () => {
    expect(入退室を書く部屋(部屋たち, '丙', undefined, 'A')).toEqual(['A']);
    expect(入退室を書く部屋([], '丙', undefined, null)).toEqual([]);
  });
});
