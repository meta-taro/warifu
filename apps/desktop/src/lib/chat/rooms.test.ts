import { describe, expect, it } from 'vitest';

import {
  その部屋の会話,
  机と部屋へ足す,
  席へ足す,
  足す,
  畳む,
  見る部屋,
  机の部屋,
  type 部屋の会話,
} from './rooms';
import type { 会話行 } from '$lib/meeting/announce';

const 行 = (body: string): 会話行 => ({ who: '自分', body, mine: true });

describe('部屋ごとの会話', () => {
  it('部屋を分けて持てる', () => {
    // **混ぜると、相手ごとの会話に見えない**（2026-09-08 オーナー指摘）
    let 会話: 部屋の会話 = {};
    会話 = 足す(会話, 'A', 行('Aへ'));
    会話 = 足す(会話, 'B', 行('Bへ'));
    expect(その部屋の会話(会話, 'A').map((r) => r.body)).toEqual(['Aへ']);
    expect(その部屋の会話(会話, 'B').map((r) => r.body)).toEqual(['Bへ']);
  });

  it('足しても、他の部屋を触らない', () => {
    // **見ていない部屋の会話が壊れないこと**
    let 会話: 部屋の会話 = 足す({}, 'A', 行('1'));
    const 前 = その部屋の会話(会話, 'A');
    会話 = 足す(会話, 'B', 行('2'));
    expect(その部屋の会話(会話, 'A')).toEqual(前);
  });

  it('知らない部屋は空', () => {
    // **空を「まだ無い」と区別しない**
    expect(その部屋の会話({}, 'どこか')).toEqual([]);
  });

  it('部屋を選んでいなければ空', () => {
    expect(その部屋の会話(足す({}, 'A', 行('x')), null)).toEqual([]);
  });

  it('畳むと会話ごと消える', () => {
    // **閉じれば消える**（履歴は持たない・issues/010）
    const 会話 = 畳む(足す({}, 'A', 行('x')), 'A');
    expect(その部屋の会話(会話, 'A')).toEqual([]);
  });

  it('畳んでも、他の部屋は残る', () => {
    let 会話: 部屋の会話 = 足す({}, 'A', 行('a'));
    会話 = 足す(会話, 'B', 行('b'));
    会話 = 畳む(会話, 'A');
    expect(その部屋の会話(会話, 'B').map((r) => r.body)).toEqual(['b']);
  });
});

describe('いま見る部屋', () => {
  it('席を選んだら、その席との 1 対 1', () => {
    // **机ぜんぶではない**（**D86**）—— zumen を選んで git-qa の行が並ぶのはバグ
    expect(見る部屋('desk:zumen のエージェント', 'ROOM1')).toBe(
      机の部屋('zumen のエージェント'),
    );
    expect(見る部屋('desk:git-qa のエージェント', 'ROOM1')).not.toBe(
      机の部屋('zumen のエージェント'),
    );
  });

  it('AI を選んでいなければ、いま居る部屋', () => {
    expect(見る部屋(null, 'ROOM1')).toBe('ROOM1');
    expect(見る部屋('BBBBBBBB', 'ROOM1')).toBe('ROOM1');
  });

  it('部屋にも居らず AI も選んでいなければ、どこも見ていない', () => {
    expect(見る部屋(null, null)).toBeNull();
  });
});

describe('部屋を選ぶ', () => {
  it('部屋を選んだら、その部屋を見る', () => {
    // **見ていない部屋も生きている。**選び直すだけで経路は切れない
    expect(見る部屋('room:ROOM2', 'ROOM1')).toBe('ROOM2');
  });

  it('AI を選ぶほうが優先される（机は部屋ではない）', () => {
    expect(見る部屋('desk:zumen の AI', 'ROOM1')).toBe(机の部屋('zumen の AI'));
  });
});

describe('部屋に居ない人を選んだとき', () => {
  it('その人との会話を見る（預かり所ごしの 1 対 1）', () => {
    expect(見る部屋('ABC', 'room-1', false)).toBe('contact:ABC');
  });

  it('同じ部屋に居るなら、部屋の会話を見る', () => {
    expect(見る部屋('ABC', 'room-1', true)).toBe('room-1');
  });

  it('留守中に届いた分を、部屋の会話に混ぜない', () => {
    // 混ぜると「いまの部屋で言われたこと」として並ぶ
    expect(見る部屋('ABC', null, false)).not.toBe(null);
    expect(見る部屋(null, 'room-1')).toBe('room-1');
  });
});

describe('机と部屋の両方へ積む（issues/1）', () => {
  it('どちらの入口から見ても、同じ話が見える', () => {
    // **片方にしか積まないと、もう片方を見ている人には何も見えない**
    let 会話: 部屋の会話 = {};
    会話 = 机と部屋へ足す(会話, 'room-1', 行('zumen です'));
    expect(その部屋の会話(会話, 机の部屋()).map((l) => l.body)).toEqual(['zumen です']);
    expect(その部屋の会話(会話, 'room-1').map((l) => l.body)).toEqual(['zumen です']);
  });

  it('部屋がまだ無ければ、机だけに積む', () => {
    let 会話: 部屋の会話 = {};
    会話 = 机と部屋へ足す(会話, null, 行('部屋はまだ無い'));
    expect(その部屋の会話(会話, 机の部屋()).length).toBe(1);
  });

  it('相手ごとの会話（預かり所ごし）には積まない', () => {
    // **そこは本当に別の相手である**
    let 会話: 部屋の会話 = {};
    会話 = 机と部屋へ足す(会話, 'room-1', 行('みんなへ'));
    expect(その部屋の会話(会話, 'contact:ABC').length).toBe(0);
  });

  it('順番が崩れない', () => {
    let 会話: 部屋の会話 = {};
    会話 = 机と部屋へ足す(会話, 'room-1', 行('1 つ目'));
    会話 = 机と部屋へ足す(会話, 'room-1', 行('2 つ目'));
    expect(その部屋の会話(会話, 'room-1').map((l) => l.body)).toEqual(['1 つ目', '2 つ目']);
    expect(その部屋の会話(会話, 机の部屋()).map((l) => l.body)).toEqual(['1 つ目', '2 つ目']);
  });
});

describe('席ごとの 1 対 1（D86）', () => {
  it('席を選んで打った行は、その席にしか出ない', () => {
    // **届いていない所に出すのは嘘である**
    let 会話: 部屋の会話 = {};
    会話 = 席へ足す(会話, 'zumen のエージェント', 行('zumen だけに'));
    expect(その部屋の会話(会話, 机の部屋('zumen のエージェント')).map((l) => l.body)).toEqual([
      'zumen だけに',
    ]);
    expect(その部屋の会話(会話, 机の部屋('git-qa のエージェント')).length).toBe(0);
    expect(その部屋の会話(会話, 机の部屋()).length).toBe(0);
    expect(その部屋の会話(会話, 'room-1').length).toBe(0);
  });

  it('全員宛の行は、席ごとの会話に入れない', () => {
    // **1 対 1 の欄に、全員へ言ったことは並べない。**
    // 「その席が見ているもの」にすると、**zumen の欄に git-qa の行が並ぶ**
    let 会話: 部屋の会話 = {};
    会話 = 机と部屋へ足す(会話, 'room-1', 行('みんなへ'));
    expect(その部屋の会話(会話, 机の部屋('zumen のエージェント')).length).toBe(0);
    expect(その部屋の会話(会話, 机の部屋()).map((l) => l.body)).toEqual(['みんなへ']);
  });

  it('ほかの席の行は混ざらない', () => {
    let 会話: 部屋の会話 = {};
    会話 = 席へ足す(会話, 'zumen のエージェント', 行('zumen の話'));
    会話 = 席へ足す(会話, 'git-qa のエージェント', 行('git-qa の話'));
    expect(その部屋の会話(会話, 机の部屋('zumen のエージェント')).map((l) => l.body)).toEqual([
      'zumen の話',
    ]);
  });
});
