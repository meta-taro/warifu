// 打った 1 行が、**どこまで行ったか。**
//
// オーナーが挙げた行き止まりの 1 つ ——「相手が読んだかどうかが分からない」。
//
// **読んだかどうかは、いまの割符では分からない。**
// 真ん中の機械が無いので、既読を集める所が無い（相手が「読んだ」と言ってくれない限り、
// こちらには何も来ない）。**分からないものを「既読」と書かない**（DESIGN §2 原則 7）。
//
// **分かるのはここまで** ——
//
//   渡した  …… 相手の機械へ渡った（経路が生きていた）
//   預けた  …… 相手が留守だったので、預かり所へ封のまま置いた（**D71**）
//   届かない …… 経路も預かり所も無い。**打ったものはどこにも残っていない**
//
// この 3 つを、打った行のそばに出す。**「送信しました」と書かない。**

import type { 送り方 } from './postbox';

/** 打った行の届き方。**読んだかどうかではない。** */
export type 届き = '渡した' | '預けた' | '届かない';

/** 行に出す札（文言の鍵つき）。 */
export interface 届きの札 {
  届き: 届き;
  /** 短い札。 */
  札: string;
  /** 押したときに出す説明（**読んだかは分からない**と書く）。 */
  訳: string;
}

/**
 * その送り方だと、どこまで行ったか。
 *
 * `相手の数` は**そのとき経路が生きていた相手の数**である。
 * 0 なら、部屋へ送ったつもりでも**誰にも渡っていない。**
 */
export function 届きを見る(送り方: 送り方, 相手の数: number): 届きの札 {
  if (送り方.種類 === '預ける') {
    return { 届き: '預けた', 札: 'mark.kept', 訳: 'mark.kept.hint' };
  }
  if (送り方.種類 === '送れない') {
    return { 届き: '届かない', 札: 'mark.none', 訳: 'mark.none.hint' };
  }
  // 机（その席へ）と部屋（居る人へ）は、**経路が生きている相手に渡っている**
  if (送り方.種類 === '机') {
    return { 届き: '渡した', 札: 'mark.sent', 訳: 'mark.sent.hint' };
  }
  if (相手の数 > 0) {
    return { 届き: '渡した', 札: 'mark.sent', 訳: 'mark.sent.hint' };
  }
  // **誰も居ない部屋へ打った。**渡ってはいない
  return { 届き: '届かない', 札: 'mark.none', 訳: 'mark.none.hint' };
}

/** 打てるかを見るのに要るもの。 */
export interface いまの様子 {
  /** 机の席（`desk:`）を選んでいるとき、その席が着いているか。 */
  席が着いている: boolean;
  /** いま経路が生きている相手の数。 */
  届く先の数: number;
  /**
   * 机の席の行を選んでいるか。
   *
   * **切れている席は宛先が決まらない**ので、`送り方` は部屋あてになる。
   * それだけを見ると「ルームに誰も入っていません」と出てしまうが、
   * **人が見ているのは席の行である。**
   */
  席を選んでいる?: boolean;
}

/**
 * いま打てないなら、その訳（文言の鍵）。打てるなら `null`。
 *
 * **ルームの話を、席の話にすり替えない**（2026-09-10 に実物で出た）——
 * 繋がっていないエージェントを選んでいるのに
 * 「鍵を渡して、入ってもらうと送れます」と出ていた。**鍵の話ではない。**
 */
export function 打てない訳(送り方: 送り方, 様子: いまの様子): string | null {
  if (送り方.種類 === '送れない') return 送り方.訳;
  // 預かり所へなら、相手が留守でも置ける（D71）
  if (送り方.種類 === '預ける') return null;
  if (送り方.種類 === '机' || 様子.席を選んでいる) {
    return 様子.席が着いている ? null : 'act.chat.desk.none';
  }
  // 部屋へ打つなら、**誰か入っていないと渡らない**
  return 様子.届く先の数 > 0 ? null : 'chat.nobody';
}
