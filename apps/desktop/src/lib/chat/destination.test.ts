import { describe, expect, it } from 'vitest';
import { 宛先の見出し } from './destination';

describe('宛先の見出し', () => {
  it('名前の付いたルームは、名前と人数で呼ぶ', () => {
    expect(
      宛先の見出し({ 種類: 'ルーム' }, { ルーム名: 'そーたのへや', 人数: 3, 相手の呼び名: null }),
    ).toEqual({ 鍵: 'chat.to.room', 値: { name: 'そーたのへや', n: 3 } });
  });

  it('名前が無ければ、番号のルームとして呼ぶ', () => {
    expect(
      宛先の見出し({ 種類: 'ルーム' }, { ルーム名: null, 人数: 2, 相手の呼び名: null, 何番目: 1 }),
    ).toEqual({ 鍵: 'chat.to.room.nth', 値: { n: 2, nth: 1 } });
  });

  it('**人数を必ず出す。**「誰に届くか」は人数が要る', () => {
    const 出た = 宛先の見出し({ 種類: 'ルーム' }, { ルーム名: 'あ', 人数: 12, 相手の呼び名: null });
    expect(出た.値?.n).toBe(12);
  });

  it('**自分だけのルームでは「へ」と言わない。**届く先が無いのに宛先を名乗らない', () => {
    expect(
      宛先の見出し({ 種類: 'ルーム' }, { ルーム名: 'そーたのへや', 人数: 1, 相手の呼び名: null }),
    ).toEqual({ 鍵: 'chat.to.alone' });
  });

  it('この機械のエージェントへは、その 1 人だけへ', () => {
    expect(
      宛先の見出し(
        { 種類: 'この機械', 宛先: 'zumen' },
        { ルーム名: null, 人数: 3, 相手の呼び名: 'zumen のエージェント' },
      ),
    ).toEqual({ 鍵: 'chat.to.desk', 値: { name: 'zumen のエージェント' } });
  });

  it('**預けるときは「だけへ」と言い切る。**ルームと混ぜない', () => {
    expect(
      宛先の見出し(
        { 種類: '預ける', key: 'K1' },
        { ルーム名: 'そーたのへや', 人数: 3, 相手の呼び名: '田中' },
      ),
    ).toEqual({ 鍵: 'chat.to.sealed', 値: { name: '田中' } });
  });

  it('送れないときは、訳をそのまま持たせる（言い換えない）', () => {
    expect(
      宛先の見出し({ 種類: '送れない', 訳: 'send.absent' }, { ルーム名: null, 人数: 1, 相手の呼び名: null }),
    ).toEqual({ 鍵: 'chat.to.none', 訳: 'send.absent' });
  });

  it('呼び名が分からない相手でも、宛先は名乗る（鍵の頭で出る前提）', () => {
    expect(
      宛先の見出し({ 種類: '預ける', key: 'K1' }, { ルーム名: null, 人数: 1, 相手の呼び名: 'K5JEMQID…' }),
    ).toEqual({ 鍵: 'chat.to.sealed', 値: { name: 'K5JEMQID…' } });
  });
});
