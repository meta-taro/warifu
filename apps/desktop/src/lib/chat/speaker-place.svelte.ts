// **話し手の場所の帳**（0.1.52・#6）。相手の機械から届いた「名札 ↔ 起動した場所」を、画面ぜんたいで持つ。
// 参加者の欄と `@` の候補が同じ帳を読み、名乗り直したエージェントを 1 人にまとめる。

import { 場所の帳の鍵 } from './name';

export const 話し手の場所 = $state<{ 帳: Record<string, string> }>({ 帳: {} });

/** 届いた分を控える。同じ機械・同じ名札は上書き。 */
export function 場所を控える(機械の鍵: string, 札: string, 場所: string): void {
  話し手の場所.帳 = { ...話し手の場所.帳, [場所の帳の鍵(機械の鍵, 札)]: 場所 };
}
