// **まだ見ていない行の数**（オーナー判断 2026-09-11・案 A）。
//
// 「**未読？**」→「どんな機能かまだわからないので、問題点としてストックします」
// （2026-09-10）→ 案を出して **A（相手ごと）** を選んでもらった。
//
// # 相手ごとに数える
//
// LINE と同じ形にする。**説明が要らない**のがいちばんの理由である。
// 数えるのは「その会話で、まだ見ていない**相手の行**」——
//
// - **自分が打った行は数えない**（自分に未読は無い）
// - **知らせ（入退室・切断）は数えない** ——
//   「◯◯ が入りました」で赤い数字が付くと、**話しかけられたと勘違いする**
//
// # 「読んだ」は、この機械の中だけに持つ
//
// **相手へ既読を送らない。**送るには「読んだ」を相手の機械へ届ける経路が要り、
// **相手に何も押し付けない**という線（**D12** / **D31**）に触る。
// だから既読は出さない —— 出せるのは**自分がどこまで見たか**だけである。
//
// **会話は閉じると消える**（残していない）。だから印も持ち越さない ——
// 起動すると未読は 0 から数え直しになる。**それは嘘ではない**（会話も無いので）。

import type { 会話行 } from '$lib/meeting/announce';

/** 会話ごとの「どこまで見たか」（部屋の key → 行数）。 */
export type 見た印 = Readonly<Record<string, number>>;

/** その行を未読として数えるか。 */
function 数える行か(行: 会話行): boolean {
  // **自分の行と知らせは数えない**
  return !行.mine && !行.system;
}

/**
 * まだ見ていない相手の行の数。
 *
 * `見た` は「そこまで見た」という行数。**会話より大きくても負にしない**
 * （会話は閉じると消えるので、印だけが残ることがある）。
 */
export function 未読の数(会話: readonly 会話行[], 見た: number): number {
  const 始め = Math.max(0, Math.min(見た, 会話.length));
  return 会話.slice(始め).filter(数える行か).length;
}

/** その会話を「最後まで見た」ことにする印。 */
export function 見たことにする(会話: readonly 会話行[]): number {
  return 会話.length;
}

/**
 * いま見ている会話の印だけを進める。
 *
 * **見ていない会話を、勝手に見たことにしない。**
 * 元の印は壊さず、新しい物を返す。
 */
export function 見た印を進める(
  印: 見た印,
  いま見ている: string | null,
  会話: readonly 会話行[],
): 見た印 {
  if (!いま見ている) return 印;
  return { ...印, [いま見ている]: 見たことにする(会話) };
}

/**
 * 行数を直に渡して、その会話の印を置く。
 *
 * **画面側は「いま何行あるか」しか要らない** ——
 * 会話そのものを読むと、`$effect` が会話の中身にも反応して余計に回る。
 */
export function 見た印を置く(印: 見た印, 部屋: string, 行数: number): 見た印 {
  return { ...印, [部屋]: Math.max(0, 行数) };
}
