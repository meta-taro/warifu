// 打ったものが、**いま誰に届くか**。
//
// **「1 対 1 なのか、1 対 N なのか」は、最初に人が気にする所である**
// （オーナー・2026-09-07）。割符の会話は 1 本しか無いので、
// **1 対 1 も 1 対 N も同じ入れ物**である —— 違うのは**いま何人居るか**だけ。
//
// 言葉で「全員に届きます」と書くより、**届く先をそのまま並べる**ほうが早い。
// 1 人しか並ばなければ 1 対 1、3 人並べば 1 対 3 である。

/** 届く先を作るのに要るもの。 */
export interface 届く先の素材 {
  /** 会議に居る相手の呼び名（自分を含まない）。 */
  会議の相手: readonly string[];
  /**
   * **宛先**（同じ PC の AI 1 つ）。決まっていなければ `null`。
   *
   * 決まっているときは、**そこにだけ届く。**
   */
  宛先?: string | null;
  /**
   * いま机に着いている顔ぶれ（呼び方の並び）。
   *
   * **まとめて「マイ PC エージェント」1 つにしない。**1 台の PC で複数のエージェントが
   * 着くので、まとめると**どれに届くのか分からない**（2026-09-08）。
   */
  机のAIたち: readonly string[];
}

/**
 * いま打ったものが、**どこへ行くか**。
 *
 * **選んだ相手が同じ PC の AI なら、その 1 つにだけ渡す。**
 * 3 つも 4 つも机に着いていると、**zumen だけに聞きたくても全員に飛ぶ** ——
 * それでは 1 対 1 が成り立たない（2026-09-08 オーナー指摘
 * 「このPC上でやりとりが円滑にできない以上は別端末なんてもっとむずかしい」）。
 *
 * 部屋の相手（別の PC）は**選べない。**そちらは部屋に何人居るかで決まる
 * （`issues/015`）。
 */
export function 宛先を決める(選んでいる: string | null, 机のAIたち: readonly string[]): string | null {
  if (!選んでいる) return null;
  // 画面の中だけの印（`desk:◯◯ の AI`）から呼び方を取り出す
  const 呼び方 = 選んでいる.startsWith('desk:') ? 選んでいる.slice('desk:'.length) : null;
  if (!呼び方) return null;
  // **着いていない相手を宛先にしない。**居ないものへ送ったことにしない
  return 机のAIたち.includes(呼び方) ? 呼び方 : null;
}

/**
 * 届く先を並べる。**空なら、誰にも届かない。**
 *
 * **自分は入れない。**自分に届くのは当たり前で、数に入れると
 * 「1 人に届く」が「自分だけ」なのか「相手 1 人」なのか読めなくなる。
 */
export function 届く先を並べる(素材: 届く先の素材): string[] {
  // **宛先が決まっていれば、そこだけ。**1 対 1 がその場で分かる
  if (素材.宛先) return [素材.宛先];
  // **着いている 1 つずつを並べる。**まとめると、どれに届くのか分からない
  return [...素材.会議の相手, ...素材.机のAIたち];
}
