// **吹き出しの左右と、人かエージェントか**（0.1.36）。
//
// 1 列に流していた頃は、長い発言ほど「どこからどこまでが 1 通か」「誰の発言か」が読みにくく、
// 人とエージェントの見分けも名前の色だけだった。
// **この機械から出た発言（自分とこの機械のエージェント）は右、ほかの機械からは左**に置き、
// エージェントの発言には印を付ける。

import type { 会話行 } from '$lib/meeting/announce';

export interface 吹き出し {
  /** 右＝この機械から出た／左＝ほかの機械から届いた／中＝会議からの知らせ。 */
  側: '右' | '左' | '中';
  主: '人' | 'エージェント';
}

/**
 * ほかの機械のエージェントの種か。
 *
 * 機械は、札の付いた発言を `鍵の頭（札）` の名で渡してくる（人なら公開鍵の全桁）。
 * 公開鍵に `（` は出ないので、これで分かる。
 */
function ほかの機械のエージェントか(種: string | undefined): boolean {
  return 種 !== undefined && 種.includes('（');
}

export function 吹き出しの形(行: 会話行): 吹き出し {
  if (行.system) return { 側: '中', 主: '人' };
  if (行.agent) return { 側: '右', 主: 'エージェント' };
  if (行.mine) return { 側: '右', 主: '人' };
  return { 側: '左', 主: ほかの機械のエージェントか(行.顔の種) ? 'エージェント' : '人' };
}
