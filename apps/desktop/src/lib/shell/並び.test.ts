import { describe, expect, it } from 'vitest';
import { 入る口を先に出すか, 初めの入退の面 } from './並び';

describe('ルームの面の並び（2026-09-24・オーナー指摘）', () => {
  it('相手が居ないうちは、入る口が先', () => {
    // **招かれた側は、この画面を今日初めて開く人である。**
    // その人がやることは「もらったルームキーを貼る」1 つだけ
    expect(入る口を先に出すか({ 相手が居る: false })).toBe(true);
  });

  it('相手が居たら、会話が先', () => {
    // 2026-09-07 にオーナーの画面でチャットが 3 枚の札の下に埋まっていた ——
    // **スクロールしないと会話が見えない並びは、製品と逆である**
    expect(入る口を先に出すか({ 相手が居る: true })).toBe(false);
  });

  it('初めに出すのは「入る」', () => {
    // **つくるのは主催だけ。**招かれた側のほうが人数が多い
    expect(初めの入退の面).toBe('入る');
  });
});
