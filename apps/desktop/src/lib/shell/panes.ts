// 画面の「面」。**どこを見ているか**を決める。
//
// **これは「画面の状態」（`$lib/meeting/stage`）とは別の軸である。**混ぜない。
//
//   面     —— 連絡帳 / 会議 / 予定      ← どこを見ているか
//   状態   —— 会議前 / 待っている / 会議中 ← 会議がどうなっているか
//
// 依存は **面 → 状態 の一方向**。`stage.ts` に面の話を足さない
// （D45 と D55 が「会議がどうなっているか」を 1 か所に集めた意味が薄れる）。
//
// **入口は連絡帳である。**起動して最初に出るのは会議ではない ——
// 「割符はビデオ会議が中心のアプリではありません。**チャットやメールを
// MCP を通じておこなえる OSS** です」（オーナー・2026-09-06）。

import type { 画面の状態 } from '$lib/meeting/stage';

/** 面。 */
export type 面 = '連絡帳' | '会議' | '予定';

/** 起動して最初に出る面。**会議ではない。** */
export const 既定の面: 面 = '連絡帳';

/** 並び。**固定する**（押すたびに位置が変わると探させる）。 */
export const 面の並び: readonly 面[] = ['連絡帳', '会議', '予定'] as const;

/**
 * その面を、見ていないときに畳んでよいか。
 *
 * **会議の面は畳めない。**相手の音は `<video>` 要素から出ているので、
 * `{#if}` で外すと**連絡帳へ移った瞬間に相手の声が消える。**
 * 隠すだけにする（`hidden`）。
 */
export function 畳んでよい(面: 面): boolean {
  return 面 !== '会議';
}

/**
 * 面を移してよいきっかけか。
 *
 * **相手の操作でこちらの画面を動かさない。**
 * 「知らない相手が通知を出せる導線を作らない」（**D31** / DESIGN §2 原則 8）の隣に、
 * 「知らない相手がこちらの面を切り替えられる導線を作らない」がある。
 */
export function 面へ移ってよい(きっかけ: '人の操作' | '相手の入室'): boolean {
  return きっかけ === '人の操作';
}

/** 人が押した口。 */
export type 押した口 = 'chat' | 'group' | 'call' | 'calendar' | 'meeting.start' | 'meeting.join';

/**
 * 押したあと、どの面へ移るか。移らないなら `null`。
 *
 * **チャットは会議へ連れて行かない。**「会議ありきのチャットじゃないんです」
 * （オーナー・2026-09-07）。繋ぎ方は同じでも、行き先が違う。
 *
 * **グループチャットは会議の面へ移る。**ルームを作るのも鍵を出すのもそこである
 * （いまは同じ仕組みの上に乗っている。分けるのは別の回）。
 *
 * **予定はどこへも移さない。**まだ読む口が 1 本も無い。
 */
export function 押した後の面(口: 押した口): 面 | null {
  if (口 === 'chat' || 口 === 'calendar') return null;
  return '会議';
}

/** 面に出す印（レールの小さな目印）。無ければ `null`。 */
export function 面の印(面: 面, 状態: 画面の状態): 画面の状態 | null {
  if (面 !== '会議') return null;
  return 状態 === '会議前' ? null : 状態;
}

/**
 * その面がもう使えるか。使えないなら、**理由の鍵**を必ず返す。
 *
 * **予定は 2026-09-10 に動くようになった**（自分の予定を置ける）。
 * ただし**相手の予定は見えない** —— それは相手の側の話であって、面の話ではない。
 */
export function 使える面か(面: 面): { 使える: boolean; 訳: string | null } {
  // **黙って空を出さない。**使えない面ができたら、ここに理由を書く
  void 面;
  return { 使える: true, 訳: null };
}
