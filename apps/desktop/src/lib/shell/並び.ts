// **ルームの面の並び**（2026-09-24）。
//
// # 何が起きていたか
//
// 入ろうとする人が、入る口を探して上から読み、スクロールしないといけなかった。
// 最初は「並べ替え」で応えた（入る口を、つくる口より上へ置いた）が、
// **縦一列のままなので改善にならなかった。**要るのは「上へ移す」ではなく「**分ける**」だった。
//
// # 何が本体だったか
//
// **中継と留守番は、ほとんどの人が一度も触らない設定**なのに、
// 同じ大きさの札で同じ列に並んでいた。**いちばん使う文字の欄が 2 番目**にあった。
//
// **「縦一列に、重さの違うものが同じ大きさで並んでいる」**——これが本体である。
//
// # 決めた 3 つ
//
//   1. **入る／つくるは、1 つずつ出す**（札の中で切り替える。両方積まない）
//   2. **入る前は入る口が主役、入ったあとは会話が主役**（下の関数）
//   3. **一度も触らない設定は畳む**（中継・留守番）

/**
 * **入る口を、会話より先に出すか。**
 *
 * **相手が居ないうちは、入る口が主役である** ——
 * 招かれた側は、この画面を**今日初めて開く人**であり、
 * その人がやることは「もらったルームキーを貼る」1 つだけである。
 *
 * **相手が居たら、会話が主役に変わる。**
 * 2026-09-07 に**チャットが 3 枚の札の下に埋まっていた** ——
 * **スクロールしないと会話が見えない並びは、製品と逆である。**
 *
 * **畳むのではなく、順を入れ替える** —— 入ったあとも招けるべきなので、口は消さない。
 */
export function 入る口を先に出すか(いま: {
  /** つながっている相手が居るか。 */
  相手が居る: boolean;
}): boolean {
  return !いま.相手が居る;
}

/** 入る／つくるの、どちらを出しているか。 */
export type 入退の面 = '入る' | 'つくる';

/**
 * **初めに出す面。**
 *
 * **招かれた側のほうが、初めてこの画面を開く人である確率が高い**
 * （鍵を渡される側は、この製品を今日初めて開く）。
 * だから**入る**から出す。
 */
export const 初めの入退の面: 入退の面 = '入る';
