import { describe, expect, it } from 'vitest';

import {
  既定の面,
  面の並び,
  畳んでよい,
  面へ移ってよい,
  押した後の面,
  面の印,
  使える面か,
} from './panes';

describe('面（連絡帳 / 会議 / 予定）', () => {
  it('起動して最初に出るのは連絡帳である（会議ではない）', () => {
    // **入口は連絡帳。**「割符はビデオ会議が中心のアプリではありません」
    // （オーナー・2026-09-06）
    expect(既定の面).toBe('連絡帳');
  });

  it('並びは固定する', () => {
    // 押すたびに位置が変わると、毎回探させることになる
    expect(面の並び).toEqual(['連絡帳', '会議', '予定']);
  });
});

describe('畳んでよいか', () => {
  it('会議の面は畳まない（畳むと相手の声が消える）', () => {
    // **相手の音は video 要素から出ている。**{#if} で外すと、
    // 連絡帳へ移った瞬間に声が消える
    expect(畳んでよい('会議')).toBe(false);
  });

  it('連絡帳と予定は畳んでよい（外しても失うものが無い）', () => {
    expect(畳んでよい('連絡帳')).toBe(true);
    expect(畳んでよい('予定')).toBe(true);
  });
});

describe('面を移すきっかけ', () => {
  it('人が押したときは移してよい', () => {
    expect(面へ移ってよい('人の操作')).toBe(true);
  });

  it('相手が入ってきただけでは移さない', () => {
    // **相手の操作でこちらの画面を動かさない**（D31 / DESIGN §2 原則 8）
    expect(面へ移ってよい('相手の入室')).toBe(false);
  });
});

describe('押したあとの行き先', () => {
  it('会議に呼ぶを押したら、会議の面へ移る', () => {
    expect(押した後の面('call')).toBe('会議');
  });

  it('会議をはじめる・入室するでも、会議の面へ移る', () => {
    expect(押した後の面('meeting.start')).toBe('会議');
    expect(押した後の面('meeting.join')).toBe('会議');
  });

  it('チャットするを押しても、面は移らない', () => {
    // **会議ありきのチャットにしない**（オーナー・2026-09-07）
    expect(押した後の面('chat')).toBeNull();
  });

  it('グループチャットは、鍵を出す所（会議の面）へ移る', () => {
    // **ルームを作るのも鍵を出すのも会議の面である。**
    // 何人ぶん出すかは人が決める（D84）ので、勝手に建てない
    expect(押した後の面('group')).toBe('会議');
  });

  it('予定を押しても、どこへも移らない', () => {
    // **読む口が 1 本も無い。**移した先に何も無いなら、移さない
    expect(押した後の面('calendar')).toBeNull();
  });
});

describe('面の印', () => {
  it('会議中は、どの面に居ても会議の面に印が出る', () => {
    expect(面の印('会議', '会議中')).toBe('会議中');
    expect(面の印('会議', '待っている')).toBe('待っている');
  });

  it('会議前は印を出さない', () => {
    expect(面の印('会議', '会議前')).toBeNull();
  });

  it('連絡帳と予定に印は出さない', () => {
    expect(面の印('連絡帳', '会議中')).toBeNull();
    expect(面の印('予定', '会議中')).toBeNull();
  });
});

describe('使える面か', () => {
  it('予定は、まだ使えないことを理由つきで返す', () => {
    // **黙って空を出さない**（DESIGN §2 原則 7）
    const { 使える, 訳 } = 使える面か('予定');
    expect(使える).toBe(false);
    expect(訳).toBe('schedule.none');
  });

  it('連絡帳と会議は使える', () => {
    expect(使える面か('連絡帳').使える).toBe(true);
    expect(使える面か('会議').使える).toBe(true);
  });
});
