// **顔（アバター）。公開鍵から描く。**
//
// オーナー指示（2026-09-08）——
// 「**名前と、github のアバターアイコンみたいなものも設置したいです。
//   すると、先方にもそれがみれます。**」
//
// **絵は鍵から作る。**上げてもらう画像にしない。理由は 3 つある。
//
// 1. **真似できない。**鍵が同じなら同じ絵になる。**別人が同じ顔を出せない**
// 2. **送らなくていい。**相手も同じ鍵から同じ絵を描ける（帯域も保存も要らない）
// 3. **いつでもある。**設定していない人が「顔なし」にならない
//
// GitHub の既定アバターと同じ位置づけである。**人が選んだ画像ではない**ので、
// 「その人が選んだ顔」として出さない。

/** 顔の色。**地の色調（木・カフェオレ）から外れすぎない範囲で散らす。** */
const 色たち = [
  '#7b5a3e', // 木
  '#9c6b4a', // 赤みの木
  '#8a7b4f', // 枯草
  '#5f7355', // 苔
  '#4f6b73', // 藍鼠
  '#6b5570', // 葡萄
  '#a3714f', // 錆
  '#5c5f6b', // 石
] as const;

/** 一辺のます目。**奇数**（真ん中の列で折り返すため）。 */
export const マス = 5;

/**
 * 文字列から数を作る（FNV-1a・32 ビット）。
 *
 * **暗号には使わない。**顔を散らすためだけのものである。
 */
function 数にする(文字: string): number {
  let h = 0x811c9dc5;
  for (let i = 0; i < 文字.length; i += 1) {
    h ^= 文字.charCodeAt(i);
    // 32 ビットに収める（`Math.imul` を使わないと桁が溢れる）
    h = Math.imul(h, 0x01000193) >>> 0;
  }
  return h >>> 0;
}

/** 1 つの顔。 */
export interface 顔 {
  /** 塗る色。 */
  色: string;
  /** ます目（`true` が塗る）。**左右対称。** */
  ます: boolean[][];
}

/**
 * 公開鍵から顔を作る。**同じ鍵なら、いつでもどこでも同じ顔。**
 *
 * 左半分だけを決めて、**右へ折り返す。**左右非対称にすると、
 * 小さいときに「模様」ではなく「汚れ」に見える。
 */
export function 顔を描く(鍵: string): 顔 {
  const 種 = 数にする(鍵);
  // 色は鍵の頭ではなく、混ぜた数から採る（頭が似た鍵でも色が分かれる）
  const 色 = 色たち[種 % 色たち.length];

  const 半分 = Math.ceil(マス / 2);
  const ます: boolean[][] = [];
  for (let y = 0; y < マス; y += 1) {
    const 行: boolean[] = [];
    for (let x = 0; x < 半分; x += 1) {
      // 桁ごとに違う数を使う。**同じ数を使い回すと、縞模様になる**
      const 位 = y * 半分 + x;
      const 混ぜ = 数にする(`${鍵}:${位}`);
      行.push((混ぜ & 0x10) !== 0);
    }
    // 折り返す（真ん中の列は 1 つだけ）
    for (let x = マス - 半分 - 1; x >= 0; x -= 1) 行.push(行[x]);
    ます.push(行);
  }
  return { 色, ます };
}
