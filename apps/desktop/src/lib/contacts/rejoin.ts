// **前に入ったルームへ戻る口を出すか。**
//
// `gh issue 13`（ASUS・2026-09-12）——
//
// > アプリの更新は再起動を伴います。更新のたびに鍵を貼り直すことになり、
// > 鍵は 1 本 = 1 人なので、出し直してもらう手間が毎回かかります。
//
// **鍵の文字は画面に出さない。**入っているのは割符の片割れである。
// 出すのは「戻る」の押し口だけ —— 文字を見せると、人が別の相手へ渡せてしまう。

/** 戻る口を出すかを決めるのに要るもの。 */
export type いま = {
	/** 帰り道のルーム id。無ければ `null`。 */
	帰り道のルーム: string | null;
	/** いま持っているルームの id。 */
	持っているルーム: readonly string[];
};

/** 戻る口を出すか。**もう居るルームには出さない**（押す意味が無い）。 */
export function 戻る口を出すか(いま: いま): boolean {
	if (!いま.帰り道のルーム) return false;
	return !いま.持っているルーム.includes(いま.帰り道のルーム);
}
