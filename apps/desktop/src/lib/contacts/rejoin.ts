// **前に入ったルームへ戻る口を出すか。**
//
// `gh issue 13`（2026-09-12）——
// アプリの更新は再起動を伴う。鍵は 1 本 = 1 人なので、
// 更新のたびに鍵を出し直してもらう手間がかかっていた。
//
// **鍵の文字は画面に出さない。**入っているのは割符の片割れである。
// 出すのは「戻る」の押し口だけ —— 文字を見せると、人が別の相手へ渡せてしまう。

/** 戻る口を出すかを決めるのに要るもの。 */
export type いま = {
	/** 帰り道のルーム id。無ければ `null`。 */
	帰り道のルーム: string | null;
	/** いま持っているルーム（人数は自分を含む）。 */
	持っているルーム: readonly { id: string; members: number; host: boolean }[];
};

/**
 * 戻る口を出すか。**もう居るルームには出さない**（押す意味が無い）。
 *
 * **ただし、ゲストで入った部屋に自分しか残っていなければ出す**（**#48**）。
 * 主催が落ちて上がり直すと、主催は部屋を戻して待ち、ゲストも同じ部屋に 1 人で残って待つ。
 * 部屋を持っているので「もう居る」と見なしていたため、**どちらからもつなぎ直せなかった。**
 */
export function 戻る口を出すか(いま: いま): boolean {
	if (!いま.帰り道のルーム) return false;
	const 部屋 = いま.持っているルーム.find((r) => r.id === いま.帰り道のルーム);
	if (!部屋) return true;
	return !部屋.host && 部屋.members <= 1;
}
