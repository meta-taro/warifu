import { describe, expect, it } from 'vitest';
import { 戻る口を出すか } from './rejoin';

/** 持っているルーム 1 つ。既定は「ゲストで入っていて、主催と 2 人」。 */
const 部屋 = (id: string, members = 2, host = false) => ({ id, members, host });

describe('前のルームに戻る口', () => {
  // gh issue 13（2026-09-12）—— 更新のたびに再起動し、鍵を出し直してもらう手間がかかっていた。

  it('帰り道があって、そのルームに居ないなら出す', () => {
    expect(戻る口を出すか({ 帰り道のルーム: 'AAA', 持っているルーム: [部屋('BBB')] })).toBe(true);
  });

  it('**もうそのルームに居るなら出さない**（押す意味が無い）', () => {
    expect(戻る口を出すか({ 帰り道のルーム: 'AAA', 持っているルーム: [部屋('AAA', 2), 部屋('BBB')] })).toBe(
      false
    );
  });

  it('帰り道が無ければ出さない', () => {
    expect(戻る口を出すか({ 帰り道のルーム: null, 持っているルーム: [] })).toBe(false);
  });

  it('ルームを 1 つも持っていなくても、帰り道があれば出す', () => {
    expect(戻る口を出すか({ 帰り道のルーム: 'AAA', 持っているルーム: [] })).toBe(true);
  });

  // **#48** —— 主催が落ちて上がり直すと、主催の側は部屋を戻して待ち、
  // ゲストの側も同じ部屋に 1 人で残って待つ。**どちらからも、つなぎ直す手が無かった。**
  // 部屋を持っているので「もう居る」と見なし、戻る口を出していなかった。
  it('**ゲストで入った部屋に自分しか残っていなければ出す**（主催が落ちた・#48）', () => {
    expect(戻る口を出すか({ 帰り道のルーム: 'AAA', 持っているルーム: [部屋('AAA', 1)] })).toBe(true);
  });

  it('**自分が主催の部屋なら、1 人でも出さない**（待つのは主催の役）', () => {
    expect(
      戻る口を出すか({ 帰り道のルーム: 'AAA', 持っているルーム: [部屋('AAA', 1, true)] }),
    ).toBe(false);
  });
});
