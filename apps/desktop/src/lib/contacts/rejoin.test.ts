import { describe, expect, it } from 'vitest';
import { 戻る口を出すか } from './rejoin';

describe('前のルームに戻る口', () => {
  // gh issue 13（ASUS・2026-09-12）——
  //
  // > アプリの更新は再起動を伴います。更新のたびに鍵を貼り直すことになり、
  // > 鍵は 1 本 = 1 人なので、出し直してもらう手間が毎回かかります。

  it('帰り道があって、そのルームに居ないなら出す', () => {
    expect(戻る口を出すか({ 帰り道のルーム: 'AAA', 持っているルーム: ['BBB'] })).toBe(true);
  });

  it('**もうそのルームに居るなら出さない**（押す意味が無い）', () => {
    expect(戻る口を出すか({ 帰り道のルーム: 'AAA', 持っているルーム: ['AAA', 'BBB'] })).toBe(
      false
    );
  });

  it('帰り道が無ければ出さない', () => {
    expect(戻る口を出すか({ 帰り道のルーム: null, 持っているルーム: [] })).toBe(false);
  });

  it('ルームを 1 つも持っていなくても、帰り道があれば出す', () => {
    expect(戻る口を出すか({ 帰り道のルーム: 'AAA', 持っているルーム: [] })).toBe(true);
  });
});
