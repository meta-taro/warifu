// **次に会うとき、どうするか。**
//
// オーナー指摘（2026-09-11）——
// 「**呼び名をつけないと、初回とおなじフローになるというのもそれはそれでいいかもです。
// ずっと繋がっていたいわけではない場合もあるので。**なので、再度やり取りする時に
// お互いに？ もしくは一方？ がルーム名？ を決めるように案内すればいいかと。
// **あんないのしかたが UI/UX 的に気になります。**」
//
// **覚えないことは不具合ではない。**忘れる自由がある。
// 悪いのは「**次にどうすればいいか画面が言わない**」ことである。
//
// 道は 3 つしかない ——
//
//   呼べる             …… 居場所を覚えている。連絡帳から呼ぶ（鍵は要らない）
//   向こうから呼んでもらう …… こちらは居場所を知らないが、相手が叩けば通す（D58）
//   鍵を渡し合う         …… どちらも無い。**初回と同じ**
//
// **「相手の戸口がこちらを通すか」は、こちらには分からない。**
// 分からないものを「必ず繋がります」と書かない（DESIGN §2 原則 7）。

/** 相手のいまの持ちもの。 */
export interface 手がかり {
  種類: '自分' | 'AI' | '人' | 'ルーム';
  /** その相手の居場所を覚えているか（`contacts.tsv` の 4 欄目）。 */
  住所を覚えている: boolean;
  /** こちらの戸口が、その相手を鍵なしで通すか（`known.tsv`）。 */
  鍵なしで入れる: boolean;
}

/** 次に会うときの道。 */
export type 道 = '呼べる' | '向こうから呼んでもらう' | '鍵を渡し合う';

/** 案内 1 つ。**訳（文言の鍵）を必ず持つ。** */
export interface 案内 {
  道: 道;
  訳: string;
}

/**
 * 次に会うときの道を決める。**ほかの人にだけ出す**（自分・ルーム・エージェントには `null`）。
 */
export function 再会の道を決める(手がかり: 手がかり): 案内 | null {
  if (手がかり.種類 !== '人') return null;
  // **居場所を覚えているなら、こちらから呼べる。**鍵は要らない
  if (手がかり.住所を覚えている) return { 道: '呼べる', 訳: 'reunion.call' };
  // 居場所は知らないが、一度通した相手なら、叩かれれば通す（D58）
  if (手がかり.鍵なしで入れる) {
    return { 道: '向こうから呼んでもらう', 訳: 'reunion.wait' };
  }
  // **初回と同じ。**忘れたままにするのも選択である
  return { 道: '鍵を渡し合う', 訳: 'reunion.key' };
}
