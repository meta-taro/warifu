import { describe, expect, it } from 'vitest';
import { エージェントの名札 } from './seat';

describe('エージェントの名札', () => {
  it('名乗っていれば、名前とどこのエージェントかを並べる', () => {
    expect(エージェントの名札('alpha のエージェント', 'アルファくん')).toBe('アルファくん（alpha）');
  });

  it('名乗っていなければ、エージェントそのままにする', () => {
    expect(エージェントの名札('alpha のエージェント', undefined)).toBe('alpha のエージェント');
  });

  it('名前が空なら、エージェントそのままにする', () => {
    expect(エージェントの名札('alpha のエージェント', '')).toBe('alpha のエージェント');
  });

  it('どこのエージェントかは落とさない', () => {
    // 落とすと alpha と beta の見分けが付かない（D75）
    expect(エージェントの名札('beta のエージェント', 'アルファくん')).toContain('beta');
  });

  it('「のエージェント」で終わらない呼び方でも壊れない', () => {
    expect(エージェントの名札('名乗りのないエージェント', undefined)).toBe('名乗りのないエージェント');
  });
});
