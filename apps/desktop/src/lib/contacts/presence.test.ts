import { describe, expect, it } from 'vitest';

import { 在エージェントの印 } from './presence';
import type { 行 } from './list';

const 行を作る = (o: Partial<行>): 行 => ({
  key: 'K',
  name: 'n',
  種類: '人',
  住所を覚えている: false,
  いま会議に居る: false,
  ...o,
});

describe('在エージェントの印（Slack のような ●／○）', () => {
  it('自分は、いつも つながっている', () => {
    // **この窓が動いているなら、あなたは居る**
    expect(在エージェントの印(行を作る({ 種類: '自分', いま会議に居る: true }))).toBe('つながっている');
  });

  it('この PC のエージェントは、つながっていれば ●、切れていれば ○', () => {
    // **ここは分かる。**口につながっているかどうかを、こちらが持っている
    expect(在エージェントの印(行を作る({ 種類: 'AI', いま会議に居る: true }))).toBe('つながっている');
    expect(在エージェントの印(行を作る({ 種類: 'AI', いま会議に居る: false }))).toBe('切れている');
  });

  it('ほかの人には、印を出さない', () => {
    // **相手が起動しているかは分からない**（DESIGN §2 原則 7）。
    // Slack と違って、間に居る機械が無い —— **分からないものを ○ と書かない**
    expect(在エージェントの印(行を作る({ 種類: '人' }))).toBeNull();
    expect(在エージェントの印(行を作る({ 種類: '人', いま会議に居る: true }))).toBeNull();
  });

  it('ルームには、印を出さない', () => {
    expect(在エージェントの印(行を作る({ 種類: 'ルーム', いま会議に居る: true }))).toBeNull();
  });
});
