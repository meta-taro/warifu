// 選んだ相手に、いま何ができるか。
//
// **押せない口を、押せる形で出さない**（**D49**）。
// 2026-09-06 にオーナーが「チャット送るボタンきかないよ」と言った所である ——
// ボタンは正しく動いていたが、**押せる見た目のまま断っていた。**
//
// **押せないなら、理由を一緒に返す。**理由の無い「押せない」は、
// 使う人には「壊れている」としか見えない。

/** 相手に出す口の種類。
 *
 * **`chat` は置かない**（2026-09-08 オーナー指摘
 * 「これを押したら何が起こるかわかりません」）——
 * **行を選んだ時点で、その相手との会話が開いている。**
 * 押しても何も起きない口は、**誤解しか生まない。**
 */
export type 口の種類 = 'call' | 'mail';

/** 選んだ相手の素性。 */
export interface 相手 {
  /** 自分か、マイ PC エージェント か、ほかの人か。 */
  種類: '自分' | 'AI' | '人' | '部屋';
  /** 居場所を覚えているか。**覚えていなければ、こちらから呼べない。** */
  住所を覚えている: boolean;
  /** いま会議に居るか。 */
  いま会議に居る: boolean;
  /** 机に着いているか（マイ PC エージェント の行なら、その 1 つが着いているか）。 */
  机に着いている: boolean;
  /**
   * 預かり所を置いているか（**D71**）。
   *
   * 置いていれば、**住所を知らなくても、相手が起動していなくても**文字は届く ——
   * 預けるのに要るのは公開鍵だけで、封は相手しか開けられない。
   * **会議はそうはいかない**（映像も音も、いま繋がっていないと始まらない）。
   *
   * **口の並びには効かない。**文字を打つ所は、行を選んだ時点で開いている ——
   * 打てるかどうかは、そちら（`chat/postbox.ts` の `どう送るか`）が決める。
   */
  預かり所がある?: boolean;
}

/** 1 つの口。 */
export interface 口 {
  種類: 口の種類;
  押せる: boolean;
  /** 押せない訳（文言の鍵）。**押せるときは `null`。** */
  訳: string | null;
}

/**
 * その相手にできることを並べる。
 *
 * **自分自身には何も出さない。**自分に話しかける口を作らない。
 */
export function できること(相手: 相手): 口[] {
  // **自分にも部屋にも口は出さない。**自分に話しかける口は作らない。
  // 部屋は「押して見るもの」であって、部屋そのものに何かする口は無い
  if (相手.種類 === '自分' || 相手.種類 === '部屋') return [];
  if (相手.種類 === 'AI') return AIにできること(相手);
  return 人にできること(相手);
}

function AIにできること(_相手: 相手): 口[] {
  return [
    // **同じ机に着いている。**会議に呼ぶ相手ではない
    { 種類: 'call', 押せる: false, 訳: 'act.desk.local' },
    { 種類: 'mail', 押せる: false, 訳: 'act.mail.none' },
  ];
}

function 人にできること(相手: 相手): 口[] {
  const 呼べる = !相手.いま会議に居る && 相手.住所を覚えている;

  return [
    {
      種類: 'call',
      押せる: 呼べる,
      訳: 呼べる ? null : 相手.いま会議に居る ? 'act.already' : 'act.address.none',
    },
    // **メールはどの相手でも押せない。**送る経路が 1 本も無い
    { 種類: 'mail', 押せる: false, 訳: 'act.mail.none' },
  ];
}
