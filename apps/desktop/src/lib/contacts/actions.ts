// 選んだ相手に、いま何ができるか。**ダッシュボードの中身**（**D88**）。
//
// 「相手を選ぶと、できることが出ます。こちらももう少し丁寧がいいでしょう。
// ダッシュボードでもいいと思います。**チャットをするのか、グループチャットを
// するのか、かれんだーで予定をみるのか、ビデオ会議を開始するのか**」
// （オーナー・2026-09-10）
//
// **押せない口を、押せる形で出さない**（**D49**）。
// 2026-09-06 にオーナーが「チャット送るボタンきかないよ」と言った所である ——
// ボタンは正しく動いていたが、**押せる見た目のまま断っていた。**
//
// **札には、できる／条件つき／まだできない と、その 1 行の訳を必ず添える。**
// 訳の無い札は、使う人には「壊れている」としか見えない。

/**
 * 相手に出す札の種類。**4 枚で固定する**（オーナー承認 2026-09-10）。
 *
 * **`mail` は外した。**送る経路が 1 本も無いものを 4 枚のうちの 1 枚に据えると、
 * 「いつか送れる所」に見える。メールは MCP の読む口の話であって、
 * **相手を選んでする操作ではない。**
 */
export type 口の種類 = 'chat' | 'group' | 'call' | 'calendar';

/** 札の並び。**押すたびに位置が変わると探させる**ので固定する。 */
export const 札の並び: readonly 口の種類[] = ['chat', 'group', 'call', 'calendar'] as const;

/**
 * 札の状態。
 *
 * - `できる` —— いまそのまま使える
 * - `条件つき` —— 何かが揃えば使える（**何が要るかを訳で言う**）
 * - `まだできない` —— 作っていない。**いつかできるように見せない**
 */
export type 状態 = 'できる' | '条件つき' | 'まだできない';

/** 選んだ相手の素性。 */
export interface 相手 {
  /** 自分か、マイ PC エージェント か、ほかの人か。 */
  種類: '自分' | 'AI' | '人' | 'ルーム';
  /** 居場所を覚えているか。**覚えていなければ、こちらから呼べない。** */
  住所を覚えている: boolean;
  /** いま会議に居るか。 */
  いま会議に居る: boolean;
  /** このPCにつながっているか（マイ PC エージェント の行なら、その 1 つが着いているか）。 */
  このPCにつながっている: boolean;
  /**
   * 預かり所を置いているか（**D71**）。
   *
   * 置いていれば、**住所を知らなくても、相手が起動していなくても**文字は届く ——
   * 預けるのに要るのは公開鍵だけで、封は相手しか開けられない。
   * **会議はそうはいかない**（映像も音も、いま繋がっていないと始まらない）。
   */
  預かり所がある?: boolean;
}

/** 1 枚の札。 */
export interface 口 {
  種類: 口の種類;
  状態: 状態;
  /**
   * 押せる札か。
   *
   * **押せなくても札は出す** —— 状態と訳を読ませるためである。
   * 押せる札だけが、`押す()` を呼ぶボタンを持つ。
   */
  押せる: boolean;
  /** その札の 1 行（文言の鍵）。**どの札にも必ず在る。** */
  訳: string;
}

/**
 * その相手にできることを並べる。
 *
 * **自分自身には何も出さない。**自分に話しかける口を作らない。
 */
export function できること(相手: 相手): 口[] {
  // **自分にもルームにも札は出さない。**自分に話しかける口は作らない。
  // ルームは「押して見るもの」であって、ルームそのものに何かする口は無い
  if (相手.種類 === '自分' || 相手.種類 === 'ルーム') return [];
  if (相手.種類 === 'AI') return AIにできること(相手);
  return 人にできること(相手);
}

/**
 * 同じ PC のエージェントにできること。
 *
 * **繋がっていなくても 4 枚出す**（オーナー指摘 2026-09-10
 * 「**なにもかわってないですけど**」）——
 * 一度は「口を 1 枚も出さない」形にした。理由は、押せないボタンに
 * 「はじめから同じルームに居ます」と**繋がっていないときの理由ではない訳**を
 * 添えていたからである。
 *
 * **いまは札ごとに状態と訳を持つ**（D88）ので、隠す必要が無い ——
 * 「いますか？いませんか？」には**まだできない**の札が答える。
 */
function AIにできること(相手: 相手): 口[] {
  // **繋がっていないなら、4 枚とも「まだできない」。**訳はそれぞれ違う
  if (!相手.このPCにつながっている) {
    return [
      { 種類: 'chat', 状態: 'まだできない', 押せる: false, 訳: 'act.chat.desk.none' },
      { 種類: 'group', 状態: 'まだできない', 押せる: false, 訳: 'act.group.desk.none' },
      { 種類: 'call', 状態: 'まだできない', 押せる: false, 訳: 'act.call.desk.none' },
      ...予定の札(),
    ];
  }
  return [
    // **同じこのPCにつながっている。**呼びに行く相手ではないし、文字はもう届く
    { 種類: 'chat', 状態: 'できる', 押せる: false, 訳: 'act.chat.desk' },
    { 種類: 'group', 状態: 'できる', 押せる: true, 訳: 'act.group.what' },
    { 種類: 'call', 状態: 'できる', 押せる: false, 訳: 'act.desk.local' },
    ...予定の札(),
  ];
}

function 人にできること(相手: 相手): 口[] {
  return [文字の札(相手), { 種類: 'group', 状態: 'できる', 押せる: true, 訳: 'act.group.what' }, 会議の札(相手), ...予定の札()];
}

/**
 * チャットの札。**押せる口は持たない** ——
 * 行を選んだ時点で、その相手との会話は開いている（2026-09-08 オーナー指摘
 * 「これを押したら何が起こるかわかりません」）。だから**どこに打つかだけを言う。**
 */
function 文字の札(相手: 相手): 口 {
  // **預かり所があれば、相手が起動していなくても届く**（D71）
  if (相手.預かり所がある) {
    return { 種類: 'chat', 状態: 'できる', 押せる: false, 訳: 'act.chat.postbox' };
  }
  // **無ければ、繋がっている間だけ**である。そこを黙らない
  return { 種類: 'chat', 状態: '条件つき', 押せる: false, 訳: 'act.chat.live' };
}

/**
 * ビデオ会議の札。
 *
 * **同じ網なら繋がる。別の網は実測 0 件**なので `条件つき` に留める ——
 * 中継（`--relay`）は入れたが、**網を越えて繋がったことを一度も見ていない。**
 */
function 会議の札(相手: 相手): 口 {
  if (相手.いま会議に居る) {
    return { 種類: 'call', 状態: 'できる', 押せる: false, 訳: 'act.already' };
  }
  if (!相手.住所を覚えている) {
    return { 種類: 'call', 状態: 'まだできない', 押せる: false, 訳: 'act.address.none' };
  }
  return { 種類: 'call', 状態: '条件つき', 押せる: true, 訳: 'act.call.net' };
}

/** 予定の札。**まだ読む口が 1 本も無い。** */
function 予定の札(): 口[] {
  return [{ 種類: 'calendar', 状態: 'まだできない', 押せる: false, 訳: 'act.calendar.none' }];
}
