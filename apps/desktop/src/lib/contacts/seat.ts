// **机の席（この PC のエージェント）を、画面で何と呼ぶか**（**D77**）。
//
// 2026-09-09 に実物で見た壊れ方 ——
// 連絡帳は「かくにん係」、会話は「kakunin のエージェント」と出ていた。
// **人はそれを 2 人だと読む。**
//
// 名前の決め方が 2 か所にあると、片方だけ直した瞬間に食い違う。
// Rust 側（`profile::名札にする`）と**同じ形**をここに置く。

/** 名乗りの後ろに付く言葉。**これが付いていれば、AI だと分かる。** */
const 席の印 = ' のエージェント';

/**
 * `名前（名乗り）` の形にする。名乗っていなければ席そのまま。
 *
 * **どこの席かは落とさない**（**D75**）。落とすと `zumen` と `git-qa` の
 * 見分けが付かず、**相手の画面で取り違えられる。**
 */
export function 席の名札(呼び方: string, 名前: string | undefined): string {
  if (!名前) return 呼び方;
  const 場所 = 呼び方.endsWith(席の印) ? 呼び方.slice(0, -席の印.length) : 呼び方;
  return `${名前}（${場所}）`;
}
