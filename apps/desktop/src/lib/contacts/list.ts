// 連絡帳の並び。**3 つの区画に分ける。**
//
//   この PC        —— 自分と、マイ PC エージェント（`issues/012`「人と AI はセット」）
//   いま会議に居る人 —— 覚えていなくても、いま繋がっている相手
//   覚えている相手   —— `contacts.tsv` に居る人
//
// **同じ人を二度出さない。**いま会議に居る覚えた相手は、上の区画にだけ出す。

import { 呼び名, 鍵の頭 } from '$lib/meeting/names';
import { 映像の札 } from '$lib/meeting/stage-one';

/** 一覧の 1 行。 */
export interface 行 {
  /** 公開鍵（全桁）。**押したときに使う。** */
  key: string;
  /** 画面に出す名前。 */
  name: string;
  種類: '自分' | 'AI' | '人' | 'ルーム';
  住所を覚えている: boolean;
  いま会議に居る: boolean;
  /**
   * **この部屋に映像と音が付いているか**（ルームの行だけ持つ・**#36**）。
   *
   * **開くまで分からない**のをやめる（2026-09-16・ASUS）——
   * 「**どちらの部屋を映しているかは、画面のどこにも書いてありません。**
   * 相手の鍵が出ているので、知っている人だけが逆算できます。」
   */
  映像が付いている?: boolean;
  /**
   * **自分が建てたルームか**（ルームの行だけ持つ）。
   *
   * `gh issue 13`（2026-09-12）—— 入り直したあと**ルームが 2 行**並び、
   * 「人から見て、どちらが本物か分かりません」と言われた。
   * **重複ではない** —— 片方は**起動時に建て直した自分のルーム**、
   * 片方は**鍵でもらって入ったルーム**である。
   * **どちらが自分のものかを画面が言っていない**のが問題だった。
   */
  主催か?: boolean;
}

/** 区画 1 つ。 */
export interface 区画 {
  /** 見出しの文言の鍵。 */
  title: string;
  行たち: 行[];
}

/** 連絡帳を作るのに要るもの。 */
export interface 素材 {
  /** 自分の公開鍵。 */
  自分: string;
  /**
   * いまこの機械につながっている顔ぶれ（呼び方の並び）。
   *
   * **数だけでは足りない。**1 台の PC で複数のエージェントが同じ機械につながるので、
   * まとめて 1 行にすると**どれがつながっているのか分からない**
   * （2026-09-08 オーナー指摘「この機械のどこで起動しているエージェントなのか」）。
   */
  この機械のAIたち: readonly string[];
  /** いま会議に居る相手の公開鍵（自分を含まない）。 */
  会議の相手: readonly string[];
  /**
   * **名乗り（プロフィール）を書いてあるエージェント**の呼び方。
   *
   * **エージェントは、まとめて 1 人ではない。それぞれが 1 人である**
   * （オーナー・2026-09-08）。立ち上げていない間も行を出す ——
   * 消えると、**その 1 人ぶんの名乗りが編集できなくなる。**
   */
  名乗りのあるエージェント?: readonly string[];
  /** 覚えている相手。 */
  覚えた: readonly { key: string; label: string; has_address: boolean; note?: string }[];
  /**
   * いま居るルーム。
   *
   * **持てても見えなければ切り替えようがない**（2026-09-08）。
   * ルームを複数持てるようにした以上、一覧が要る。
   */
  ルームたち?: readonly { id: string; members: number; host: boolean }[];
  /**
   * **いま映像と音が付いている部屋**（**#36**）。無ければ `null`。
   *
   * **映像の部屋は 1 つだけ**（オーナー判断 2026-09-16・`meeting/stage-one.ts`）。
   */
  映像がある部屋?: string | null;
  /**
   * ルームに付けた名前（ルーム id → 名前）。
   *
   * **付いていなければ id の頭で出す。**「どのルーム？」と人が思う所である
   * （オーナー・2026-09-08）。
   */
  ルームの名前?: Readonly<Record<string, string>>;
  /**
   * **留守中に預かり所へ言葉を置いていった相手**の公開鍵（**D71** / **D72**）。
   *
   * 覚えていない相手からも届く。**行が無いと、届いた言葉を開く所が無い** ——
   * 受け取っておいて出さないのは、黙って捨てるのと同じに見える。
   */
  留守中に届いた?: readonly string[];
}

/** この機械につながっている相手を指す、画面の中だけの印。**公開鍵ではない。** */
export const この機械の印 = 'desk:';

/** ルームを指す、画面の中だけの印。**公開鍵ではない。** */
export const ルームの印 = 'room:';

/** その行がルームか。 */
export function ルームか(key: string): boolean {
  return key.startsWith(ルームの印);
}

/** ルームの印から id を取り出す。ルームでなければ `null`。 */
export function ルームのid(key: string): string | null {
  return ルームか(key) ? key.slice(ルームの印.length) : null;
}

/** その行がこの機械の相手か。 */
export function この機械の相手か(key: string): boolean {
  return key.startsWith(この機械の印);
}

/**
 * 連絡帳を組み立てる。
 *
 * **知らない相手を、知っているように見せない。**
 * 覚えていない相手は鍵の頭で出す（`呼び名` と同じ扱い）。
 */
export function 連絡帳を組む(素材: 素材): 区画[] {
  const 名簿 = Object.fromEntries(素材.覚えた.map((c) => [c.key, c.label]));
  const 住所あり = new Set(素材.覚えた.filter((c) => c.has_address).map((c) => c.key));
  const 会議に居る = new Set(素材.会議の相手);

  const この機械: 行[] = [
    {
      key: 素材.自分,
      name: 'contacts.me',
      種類: '自分',
      住所を覚えている: false,
      いま会議に居る: true,
    },
  ];
  // **エージェントは、まとめて 1 人ではない。それぞれが 1 人である**
  // （オーナー・2026-09-08「この機械に複数のエージェントがいます。
  // まとめて一人なのではなく、それぞれが一人なのです」）。
  //
  // **いまつながっているエージェント**と、**名乗りを書いてあるエージェント**を合わせて並べる ——
  // 立ち上げていない間だけ消えると、**その 1 人ぶんの名乗りが編集できなくなる。**
  const つながっている = new Set(素材.この機械のAIたち);
  const エージェントたち = [...素材.この機械のAIたち];
  for (const 呼び方 of 素材.名乗りのあるエージェント ?? []) {
    if (!つながっている.has(呼び方)) エージェントたち.push(呼び方);
  }

  // **「マイ PC エージェント」という 1 人は居ない。**
  // 誰もつながっていないときに人の行を出すと、**それが 1 人に見える** ——
  // 「あなたが接続したならあなたはあなたで一意で、git-qa, zumen が接続したら
  // また別の人です」（オーナー・2026-09-08）。
  // 出すのは行ではなく、**着かせ方の案内**である（画面側で出す）。
  if (エージェントたち.length > 0) {
    // **1 つずつ行にする。**まとめると、どれがつながっているのか分からない
    for (const 呼び方 of エージェントたち) {
      この機械.push({
        key: `${この機械の印}${呼び方}`,
        name: 呼び方,
        種類: 'AI',
        住所を覚えている: false,
        // **つながっているかどうかは、ここで分ける。**名乗りだけがあるエージェントは居ない
        いま会議に居る: つながっている.has(呼び方),
      });
    }
  }

  // **「いま同じルームの人」の区画を作らない**（**段 C** / D107 の計画・2026-09-14）。
  //
  // **同じ人が 2 か所に出るのをやめる。**ルームの行を押せば名簿が出るので、
  // 上に別の区画を置くと、**同じ人を 2 回数える画面**になる。
  // 2026-09-15 には、こちらが**鍵の頭からどの機械かを読み違えた** ——
  // **同じ人が別の顔で 2 か所に出ていると、人も AI も取り違える。**
  //
  // **代わりに、連絡先の 1 行が「いま居る」を持つ。**覚えていない相手も
  // **連絡先に出す** —— **居るのに見えない**のがいちばん困る。
  const 覚えた: 行[] = [
    ...素材.覚えた.map((c) => ({
      key: c.key,
      name: c.label,
      種類: '人' as const,
      住所を覚えている: c.has_address,
      いま会議に居る: 会議に居る.has(c.key),
    })),
    // 覚えていないのにルームに居る人（鍵の頭で出る）
    ...素材.会議の相手
      .filter((key) => !素材.覚えた.some((c) => c.key === key))
      .map((key) => ({
        key,
        name: 呼び名(名簿, key),
        種類: '人' as const,
        住所を覚えている: 住所あり.has(key),
        いま会議に居る: true,
      })),
  ].sort((a, b) => a.name.localeCompare(b.name));

  const 区画たち: 区画[] = [{ title: 'contacts.this', 行たち: この機械 }];

  // **ルームは、居るときだけ出す。**空の見出しを並べない
  const ルーム: 行[] = (素材.ルームたち ?? []).map((r, i) => ({
    key: `${ルームの印}${r.id}`,
    // **付けた名前があればそれで呼ぶ。**
    // 無ければ**数えて呼ぶ**（`room.nth:<番>:<人数>`）——
    // **生の id を人に見せない**（DESIGN §10-A）。
    // 「HPXQEPXFKFMA…」では、どのルームか分からない。
    // 文言にするのは画面側（辞書を持たないこの層で組み立てない）
    name: 素材.ルームの名前?.[r.id] ?? `room.nth:${i + 1}:${r.members}`,
    種類: 'ルーム' as const,
    住所を覚えている: false,
    いま会議に居る: r.members > 1,
    主催か: r.host,
    映像が付いている: 映像の札(r.id, 素材.映像がある部屋 ?? null),
  }));
  if (ルーム.length > 0) 区画たち.push({ title: 'contacts.rooms', 行たち: ルーム });

  // **留守中に置いていった相手。**覚えていなくても、開く所を出す
  // （**同じ人を二度出さない** —— 覚えている相手なら、下の区画にもう居る）
  const 出た = new Set([...会議に居る, ...素材.覚えた.map((c) => c.key), 素材.自分]);
  const 留守中: 行[] = (素材.留守中に届いた ?? [])
    .filter((key) => !出た.has(key))
    .map((key) => ({
      key,
      name: 呼び名(名簿, key),
      種類: '人' as const,
      // **住所は知らない。**預かり所ごしに届いただけで、居場所は分からない
      住所を覚えている: false,
      いま会議に居る: false,
    }));
  if (留守中.length > 0) 区画たち.push({ title: 'contacts.late', 行たち: 留守中 });

  区画たち.push({ title: 'contacts.saved', 行たち: 覚えた });
  return 区画たち;
}
