import { describe, expect, it } from 'vitest';

import { 再会の道を決める } from './reunion';

const 人 = {
  種類: '人' as const,
  住所を覚えている: false,
  鍵なしで入れる: false,
};

describe('次に会うときの道（案内の仕方）', () => {
  it('居場所を覚えていれば、連絡先から呼べる', () => {
    const 道 = 再会の道を決める({ ...人, 住所を覚えている: true });
    expect(道?.道).toBe('呼べる');
    expect(道?.訳).toBe('reunion.call');
  });

  it('居場所を知らず、戸口に居るだけなら、向こうから呼んでもらう', () => {
    // **こちらからは呼べない**（住所を知らない）。
    // ただし相手が叩けば通す（一度通した相手・D58）
    const 道 = 再会の道を決める({ ...人, 鍵なしで入れる: true });
    expect(道?.道).toBe('向こうから呼んでもらう');
    expect(道?.訳).toBe('reunion.wait');
  });

  it('どちらも無ければ、初回と同じで鍵を渡し合う', () => {
    // **これは不具合ではない**（オーナー・2026-09-11
    // 「ずっと繋がっていたいわけではない場合もあるので」）。
    // **そう案内する**ことが大事である
    const 道 = 再会の道を決める(人);
    expect(道?.道).toBe('鍵を渡し合う');
    expect(道?.訳).toBe('reunion.key');
  });

  it('自分とルームとエージェントには出さない', () => {
    // **再会の話は、ほかの人に対してだけ**
    for (const 種類 of ['自分', 'ルーム', 'AI'] as const) {
      expect(再会の道を決める({ ...人, 種類, 住所を覚えている: true })).toBeNull();
    }
  });
});
