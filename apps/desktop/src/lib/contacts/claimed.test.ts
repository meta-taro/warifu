import { describe, expect, it } from 'vitest';

import { 名乗りを添えるか, 呼ぶ名 } from './claimed';

describe('相手の名乗り', () => {
  it('こちらが付けた呼び名が勝つ', () => {
    // **名乗った名前は誰でも真似できる**（D46 は残る）
    expect(呼ぶ名('mac air', { 名前: 'べつじん', 紹介: '' }, '4VKC…')).toBe('mac air');
  });

  it('呼び名が無ければ、本人の名乗りで呼ぶ', () => {
    expect(呼ぶ名(undefined, { 名前: 'めたたろ', 紹介: '' }, '4VKC…')).toBe('めたたろ');
  });

  it('どちらも無ければ、鍵の頭で呼ぶ', () => {
    // **知らない相手を、知っているように見せない**
    expect(呼ぶ名(undefined, undefined, '4VKC…')).toBe('4VKC…');
    expect(呼ぶ名(undefined, { 名前: '', 紹介: 'ひとこと' }, '4VKC…')).toBe('4VKC…');
  });

  it('呼び名と名乗りが違うときは、名乗りも添える', () => {
    // **違っていることが、その場で分かる必要がある**
    expect(名乗りを添えるか('mac air', { 名前: 'べつじん', 紹介: '' })).toBe(true);
  });

  it('同じなら添えない', () => {
    expect(名乗りを添えるか('めたたろ', { 名前: 'めたたろ', 紹介: '' })).toBe(false);
  });

  it('呼び名を付けていない相手には添えない', () => {
    // 名乗りがそのまま名前になっているので、二度出さない
    expect(名乗りを添えるか(undefined, { 名前: 'めたたろ', 紹介: '' })).toBe(false);
  });
});
