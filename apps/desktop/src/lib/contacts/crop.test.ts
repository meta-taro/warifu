// **64 KB に収まらない**（オーナー・2026-09-10「クロップですが、64 KB に
// 収まりませんでしたとでて保存できません」）
// ---------------------------------------------------------------------------

/** 試験用の出し口。**頼んだ形を覚え、決めた大きさを返す。** */
function 作りものの口(
  返す: (型: string, 質: number, 一辺: number) => { 型: string; 大きさ: number } | null,
) {
  const 頼まれた: { 型: string; 質: number; 一辺: number }[] = [];
  const 口: 絵を出す口 = async (型, 質, 一辺) => {
    頼まれた.push({ 型, 質, 一辺 });
    const 出た = 返す(型, 質, 一辺);
    if (!出た) return null;
    return {
      型: 出た.型,
      大きさ: 出た.大きさ,
      中身: async () => new Uint8Array(出た.大きさ),
    };
  };
  return { 口, 頼まれた };
}

describe('64 KB に収める（D87・2026-09-10 の不具合）', () => {
  it('WebP が出せて収まるなら、WebP を返す', async () => {
    const { 口, 頼まれた } = 作りものの口(() => ({ 型: 'image/webp', 大きさ: 20_000 }));
    const 出た = await 収まるまで出す(口);
    expect(出た.型).toBe('image/webp');
    expect(出た.中身.length).toBe(20_000);
    // **いちばん良い質から試す**
    expect(頼まれた[0]).toEqual({ 型: 'image/webp', 質: 質の段[0], 一辺: 辺の段[0] });
  });

  it('WebP を頼んだのに別の形が返ってきたら、JPEG に切り替える', async () => {
    // **これが 2026-09-10 の不具合である。**
    // WebP を出せない webview は、黙って PNG を返す ——
    // 写真の 512px PNG は 64 KB に入らないので、**必ず失敗していた**
    const { 口, 頼まれた } = 作りものの口((型) =>
      型 === 'image/webp'
        ? { 型: 'image/png', 大きさ: 400_000 }
        : { 型: 'image/jpeg', 大きさ: 30_000 },
    );
    const 出た = await 収まるまで出す(口);
    expect(出た.型).toBe('image/jpeg');
    // **PNG が返ると分かった時点で、WebP を粘らない**（質を 7 段も試さない）
    expect(頼まれた.filter((t) => t.型 === 'image/webp').length).toBe(1);
  });

  it('質を落としても収まらなければ、一辺を落とす', async () => {
    const { 口, 頼まれた } = 作りものの口((型, 質, 一辺) => ({
      型,
      // 512px はどの質でも入らない。384px なら入る
      大きさ: 一辺 >= 512 ? 100_000 : 50_000,
    }));
    const 出た = await 収まるまで出す(口);
    expect(出た.中身.length).toBe(50_000);
    expect(頼まれた.some((t) => t.一辺 === 384)).toBe(true);
  });

  it('どうしても収まらなければ、実際の形と大きさを添えて投げる', async () => {
    const { 口 } = 作りものの口(() => ({ 型: 'image/webp', 大きさ: 999_999 }));
    // **「収まりませんでした」だけでは、次に何をすればよいか分からない**
    await expect(収まるまで出す(口)).rejects.toThrow(/999999|976|image\/webp/);
  });

  it('64 KB ぴったりは通す', async () => {
    const { 口 } = 作りものの口(() => ({ 型: 'image/webp', 大きさ: 顔の上限 }));
    await expect(収まるまで出す(口)).resolves.toBeTruthy();
  });

  it('出し口が何も返さなくても落ちない（次の質へ進む）', async () => {
    let 回 = 0;
    const { 口 } = 作りものの口(() => (回++ === 0 ? null : { 型: 'image/webp', 大きさ: 10_000 }));
    await expect(収まるまで出す(口)).resolves.toBeTruthy();
  });
});
