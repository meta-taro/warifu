import { describe, expect, it } from 'vitest';
import { まん中の枠, 寄れる下限, 枠を収める, 見せる倍率 } from './crop';

describe('切り取る枠（D87）', () => {
  it('横長の画像は、真ん中の正方形になる', () => {
    expect(まん中の枠(200, 100)).toEqual({ 辺: 100, x: 50, y: 0 });
  });

  it('縦長の画像も、真ん中の正方形になる', () => {
    expect(まん中の枠(100, 300)).toEqual({ 辺: 100, x: 0, y: 100 });
  });

  it('枠が外へ出たら、内へ戻す', () => {
    // **縁が欠けた顔を作らない**
    expect(枠を収める({ x: -50, y: -50, 辺: 80 }, 200, 200)).toEqual({ x: 0, y: 0, 辺: 80 });
    expect(枠を収める({ x: 500, y: 500, 辺: 80 }, 200, 200)).toEqual({
      x: 120,
      y: 120,
      辺: 80,
    });
  });

  it('枠は画像より大きくならない', () => {
    expect(枠を収める({ x: 0, y: 0, 辺: 999 }, 200, 100).辺).toBe(100);
  });

  it('枠が小さすぎるところまでは縮まない', () => {
    // **1px の顔を作らせない**
    expect(枠を収める({ x: 0, y: 0, 辺: 1 }, 200, 200).辺).toBe(16);
  });
});

describe('見せる倍率（D87・2026-09-10 の不具合）', () => {
  it('枠を小さくすると、絵は大きく映る', () => {
    // オーナー指摘「**クロップうまくできません**」——
    // 倍率を「画像の短辺 → 窓」で固定していたので、**枠を小さくしても
    // 絵が大きくならなかった**（いつも真ん中の正方形が出るだけだった）
    expect(見せる倍率(320, 320)).toBe(1);
    expect(見せる倍率(320, 160)).toBe(2);
    expect(見せる倍率(320, 640)).toBe(0.5);
  });

  it('枠が 0 なら 1 を返す（0 で割らない）', () => {
    expect(見せる倍率(320, 0)).toBe(1);
    expect(見せる倍率(0, 320)).toBe(1);
  });
});

describe('寄れる下限', () => {
  it('短辺の 1/8 か 64px の大きい方', () => {
    expect(寄れる下限(4000, 3000)).toBe(375);
    expect(寄れる下限(400, 300)).toBe(64);
  });

  it('画像より大きくならない', () => {
    // **32px の絵に 64px の枠は置けない**
    expect(寄れる下限(32, 32)).toBe(32);
  });
});
