import { describe, expect, it } from 'vitest';
import { まん中の枠, 枠を収める } from './crop';

describe('切り取る枠（D87）', () => {
  it('横長の画像は、真ん中の正方形になる', () => {
    expect(まん中の枠(200, 100)).toEqual({ 辺: 100, x: 50, y: 0 });
  });

  it('縦長の画像も、真ん中の正方形になる', () => {
    expect(まん中の枠(100, 300)).toEqual({ 辺: 100, x: 0, y: 100 });
  });

  it('枠が外へ出たら、内へ戻す', () => {
    // **縁が欠けた顔を作らない**
    expect(枠を収める({ x: -50, y: -50, 辺: 80 }, 200, 200)).toEqual({ x: 0, y: 0, 辺: 80 });
    expect(枠を収める({ x: 500, y: 500, 辺: 80 }, 200, 200)).toEqual({
      x: 120,
      y: 120,
      辺: 80,
    });
  });

  it('枠は画像より大きくならない', () => {
    expect(枠を収める({ x: 0, y: 0, 辺: 999 }, 200, 100).辺).toBe(100);
  });

  it('枠が小さすぎるところまでは縮まない', () => {
    // **1px の顔を作らせない**
    expect(枠を収める({ x: 0, y: 0, 辺: 1 }, 200, 200).辺).toBe(16);
  });
});
