// それまでは、**1 行だけ**書いてあった（「相手を選ぶと、できることが出ます。」）。
// 開いた人が最初に見る所なのに、**この道具が何をするものか**が書いていなかった。
//
// **ここに数字を作らない。**出すのは、連絡帳が既に持っている数だけである。

import type { 口の種類, 状態 } from './actions';
import type { 素材 } from './list';

/** いまの様子（**数えるだけ。判断しない**）。 */
export interface 様子 {
  /** このPCにつながっているエージェントのエージェント数。 */
  エージェント: number;
  /** いま居るルームの数。 */
  ルーム: number;
  /** そのルームに居る人の数（自分を含む・重複は数えたまま）。 */
  ルームの人: number;
  /** 覚えている相手の数。 */
  覚えた: number;
  /** 預かり所を置いているか。 */
  預かり所: boolean;
}

/** 連絡帳の素材から、いまの様子を数える。 */
export function いまの様子(素材: 素材, 預かり所がある: boolean): 様子 {
  const ルームたち = 素材.ルームたち ?? [];
  return {
    エージェント: 素材.このPCのAIたち.length,
    ルーム: ルームたち.length,
    // **居る人はルームごとに数える。**同じ人が 2 室に居れば 2 と出る ——
    // 「何人と話せるか」ではなく「どこに何人居るか」を出している所である
    ルームの人: ルームたち.reduce((足す, ルーム) => 足す + ルーム.members, 0),
    覚えた: 素材.覚えた.length,
    預かり所: 預かり所がある,
  };
}

/** 初期画面に出す 1 枚。**相手を選んでいないので、押せる口は無い。** */
export interface 案内 {
  種類: 口の種類;
  状態: 状態;
  /** その 1 行（文言の鍵）。 */
  訳: string;
}

/**
 * この道具でできること（**相手に依らない一般形**）。
 *
 * 相手を選んだときの札（`actions.ts`）とは**別**である ——
 * あちらは「その相手に」できること、こちらは「この道具で」できること。
 * **状態の付け方は揃える**（できる／条件つき／まだできない）。
 */
export function できることの案内(): 案内[] {
  return [
    { 種類: 'chat', 状態: 'できる', 訳: 'home.chat' },
    { 種類: 'group', 状態: 'できる', 訳: 'home.group' },
    // **網を越えて繋がったことを、まだ一度も見ていない**（実測 0 件・D88）
    { 種類: 'call', 状態: '条件つき', 訳: 'home.call' },
    // **2026-09-10 から動く。**自分の予定は置ける（相手の予定は見えない）
    { 種類: 'calendar', 状態: 'できる', 訳: 'home.calendar' },
  ];
}

/**
 * **はじめの一歩を出すか。**
 *
 * 誰も覚えておらず、このPCにも誰も着いていないなら、**この画面から先へ進めない。**
 * そのときだけ、どこを押すかを言う。
 */
export function はじめの一歩を出すか(様子: 様子): boolean {
  return 様子.覚えた === 0 && 様子.エージェント === 0 && 様子.ルーム === 0;
}
