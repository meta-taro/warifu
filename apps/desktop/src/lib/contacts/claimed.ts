// **相手が名乗った名前**（**D75**）。
//
// **これは本人確認ではない。**名乗った名前は誰でも真似できる ——
// `mac air` と呼んでいる相手の隣に、別人が「mac air」と名乗って並べる。
//
// だから **こちらが付けた呼び名が勝つ**（**D46**）。
// 名乗りは、呼び名を付けていない相手にだけ出す。

/** 相手が名乗ったもの。 */
export interface 名乗り {
  名前: string;
  紹介: string;
}

/** 公開鍵 → 名乗り。 */
export type 名乗りたち = Readonly<Record<string, 名乗り>>;

/**
 * その相手を、画面で何と呼ぶか。
 *
 * **こちらが付けた呼び名が最優先。**次に本人の名乗り、最後に鍵の頭。
 * **名乗りをそのまま名前にしない** —— 呼び名を付けた相手の名前が、
 * 相手の都合で変わってしまう。
 */
export function 呼ぶ名(
  呼び名: string | undefined,
  名乗り: 名乗り | undefined,
  既定: string,
): string {
  if (呼び名) return 呼び名;
  if (名乗り?.名前) return 名乗り.名前;
  return 既定;
}

/**
 * 名乗りを「本人の名乗り」として添えるか。
 *
 * **こちらが呼び名を付けている相手には添える** ——
 * 呼び名と名乗りが違うことが、その場で分かる必要がある。
 * 付けていない相手には、名乗りがそのまま名前になっているので添えない。
 */
export function 名乗りを添えるか(呼び名: string | undefined, 名乗り: 名乗り | undefined): boolean {
  return !!呼び名 && !!名乗り?.名前 && 呼び名 !== 名乗り.名前;
}
