// 在エージェントの印。**分かる所にだけ出す。**
//
// オーナー指摘（2026-09-10）——
// 「**たとえば slack discoard では、オンラインオフラインアイコンがつきますね。
// わかります？ UX がたりないことが。**」
//
// そのとおりである。**印が無いのに「切れている」と読ませていた。**
//
// ただし **Slack と同じにはできない。**あちらは真ん中の機械が全員の在エージェントを知っている。
// 割符には真ん中が無いので、**ほかの人が起動しているかは分からない**
// （DESIGN §2 原則 7 / `issues/010` 段 4）。
//
// **分かるのは、この PC の中だけ** —— 自分と、口につながっているエージェントである。
// だから**印を出すのもそこだけ**にする。**分からないものを ○ と書かない。**

import type { 行 } from './list';

/** 在エージェントの印。**出さないなら `null`。** */
export type 在エージェント = 'つながっている' | '切れている';

/**
 * その行に出す印。**分からない相手には `null` を返す。**
 *
 * `いま会議に居る` は、この PC のエージェントでは「**口につながっているか**」である
 * （`list.ts` がそう詰めている）。
 */
export function 在エージェントの印(行: 行): 在エージェント | null {
  // **この窓が動いているなら、あなたは居る**
  if (行.種類 === '自分') return 'つながっている';
  if (行.種類 === 'AI') return 行.いま会議に居る ? 'つながっている' : '切れている';
  // **ほかの人とルームには出さない。**相手が起動しているかは分からない
  return null;
}
