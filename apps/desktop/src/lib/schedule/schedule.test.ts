import { describe, expect, it } from 'vitest';

import {
  いま進んでいる,
  これから,
  終わったもの,
  日にする,
  時刻にする,
  秒にする,
  長さの分,
  type 予定,
} from './schedule';

const 作る = (start: number, end: number, title = '打ち合わせ'): 予定 => ({
  start,
  end,
  title,
  note: '',
});

describe('予定の並べ方', () => {
  it('これからの予定だけを、早い順に出す', () => {
    // **終わった予定を上に出さない。**人が見たいのは次に来るもの
    const 予定たち = [作る(300, 400, 'あと'), 作る(50, 80, 'おわった'), 作る(100, 200, 'つぎ')];
    expect(これから(予定たち, 90).map((x) => x.title)).toEqual(['つぎ', 'あと']);
  });

  it('いま進んでいる予定は、これからに入れる', () => {
    // **始まっているが終わっていない。**消えると「何の会だっけ」になる
    expect(これから([作る(100, 200)], 150)).toHaveLength(1);
  });

  it('終わった予定は消さず、新しい順で持つ', () => {
    const 予定たち = [作る(10, 20, 'ふるい'), 作る(50, 60, 'あたらしい')];
    expect(終わったもの(予定たち, 100).map((x) => x.title)).toEqual(['あたらしい', 'ふるい']);
  });

  it('いま進んでいるかを見分ける', () => {
    const 一つ = 作る(100, 200);
    expect(いま進んでいる(一つ, 99)).toBe(false);
    expect(いま進んでいる(一つ, 100)).toBe(true);
    expect(いま進んでいる(一つ, 199)).toBe(true);
    expect(いま進んでいる(一つ, 200)).toBe(false);
  });

  it('長さを分で出す', () => {
    expect(長さの分(作る(0, 3600))).toBe(60);
    expect(長さの分(作る(0, 0))).toBe(0);
  });
});

describe('人が書いた日と時刻を秒に直す', () => {
  it('地元の時計で読む', () => {
    const 秒 = 秒にする('2026-09-11', '09:30');
    expect(秒).not.toBeNull();
    expect(日にする(秒 ?? 0)).toBe('2026-09-11');
    expect(時刻にする(秒 ?? 0)).toBe('09:30');
  });

  it('読めない形は null（0 にしない）', () => {
    // **0 にすると 1970 年の予定が入る**
    for (const [日, 時] of [
      ['', '09:30'],
      ['2026-9-11', '09:30'],
      ['2026-09-11', '9時半'],
      ['2026-09-11', '25:00'],
      ['2026-09-11', '09:70'],
    ]) {
      expect(秒にする(日, 時), `${日} ${時}`).toBeNull();
    }
  });

  it('存在しない日は null（繰り上がりを黙って通さない）', () => {
    // **2 月 30 日は 3 月 2 日ではない**
    expect(秒にする('2026-02-30', '09:00')).toBeNull();
  });

  it('1 桁の時も読める', () => {
    expect(秒にする('2026-09-11', '9:05')).not.toBeNull();
  });
});
