import { describe, expect, it } from 'vitest';
import {
  鍵の口を出す,
  支度の口を出す,
  画面の状態を決める,
  届く先がある,
  映像を出すか,
  抜けたら畳む,
  つながりの言い方,
} from './stage';

describe('画面の状態', () => {
  it('何もしていなければ会議前', () => {
    expect(画面の状態を決める({ 相手: 0, 会議キー: false, 人が入った: false })).toBe('会議前');
    expect(鍵の口を出す('会議前')).toBe(true);
  });

  it('相手が居れば会議中', () => {
    expect(画面の状態を決める({ 相手: 1, 会議キー: true, 人が入った: true })).toBe('会議中');
    expect(鍵の口を出す('会議中')).toBe(false);
  });

  it('会議キーを出して待っている間は、会議前へ戻さない', () => {
    // 戻すと、したく・はじめる・入室する が一度に出て、
    // **チャットと名簿が窓の外（下へ 442px）へ押し出される**
    expect(画面の状態を決める({ 相手: 0, 会議キー: true, 人が入った: false })).toBe('待っている');
    expect(鍵の口を出す('待っている')).toBe(false);
  });

  it('この機械のエージェントと話しただけでは、会議前のままにする', () => {
    // **2026-09-09 に実物で踏んだ。**行数で数えていたので、
    // この機械と 1 行話しただけで `ルームをつくる` が消え、**以後だれも呼べなくなっていた**
    expect(画面の状態を決める({ 相手: 0, 会議キー: false, 人が入った: false })).toBe('会議前');
  });

  it('相手が落ちた直後も、会議前へ戻さない', () => {
    // **落ちた知らせがチャットに出るのは、まさにこの瞬間である。**
    // 2026-09-05 に D44 を確かめたとき、その 1 行を目で見つけられなかった
    expect(画面の状態を決める({ 相手: 0, 会議キー: false, 人が入った: true })).toBe('待っている');
  });
});

describe('届く先がある', () => {
  it('会議に人が居れば送れる', () => {
    expect(届く先がある({ 相手: 1, この機械の人数: 0 })).toBe(true);
  });

  it('会議に誰も居なくても、同じエージェントの AI が居れば送れる', () => {
    // **2026-09-07、オーナーが「こんにちは」と打って送れなかった。**
    // AI は画面に書けるのに人は返せない、という片側だけの経路になっていた。
    // 「会議ありきのチャットじゃないんです」（2026-09-06）
    expect(届く先がある({ 相手: 0, この機械の人数: 1 })).toBe(true);
  });

  it('どちらも居なければ送れない', () => {
    // **押せる形にして「まだ誰も居ません」と返すのはしない**（D49）
    expect(届く先がある({ 相手: 0, この機械の人数: 0 })).toBe(false);
  });
});

describe('映像を出すか（グループチャットとビデオ会議を分ける）', () => {
  it('既定では出さない（開いた人のカメラを勝手に点けない）', () => {
    expect(映像を出すか({ 映像を使う: false, 支度した: false, 相手が居る: false })).toBe(false);
    // **相手が居ても、こちらが選んでいなければ出さない**
    expect(映像を出すか({ 映像を使う: false, 支度した: true, 相手が居る: true })).toBe(false);
  });

  it('選んで、機器が取れていれば出す', () => {
    expect(映像を出すか({ 映像を使う: true, 支度した: true, 相手が居る: false })).toBe(true);
  });

  it('選んでいて、相手の映像が来ているなら出す（機器が無くても）', () => {
    // カメラもマイクも無い機械はある（この mac mini がそう）
    expect(映像を出すか({ 映像を使う: true, 支度した: false, 相手が居る: true })).toBe(true);
  });

  it('選んだだけで、機器も相手も無ければ出さない', () => {
    expect(映像を出すか({ 映像を使う: true, 支度した: false, 相手が居る: false })).toBe(false);
  });
});

describe('ルームキーの口と、支度の口は別もの', () => {
  // ASUS のエージェント・2026-09-12（実物を触って）——
  //
  // > ご案内の手順を試しましたが、Windows 版には「もらったルームキーでルームに入る」が
  // > ありません。連絡帳にもルームにも無く、MSI 版・NSIS 版どちらの中身でも同じ画面でした。
  //
  // **Windows のせいではなかった。**`映像を使う` が 3 枚まとめて包んでいたため、
  // **文字だけのルーム（既定）では、入れたばかりの人が入る口を持てない。**
  // D90 でビデオ会議を分けたときに、鍵の 2 枚を巻き込んだ。

  it('**入れたばかり（文字だけ）でも、ルームキーの口は出す**', () => {
    expect(鍵の口を出す('会議前')).toBe(true);
  });

  it('待っている間・会議中は、鍵の口を出さない（チャットと名簿を押し出さない）', () => {
    expect(鍵の口を出す('待っている')).toBe(false);
    expect(鍵の口を出す('会議中')).toBe(false);
  });

  it('**カメラの支度は、ビデオ会議を使うときだけ**（文字だけの人に見せない）', () => {
    expect(支度の口を出す('会議前', true)).toBe(true);
    expect(支度の口を出す('会議前', false)).toBe(false);
  });

  it('会議中は支度の口も出さない', () => {
    expect(支度の口を出す('会議中', true)).toBe(false);
  });
});

describe('抜けたら畳む（#33）', () => {
  it('**畳んだ姿を当てると、会議前に戻る**', () => {
    // ASUS の実測 —— 抜けたあと画面が「抜けた側」を映したまま動かず、
    // **［ルームをつくる］も［もらったルームキーで入る］も消えたまま**だった
    const 畳 = 抜けたら畳む();
    const 状態 = 画面の状態を決める({
      相手: 畳.相手たち.length,
      会議キー: !!畳.会議キー,
      人が入った: 畳.人が入った,
    });
    expect(状態).toBe('会議前');
    expect(鍵の口を出す(状態)).toBe(true);
  });

  it('**映像も支度も畳む**（枠が黒いまま残らない）', () => {
    const 畳 = 抜けたら畳む();
    expect(畳.映像を使う).toBe(false);
    expect(畳.支度した).toBe(false);
    expect(畳.送るもの).toBe('none');
  });

  it('**選んでいた行を外す**（無くなった行を選んだままにしない）', () => {
    expect(抜けたら畳む().選んだ相手).toBeNull();
  });

  it('**畳むものを一覧で持つ**（1 つ落とすと不具合が戻る）', () => {
    // **次に項目を増やしたら、ここが落ちる。**それが目的
    expect(Object.keys(抜けたら畳む()).sort()).toEqual(
      [
        '人が入った',
        '会議キー',
        '名簿',
        '送るもの',
        '支度した',
        '映像を使う',
        '相手たち',
        '選んだ相手',
      ].sort(),
    );
  });
});

describe('つながりの言い方（#39・D113）', () => {
  it('**受けているのに送っていないときは、そう言う**', () => {
    // 「つながっています」しか出していなかったので、**人は「壊れている」と読んだ**
    expect(つながりの言い方({ 相手が居る: true, 受けている: true, 送っている: false })).toBe(
      'meeting.status.recvonly',
    );
  });

  it('送っているのに受けていないときも、そう言う', () => {
    expect(つながりの言い方({ 相手が居る: true, 受けている: false, 送っている: true })).toBe(
      'meeting.status.sendonly',
    );
  });

  it('両方流れていれば、そう言う', () => {
    expect(つながりの言い方({ 相手が居る: true, 受けている: true, 送っている: true })).toBe(
      'meeting.status.both',
    );
  });

  it('文字だけなら、文字だけと言う（**カメラが点いていないことを隠さない**）', () => {
    expect(つながりの言い方({ 相手が居る: true, 受けている: false, 送っている: false })).toBe(
      'meeting.status.textonly',
    );
  });

  it('相手が居なければ、待っていると言う', () => {
    expect(つながりの言い方({ 相手が居る: false, 受けている: false, 送っている: false })).toBe(
      'meeting.status.wait',
    );
  });
});
