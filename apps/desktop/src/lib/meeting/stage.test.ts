import { describe, expect, it } from 'vitest';
import { 準備を出す, 画面の状態を決める } from './stage';

describe('画面の状態', () => {
  it('何もしていなければ会議前', () => {
    expect(画面の状態を決める({ 相手: 0, 会議キー: false, 会話: 0 })).toBe('会議前');
    expect(準備を出す('会議前')).toBe(true);
  });

  it('相手が居れば会議中', () => {
    expect(画面の状態を決める({ 相手: 1, 会議キー: true, 会話: 3 })).toBe('会議中');
    expect(準備を出す('会議中')).toBe(false);
  });

  it('会議キーを出して待っている間は、会議前へ戻さない', () => {
    // 戻すと、したく・はじめる・入室する が一度に出て、
    // **チャットと名簿が窓の外（下へ 442px）へ押し出される**
    expect(画面の状態を決める({ 相手: 0, 会議キー: true, 会話: 0 })).toBe('待っている');
    expect(準備を出す('待っている')).toBe(false);
  });

  it('相手が落ちた直後も、会議前へ戻さない', () => {
    // **落ちた知らせがチャットに出るのは、まさにこの瞬間である。**
    // 2026-09-05 に D44 を確かめたとき、その 1 行を目で見つけられなかった
    expect(画面の状態を決める({ 相手: 0, 会議キー: false, 会話: 2 })).toBe('待っている');
  });
});
