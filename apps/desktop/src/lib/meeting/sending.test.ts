import { describe, expect, it } from 'vitest';
import { ハウリングの危険, 送ってよいか } from './sending';

describe('送ってよいか', () => {
  it('押していないなら、音も映像も送らない', () => {
    // **2026-09-17 の音漏れ。**`マイク入` は前の会議から持ち越される（loadPrefs）ので、
    // これが無いと**入った瞬間に音が流れる**
    expect(
      送ってよいか({ 映像を使う: false, マイク入: true, カメラ入: true, 測れた: true }),
    ).toEqual({ 音: false, 映像: false });
  });

  it('押していないなら、測れていても送らない', () => {
    expect(送ってよいか({ 映像を使う: false, マイク入: true, カメラ入: false, 測れた: true }).音).toBe(
      false,
    );
  });

  it('押したら、支度の入切に従う', () => {
    expect(
      送ってよいか({ 映像を使う: true, マイク入: true, カメラ入: true, 測れた: true }),
    ).toEqual({ 音: true, 映像: true });
  });

  it('マイクを切にしていれば、押しても音は送らない', () => {
    // **人の指定が勝つ**（支度で切ったものを、参加が入に戻さない）
    expect(
      送ってよいか({ 映像を使う: true, マイク入: false, カメラ入: true, 測れた: true }).音,
    ).toBe(false);
  });

  it('測れるまで映像は流さない（D29）', () => {
    // **音は測りを待たない。**声は細いので、測る前から通してよい
    const 出た = 送ってよいか({ 映像を使う: true, マイク入: true, カメラ入: true, 測れた: false });
    expect(出た.映像).toBe(false);
    expect(出た.音).toBe(true);
  });

  it('カメラを切にしていれば、測れても映像は流さない', () => {
    expect(
      送ってよいか({ 映像を使う: true, マイク入: false, カメラ入: false, 測れた: true }).映像,
    ).toBe(false);
  });
});

describe('ハウリングの危険', () => {
  it('自分が黙っていれば、こちらからは回らない', () => {
    expect(
      ハウリングの危険({ 音を送っている: false, 音を受けている数: 2, 同じ網の相手: 2 }),
    ).toBe(false);
  });

  it('同じ網に相手が居て、音が往復しているなら危ない', () => {
    // **机の隣に別の端末が在る形。**エコー除去は自分の出力しか知らない
    expect(
      ハウリングの危険({ 音を送っている: true, 音を受けている数: 1, 同じ網の相手: 1 }),
    ).toBe(true);
  });

  it('別の網の相手だけなら、案内しない', () => {
    // **無駄に出す警告は読まれなくなる**（#33 / #35 で踏んだ形）
    expect(
      ハウリングの危険({ 音を送っている: true, 音を受けている数: 2, 同じ網の相手: 0 }),
    ).toBe(false);
  });

  it('相手が誰も音を出していないなら、案内しない', () => {
    expect(
      ハウリングの危険({ 音を送っている: true, 音を受けている数: 0, 同じ網の相手: 2 }),
    ).toBe(false);
  });
});
