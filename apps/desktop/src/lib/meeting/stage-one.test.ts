import { describe, expect, it } from 'vitest';
import { 映像を始めてよいか, 映像の札 } from './stage-one';

describe('映像を始めてよいか', () => {
  it('どこにも付いていなければ、そのまま始める', () => {
    expect(映像を始めてよいか({ 映像がある部屋: null, 始めたい部屋: 'A' })).toEqual({
      どうする: '始める',
    });
  });

  it('**別の部屋に付いていたら、移すかを尋ねる。黙って 2 つ目を始めない**', () => {
    // オーナー（2026-09-16）——「**カメラ付き音声は人あってこそなので、
    // 通常 同時に会議はできません。**」**人は 2 つの会議に出られない**ので、
    // 黙って始めると**必ず片方が放置になる**
    expect(映像を始めてよいか({ 映像がある部屋: 'A', 始めたい部屋: 'B' })).toEqual({
      どうする: '移すか尋ねる',
      いまの部屋: 'A',
    });
  });

  it('同じ部屋なら、すでに付いている（二重に始めない）', () => {
    expect(映像を始めてよいか({ 映像がある部屋: 'A', 始めたい部屋: 'A' })).toEqual({
      どうする: 'すでに付いている',
    });
  });

  it('部屋が決まっていなければ始められない（どこに付けるか分からない）', () => {
    expect(映像を始めてよいか({ 映像がある部屋: null, 始めたい部屋: null })).toEqual({
      どうする: '部屋がない',
    });
  });
});

describe('映像の札', () => {
  it('映像が付いている部屋にだけ、札を出す', () => {
    expect(映像の札('A', 'A')).toBe(true);
    expect(映像の札('B', 'A')).toBe(false);
  });

  it('どこにも付いていなければ、どの部屋にも出さない', () => {
    expect(映像の札('A', null)).toBe(false);
  });
});
