/**
 * **何を送ってよいか。**
 *
 * ## なぜ 1 つの所で決めるのか
 *
 * **2026-09-17 に、音だけが漏れていた。**Mac Air の実測 ——
 *
 * ```text
 * 押す前   送り 映像 0 / 音 90    ← ［ビデオ会議を始める］を押していない
 * 押す前   送り 映像 0 / 音 91
 * 押した後 送り 映像 355863 / 音 96634
 * ```
 *
 * **同じ窓の中で、画面はこう言っていた。**
 *
 * ```text
 * このルームは、いま文字だけです。カメラもマイクも使っていません。
 * ```
 *
 * オーナー ——「**なのに、相手には、もう見えている、、、プライバシーもへったくれもないな**」
 *
 * ## 原因は、**条件の数が違っていたこと**
 *
 * | | それまでの関門 |
 * |---|---|
 * | 映像 | `カメラ入` **かつ** `測れた`（**D29**） |
 * | 音 | **`マイク入` だけ** |
 * |
 * `マイク入` は**次の起動へ持ち越される**（`loadPrefs`）。
 * だから**前の会議で 1 度マイクを入れた人は、以後どの部屋でも、
 * 入った瞬間から音を送る。**押していないのに送る。
 *
 * ## 決めたこと
 *
 * **この部屋で「映像と音を足す」と決めていないなら、音も映像も送らない。**
 * **D113**（支度を通ってから参加する）を、送り側の 1 か所で守らせる。
 *
 * **「送らない」は「繋がない」ではない。**文字は流れ、相手の映像と音は受け取る ——
 * **受け取る枠は張ったまま**にする（張らないと相手から何も来ない）。
 *
 * ## いま効いているのは音だけ（**正直に書いておく**）
 *
 * **`映像` はここで決めているが、送り手はまだ従っていない。**
 * 支度の「自分の姿」と送り手が**同じトラックを見ている**ので、
 * 切ると**自分の姿まで黒くなる。**
 * **送らずに自分だけ見る**には `sender.replaceTrack(null)` が要り、
 * それは支度と参加を分ける仕事（**#39 の 3**）に属する。
 *
 * **漏れていたのは音だけ**（映像は 3 回とも実測 0 パケット）なので、
 * **いま塞ぐのは音**にした。**`映像` の答えは、その仕事で使う。**
 */

/** 送ってよいものの答え。**トラックの `enabled` に、そのまま入れる。** */
export type 送るもの = {
  /** マイクの音を流すか。 */
  音: boolean;
  /** カメラの映像を流すか。 */
  映像: boolean;
};

/**
 * **送ってよいかを決める。**
 *
 * `映像を使う` が偽なら、**何も送らない** —— これが今回足した関門である。
 *
 * @param いま 部屋での決め（`映像を使う`）と、支度での入切と、測れたか
 */
export function 送ってよいか(いま: {
  /** **この部屋で「映像と音を足す」と決めたか。**押していなければ偽。 */
  映像を使う: boolean;
  /** 支度でマイクを入にしたか。 */
  マイク入: boolean;
  /** 支度でカメラを入にしたか。 */
  カメラ入: boolean;
  /** 回線を測れたか（**D29** —— 測る前に映像を出さない）。 */
  測れた: boolean;
}): 送るもの {
  // **押していないなら、何も送らない。**
  // ここを「音だけは送ってよい」にすると、画面の文言が嘘になる
  if (!いま.映像を使う) return { 音: false, 映像: false };
  return {
    音: いま.マイク入,
    映像: いま.カメラ入 && いま.測れた,
  };
}

/**
 * **ハウリングの危険が、いま在るか。**
 *
 * エコー除去は**自分の出力しか知らない。**
 * **隣の机の別の端末から出た音は、消せない**（`AUDIO_PROCESSING` の注記）。
 *
 * **支度のときだけ案内していた。**それでは遅い ——
 * **危なくなるのは「2 人目が音を出した時」**であって、支度の時ではない。
 *
 * @param いま 自分が音を出しているか、音を出している相手の数、同じ網に何人居るか
 */
export function ハウリングの危険(いま: {
  /** 自分がマイクを流しているか。 */
  音を送っている: boolean;
  /** 音が届いている相手の数。 */
  音を受けている数: number;
  /** **同じ網に居る相手の数。**近くに居る手がかりになる（確証ではない）。 */
  同じ網の相手: number;
}): boolean {
  // **自分が黙っているなら、こちらからは回らない。**
  // 相手同士で回ることは在りうるが、**それはその人の画面が言う**
  if (!いま.音を送っている) return false;
  // **音を出している相手が居て、その相手が同じ網に居るとき。**
  // 同じ網は「近い」の手がかり —— **別の網なら、机の隣に居ることはまず無い**
  return いま.音を受けている数 > 0 && いま.同じ網の相手 > 0;
}
