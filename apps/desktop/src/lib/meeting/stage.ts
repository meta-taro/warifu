// 画面がいまどの状態にあるか。
//
// **「会議前」と「会議中」の 2 つでは足りない**（2026-09-06 に実測で分かった）。
// `相手が 1 人以上` だけを会議中にしていたため、
//
//   - 会議キーを出して、相手を待っている間
//   - 相手が落ちて、会議が終わった直後
//
// のどちらも「会議前」へ丸ごと戻り、**したく・会議をはじめる・入室する が
// 一度に出てきて、チャットと名簿を窓の外（下へ 442px）へ押し出していた。**
//
// **相手が落ちた知らせがチャットに出るのは、まさにこの瞬間である。**
// 2026-09-05 に D44 を確かめたとき、その 1 行を目で見つけられなかった。

/** 画面の状態。**準備の口を出すのは「会議前」だけ。** */
export type 画面の状態 = '会議前' | '待っている' | '会議中';

/** いまの状態を決める。**判断はここ 1 か所に置く**（画面の各所で書くとずれる）。 */
export function 画面の状態を決める(いま: {
  /** つながっている相手の数。 */
  相手: number;
  /** 自分の会議キーを出しているか。 */
  会議キー: boolean;
  /**
   * **一度でも人がルームに入ったか。**
   *
   * **チャットの行数では数えない**（2026-09-09 に実物で踏んだ）——
   * この機械のエージェントと 1 行話しただけで「待っている」になり、
   * **`ルームをつくる` が消えて、以後だれも呼べなくなっていた。**
   *
   * 数えたいのは「**会議があったか**」であって、「何か喋ったか」ではない。
   */
  人が入った: boolean;
}): 画面の状態 {
  if (いま.相手 > 0) return '会議中';
  // **鍵を出した／一度でも人が入った後は、会議前へ戻さない。**
  // 戻すと、いま出たばかりの知らせとチャットが押し出される
  if (いま.会議キー || いま.人が入った) return '待っている';
  return '会議前';
}

/**
 * **ルームキーの口**（ルームキーを出す／もらったルームキーで入る）を出してよいか。
 *
 * **映像を使うかとは関係ない。**
 *
 * 2026-09-12、ASUS のエージェントが実物で踏んだ ——
 *
 * > ご案内の手順を試しましたが、Windows 版には「もらったルームキーでルームに入る」が
 * > ありません。連絡帳にもルームにも無く、MSI 版・NSIS 版どちらの中身でも同じ画面でした。
 *
 * **Windows のせいではなかった。**画面が
 * `{#if 支度の口を出す && 映像を使う}` で **3 枚まとめて包んでいた**ため、
 * **既定（文字だけ・D90）のままでは、入れたばかりの人が入る口を持てない。**
 * D90 でビデオ会議を分けたときに、鍵の 2 枚を巻き込んだ。
 *
 * **入る口が無いのは、製品として成り立っていない。**
 */
export function 鍵の口を出す(状態: 画面の状態): boolean {
  return 状態 === '会議前';
}

/**
 * **カメラの支度の口**を出してよいか。
 *
 * こちらは映像を使うときだけでよい —— **文字だけの人に、カメラの話を出さない。**
 */
export function 支度の口を出す(状態: 画面の状態, 映像を使う: boolean): boolean {
  return 状態 === '会議前' && 映像を使う;
}

/**
 * 打ったものに届く先があるか。
 *
 * **「相手が居ない」と「話し相手が 1 人も居ない」は違う。**
 * 会議に人が 1 人も居なくても、**同じエージェントのエージェント（この機械）が居るなら送れる。**
 *
 * オーナーの言（2026-09-06）——
 * 「**まず会議ありきではなく、チャットさえつながって**、
 * できればそれが GUI だとぐんと作業効率が上がります」
 * 「**会議ありきのチャットじゃないんです。**」
 *
 * 2026-09-07、オーナーが実際に「こんにちは」と打って**送れなかった。**
 * AI は画面に書けるのに人は返せない、という**片側だけの経路**になっていた。
 */
export function 届く先がある(場: { 相手: number; この機械の人数: number }): boolean {
  return 場.相手 > 0 || 場.この機械の人数 > 0;
}

/**
 * **映像を出すか。**
 *
 * オーナー指摘（2026-09-10）——
 * 「**ビデオ会議とグループチャットを分ける**」。
 *
 * 仕組みは 1 つである（ルームは映像も文字も同じ経路で運ぶ）。
 * 違うのは**人が何をしに来たか**で、
 *
 *   グループチャット …… ルームを作って**文字だけ**で使う。カメラもマイクも触らない
 *   ビデオ会議       …… 同じルームに**映像と音を足す**
 *
 * **既定は文字だけ。**開いた人のカメラを、頼まれてもいないのに点けない。
 */
export function 映像を出すか(いま: {
  /** 人が「ビデオ会議」を選んだか。 */
  映像を使う: boolean;
  /** 機器を取れているか（したくが済んでいるか）。 */
  支度した: boolean;
  /** つながっている相手が居るか。 */
  相手が居る: boolean;
}): boolean {
  if (!いま.映像を使う) return false;
  // **選んだだけでは出さない。**機器が取れているか、相手の映像が来ているとき
  return いま.支度した || いま.相手が居る;
}

/**
 * **部屋を抜けたら畳むもの**（**#33**・2026-09-16）。
 *
 * # 何が起きていたか（ASUS の実測）
 *
 * **［このルームを抜ける］で抜けたあと、ルーム画面が「抜けた側」を映したまま動かない。**
 *
 * ```text
 * 自分の枠が真っ黒                    ← 配管は畳まれたのに、枠だけ残っていた
 * 抜けた相手が枠に居る（○ 不明）        ← 経路だけ落ちて、行が残っていた
 * 届く先が、抜けた相手のまま
 * 左の見出しが「つながっています」のまま
 * ［ルームをつくる］が消えたまま        ← 状態が `会議前` へ戻っていない
 * ```
 *
 * **立ち上げ直すまで戻らなかった。**
 * ASUS ——「**抜けた人は、たいてい次に別のルームへ入りたい人です。**
 * その画面から**入る口も作る口も消えている**ので、
 * 『抜けたら、立ち上げ直すまで何もできない』という形になります。」
 *
 * # なぜ「全部畳む」でよいか
 *
 * **映像と音が付く部屋は 1 つだけ**（**D112**）。
 * 画面が映していたのは**抜けた部屋そのもの**なので、**残すものが無い。**
 *
 * # ここに一覧で書く理由
 *
 * **1 つ落とすと、この不具合が戻る。**畳むものを**データで持って、試験で縛る** ——
 * 次に誰かが項目を増やしたら、**落ちる側**に置いておく。
 */
export interface 畳むもの {
  /** 映していた相手（枠と経路）。 */
  相手たち: readonly never[];
  /** 名簿の行。 */
  名簿: readonly never[];
  /** **人が入った印**（これが残ると `会議前` へ戻らない）。 */
  人が入った: false;
  /** 映像と音（**機器を放す**。残ると枠が黒いまま）。 */
  映像を使う: false;
  /** 支度（カメラ・マイクを取り直せるように）。 */
  支度した: false;
  /** 送るもの。 */
  送るもの: 'none';
  /** 選んでいた行（**無くなった行を選んだままにしない**）。 */
  選んだ相手: null;
  /** 会議キー（**残ると「待っています」の帯が出たままになる**）。 */
  会議キー: null;
}

/**
 * 部屋を抜けたあとの姿。**そのまま当てれば、`会議前` に戻る。**
 */
export function 抜けたら畳む(): 畳むもの {
  return {
    相手たち: [],
    名簿: [],
    人が入った: false,
    映像を使う: false,
    支度した: false,
    送るもの: 'none',
    選んだ相手: null,
    会議キー: null,
  };
}

/**
 * **つながりの言い方**（**#39**・**D113**・2026-09-16）。
 *
 * 使った人 ——「**入った瞬間相手には映っているのに、こっちがビデオ会議を始める
 * ボタン押さないと見れないのはおかしい、最悪の UX です。**」
 *
 * **「つながっています」しか出していなかった。**
 * **人は「つながっている」と言われたら、映像も繋がったと思う** ——
 * 実際には**片方だけ流れている。**
 *
 * Mac Air の意見（#39）——
 *
 * > **いまの「片方だけ流れる」がいちばん悪い。**どちらかに揃っていれば、人は理解できます。
 * > **揃っていないので、人は「壊れている」と読みます。**——実際そう読まれました。
 *
 * **揃えるのではなく、言う**（**D113** —— 黙ってカメラを点けない）。
 */
export function つながりの言い方(いま: {
  相手が居る: boolean;
  受けている: boolean;
  送っている: boolean;
  /**
   * **カメラかマイクを掴んでいるか**（2026-09-17・ASUS の実測）。
   *
   * **掴んでいるのに「使っていません」と言うのは嘘である。**
   * ASUS が同じ窓の中で、題字とパネルが逆のことを言っているのを見つけた ——
   *
   * ```text
   * 題字    つながっています（**いま文字だけです。カメラもマイクも使っていません**）
   * パネル  **カメラとマイクは点いていますが、相手へは何も送っていません。**
   * ```
   *
   * **機械で測って、パネルが正しかった** ——
   * `msedgewebview2`（warifu の子）の録音の最大が **0.0181**。**マイクは点いていた。**
   *
   * **パネルだけ直して、題字に同じ嘘を残していた。**
   */
  掴んでいる: boolean;
}): string {
  if (!いま.相手が居る) return 'meeting.status.wait';
  if (いま.受けている && いま.送っている) return 'meeting.status.both';
  // **ここが今回の本題** —— 受けているのに送っていない
  if (いま.受けている) return 'meeting.status.recvonly';
  if (いま.送っている) return 'meeting.status.sendonly';
  // **掴んでいるなら、そう言う。**「使っていません」は嘘になる
  if (いま.掴んでいる) return 'meeting.status.holding';
  return 'meeting.status.textonly';
}
