// **映像と音が付く部屋は、常に 1 つだけ**（**#36**・オーナー判断 2026-09-16）。
//
// オーナー ——
//
//   **ルームがごちゃごちゃにできてしまうのはバグに近いですね。**
//   **同時に会議する未来はエージェント間はできますが、
//     カメラ付き音声は人あってこそなので、通常 同時に会議はできません。**
//
// **文字の部屋はいくつでもよい。**エージェントは同時に何部屋でも読み書きできて、
// **そこに意味がある。**
// **映像と音の部屋は 1 つだけ。**顔は 1 つ・マイクは 1 つ・目は 1 組で、
// **人が 2 つの会議に同時に出ることはできない。**
//
// 2026-09-15、ASUS が実際にこうなった（#36）——
// **2 つ建てたつもりがないのに部屋が 2 つあり、どちらに映像が付いているか
// 画面のどこにも書いていなかった。**そのうえ**片方を抜けたら画面が貼り付いた**（#33）。
//
// ここは純ロジック。**画面も機器も触らない。**

/** 映像を始めようとしたときに、何が起きるか。 */
export type 始めるときの答え =
  | { どうする: '始める' }
  | { どうする: 'すでに付いている' }
  | { どうする: '部屋がない' }
  /** **黙って 2 つ目を始めない。**人に移すかを尋ねる。 */
  | { どうする: '移すか尋ねる'; いまの部屋: string };

/**
 * 映像を始めてよいか。
 *
 * **黙って 2 つ目を始めない** —— 人は 2 つの会議に出られないので、
 * **必ず片方が放置になる。**
 */
export function 映像を始めてよいか(素材: {
  映像がある部屋: string | null;
  始めたい部屋: string | null;
}): 始めるときの答え {
  const { 映像がある部屋, 始めたい部屋 } = 素材;
  // **どこに付けるか分からないものは始めない**（原則 7）
  if (!始めたい部屋) return { どうする: '部屋がない' };
  if (!映像がある部屋) return { どうする: '始める' };
  if (映像がある部屋 === 始めたい部屋) return { どうする: 'すでに付いている' };
  return { どうする: '移すか尋ねる', いまの部屋: 映像がある部屋 };
}

/**
 * その部屋に「● 映像と音」の札を出すか。
 *
 * **開くまで分からない**のをやめる（#36 の提案 2）——
 * 一覧の行に出す。
 */
export function 映像の札(部屋: string, 映像がある部屋: string | null): boolean {
  return 映像がある部屋 !== null && 部屋 === 映像がある部屋;
}
