/**
 * **この機械のエージェントの声**（#50）—— 決めるところだけ（副作用なし）。
 *
 * - 人がルームごとに入れる印。**既定は切**。ルームを移る・抜けると切に戻る
 * - 声を流すかの判断（入れていない／会議が無い／流す）
 * - 音の送り手へ何を入れるか（声の間は声、終わったらマイクか無し）
 */

/** 人が入れた印。**どのルームで入れたか**まで持つ（ほかのルームへ持ち越さない）。 */
export type 声の同意 = {
  ルーム: string | null;
  入: boolean;
};

export const 初めの同意: 声の同意 = { ルーム: null, 入: false };

/** 人が入切を押した。押したときに見ているルームに付ける。 */
export function 同意を置く(ルーム: string | null, 入: boolean): 声の同意 {
  // ルームが無いところでは入れられない（流す先が無い）
  if (ルーム === null) return 初めの同意;
  return { ルーム, 入 };
}

/** いま見ているルームで入っているか。**別のルームで入れた印は効かない。** */
export function いま入っているか(同意: 声の同意, 見ている: string | null): boolean {
  return 同意.入 && 見ている !== null && 同意.ルーム === 見ている;
}

/**
 * ルームが変わったら切に戻す。**変わっていなければ同じものを返す**
 * （呼ぶ側が「切に戻ったか」を見比べて、机へ伝えられるように）。
 */
export function ルームが変わったら(同意: 声の同意, 見ている: string | null): 声の同意 {
  if (!同意.入) return 同意;
  return 同意.ルーム === 見ている ? 同意 : 初めの同意;
}

/** 声をどうするか。**机へ返す段の名と揃える。** */
export type 声の決め = 'play' | 'not_allowed' | 'no_meeting';

/**
 * **流すかを決める。**
 *
 * 人の印が先 —— 入れていなければ、会議があっても流さない。
 * 映像と音を足していない部屋・相手の居ない部屋へは流さない（送る関門と同じ）。
 */
export function 声をどうするか(いま: {
  同意: 声の同意;
  見ている: string | null;
  映像を使う: boolean;
  映像がある部屋: string | null;
  相手の数: number;
}): 声の決め {
  if (!いま入っているか(いま.同意, いま.見ている)) return 'not_allowed';
  if (!いま.映像を使う || いま.映像がある部屋 !== いま.見ている || いま.相手の数 === 0) {
    return 'no_meeting';
  }
  return 'play';
}

/**
 * **音の送り手へ入れるもの。**
 *
 * - 声があり、この部屋で映像と音を足しているなら、**マイクの入切に関わらず声**
 *   （人が声を入れたことが同意である）
 * - 声が無ければ、いつもの関門どおり（送ってよければマイク、だめなら無し）
 *
 * 声が終わったら `声: null` で呼び直せば、元へ戻る。
 */
export function 音の玉を選ぶ<T>(いま: {
  声: T | null;
  マイク: T | null;
  音を送る: boolean;
  映像を使う: boolean;
}): T | null {
  if (いま.声 !== null && いま.映像を使う) return いま.声;
  return いま.音を送る ? いま.マイク : null;
}
