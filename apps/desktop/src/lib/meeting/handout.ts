// 出した鍵を、**誰に渡したか**まで持つ（**D84** の本題）。
//
// オーナー指摘（2026-09-10）——
// 「**手動だとミスります。いかにアプリ側で普段はよしなに裏側でそれをやるかどうかです。**」
//
// **1 本につき 1 人**（**D12**）。10 人呼ぶなら 10 本出す。
// そのとき人が困るのは本数ではなく、**どの 1 本を誰に渡したか**である。
// だから**出すときに宛先を書く。**人に数えさせない。
//
// **持つのは窓が開いている間だけ。**置き場所へは書かない ——
// 会議キーは短命（既定 2 時間・D12）で、**使い終わった宛先が溜まると
// 「渡したのに入れない」相手が見えなくなる。**

/** 鍵を渡した相手。**画面に出す名前も一緒に持つ**（あとから引き直さない）。 */
export interface 宛先 {
  /** 相手の公開鍵。 */
  key: string;
  /** そのときの呼び名。 */
  名: string;
}

/** 出した鍵 1 本。 */
export interface 出した鍵 {
  /** 会議キー。**宛先と割符が 1 本になっている**（D39）。 */
  鍵: string;
  /** 渡せる 1 本のリンク（`warifu://join/…`・**D79**）。 */
  リンク: string;
  /** そのリンクの QR（SVG）。**目の前の相手に読ませる用。** */
  qr: string;
  /** 誰に渡すために出したか。**一括で出した分は空。** */
  宛先?: 宛先;
}

/**
 * 1 本足す。
 *
 * **前の鍵を捨てない。**同じ相手にもう 1 本出すこともある
 * （渡し損じた・相手が入れなかった）——**前の 1 本もまだ生きている。**
 */
export function 足す(鍵たち: readonly 出した鍵[], 本: 出した鍵): 出した鍵[] {
  return [...鍵たち, 本];
}

/** その相手に渡した鍵。**新しいものが後ろ。** */
export function その人の鍵(鍵たち: readonly 出した鍵[], key: string): 出した鍵[] {
  return 鍵たち.filter((本) => 本.宛先?.key === key);
}

/** その相手に、もう鍵を渡してあるか。 */
export function 渡してあるか(鍵たち: readonly 出した鍵[], key: string): boolean {
  return 鍵たち.some((本) => 本.宛先?.key === key);
}
