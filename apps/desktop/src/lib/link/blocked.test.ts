import { describe, expect, it } from 'vitest';
import { 画面なしで入っているか, 経路が付かないと言うか, 黙っている秒 } from './blocked';

const 場 = (o: Partial<Parameters<typeof 経路が付かないと言うか>[0]> = {}) => ({
  相手が居る: true,
  経路: 'unknown' as const,
  入ってからの秒: 黙っている秒 + 1,
  // **既定は「返してきた」**（画面どうし）。**画面なしの相手は 1 本も返さない**
  返してきた: true,
  ...o,
});

describe('経路が付かないことを言うか', () => {
  // gh issue 9 / 11（ASUS・2026-09-12）——
  //
  // > `warifu-desktop.exe` に Inbound / Outbound の Allow を手で足したところ、
  // > 同じ手順・同じ鍵で入れるようになりました。
  // > **インストーラが規則を作らず、画面も許可を聞きません。**
  //
  // 利用者からは「**コマンドは動くのに画面だけ繋がらない**」という、
  // いちばん切り分けにくい形になる。**画面が黙っているのがいちばん悪い。**

  it('相手が居るのに経路が付かないままなら、言う', () => {
    expect(経路が付かないと言うか(場())).toBe(true);
  });

  it('**すぐには言わない**（握手の途中で脅かさない）', () => {
    expect(経路が付かないと言うか(場({ 入ってからの秒: 黙っている秒 - 1 }))).toBe(false);
  });

  it('経路が付いたら言わない', () => {
    expect(経路が付かないと言うか(場({ 経路: 'direct' }))).toBe(false);
    expect(経路が付かないと言うか(場({ 経路: 'relayed' }))).toBe(false);
  });

  it('**相手が居ないなら言わない**（誰も来ていないだけ）', () => {
    expect(経路が付かないと言うか(場({ 相手が居る: false }))).toBe(false);
  });
});

describe('画面なしで入った相手（2026-09-25 に実測）', () => {
  // **`warifu join` には WebRTC が無い。**文字は通るが、下ごしらえは 1 本も返らない。
  //
  //   送信: 下ごしらえ offer を 6X7BDCXBJ3DW… へ（4563 バイト）
  //   画面: 15 秒たっても経路がありません。候補 送った 8 / **来た 0**
  //
  // **このとき画面は「ふさがっているかもしれません」と案内していた。誤案内である。**

  it('1 本も返ってこなければ、画面なしと見る', () => {
    expect(画面なしで入っているか(場({ 返してきた: false }))).toBe(true);
  });

  it('**ふさがりの話にはしない**', () => {
    // **塞がれている相手は、下ごしらえだけは返る**（割符の経路で届くので）
    expect(経路が付かないと言うか(場({ 返してきた: false }))).toBe(false);
  });

  it('返してきたのに経路が付かないなら、ふさがりの話', () => {
    expect(経路が付かないと言うか(場())).toBe(true);
    expect(画面なしで入っているか(場())).toBe(false);
  });

  it('待つ前には、どちらも言わない', () => {
    const 早い = { 入ってからの秒: 黙っている秒 - 1 };
    expect(画面なしで入っているか(場({ ...早い, 返してきた: false }))).toBe(false);
    expect(経路が付かないと言うか(場(早い))).toBe(false);
  });

  it('経路が付いていれば、どちらも言わない', () => {
    expect(画面なしで入っているか(場({ 経路: 'direct', 返してきた: false }))).toBe(false);
  });
});
