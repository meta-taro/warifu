import { describe, expect, it } from 'vitest';
import { 切れた知らせの文, 戻ったら消すか } from './lost';

// **2026-09-29、入り直してつながったのに、帯に「相手との経路が切れました」が残った**
// （記録では `経路 relayed` と「経路が切れました」が同じ行に出ていた）。
// 切れた知らせを出す所はあったが、**同じ相手が戻ったときに消す所が無かった。**
describe('相手が戻ったら、切れた知らせを消すか', () => {
  const 切れた = { 文: '相手との経路が切れました。…', 相手: 'AAAA' };

  it('**同じ相手が戻り、帯がまだその知らせなら消す**', () => {
    expect(戻ったら消すか('相手との経路が切れました。…', 切れた, 'AAAA')).toBe(true);
  });

  it('別の相手が入っただけなら消さない', () => {
    expect(戻ったら消すか('相手との経路が切れました。…', 切れた, 'BBBB')).toBe(false);
  });

  it('**帯がもう別の知らせに変わっていたら触らない**（ほかの知らせを消さない）', () => {
    expect(戻ったら消すか('カメラが見つかりません', 切れた, 'AAAA')).toBe(false);
  });

  it('切れた知らせを出していなければ消さない', () => {
    expect(戻ったら消すか('', null, 'AAAA')).toBe(false);
  });
});

// **#48** —— 主催が落ちたのに、ゲストの帯に「同じルームキーで戻ってこられます — 待っています」と出た。
// これは主催の側の言い方である。**ゲストが待っても、主催は戻ってこない**（戻るのはゲストの役）。
describe('切れたときに出す知らせ', () => {
  const ルームたち = [
    { id: 'R1', host: false, host_key: 'HOST' },
    { id: 'R2', host: true, host_key: 'ME' },
  ];

  it('**ゲストで入っている部屋の主催が落ちたら、戻り方を言う**', () => {
    expect(切れた知らせの文('lost', 'HOST', ルームたち)).toBe('link.lost.host');
  });

  it('自分の部屋のゲストが落ちたら、これまでどおり「待っています」', () => {
    expect(切れた知らせの文('lost', 'GUEST', ルームたち)).toBe('link.lost');
  });

  it('**自分で抜けたのは、落ちたのと言い分けない**（退出しました）', () => {
    expect(切れた知らせの文('left', 'HOST', ルームたち)).toBe('link.closed');
  });
});
