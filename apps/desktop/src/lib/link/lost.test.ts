import { describe, expect, it } from 'vitest';
import { 戻ったら消すか } from './lost';

// **2026-09-29、入り直してつながったのに、帯に「相手との経路が切れました」が残った**
// （記録では `経路 relayed` と「経路が切れました」が同じ行に出ていた）。
// 切れた知らせを出す所はあったが、**同じ相手が戻ったときに消す所が無かった。**
describe('相手が戻ったら、切れた知らせを消すか', () => {
  const 切れた = { 文: '相手との経路が切れました。…', 相手: 'AAAA' };

  it('**同じ相手が戻り、帯がまだその知らせなら消す**', () => {
    expect(戻ったら消すか('相手との経路が切れました。…', 切れた, 'AAAA')).toBe(true);
  });

  it('別の相手が入っただけなら消さない', () => {
    expect(戻ったら消すか('相手との経路が切れました。…', 切れた, 'BBBB')).toBe(false);
  });

  it('**帯がもう別の知らせに変わっていたら触らない**（ほかの知らせを消さない）', () => {
    expect(戻ったら消すか('カメラが見つかりません', 切れた, 'AAAA')).toBe(false);
  });

  it('切れた知らせを出していなければ消さない', () => {
    expect(戻ったら消すか('', null, 'AAAA')).toBe(false);
  });
});
