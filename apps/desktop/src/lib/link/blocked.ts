// **経路が付かないことを、黙って見過ごさない。**
//
// `gh issue 9` / `gh issue 11`（2026-09-12）—— Windows で `warifu-desktop.exe` に
// Inbound / Outbound の Allow を手で足すと（**コードは変えずに**）、同じ手順・同じ鍵で入れた。
//
// **インストーラが規則を作らず、画面も許可を聞かない。**
// 結果、利用者からは「**コマンドは動くのに画面だけ繋がらない**」という、
// いちばん切り分けにくい形になる。
//
// **文字は割符の経路で流れるので、映像だけが乗らない。**
// そのうえ画面は `unknown` と出したまま黙るので、**何が起きているか誰にも分からない。**

import type { LinkPath } from './path';

/**
 * **これだけ待ってから言う。**
 *
 * 握手には数秒かかる。**途中で「塞がっています」と出すと、直っているのに人が慌てる。**
 */
export const 黙っている秒 = 15;

/** 言うかどうかを決めるのに要るもの。 */
export type 場 = {
	/** ルームに相手が居るか。 */
	相手が居る: boolean;
	/** いまの経路。 */
	経路: LinkPath;
	/** 相手が入ってからの秒。 */
	入ってからの秒: number;
	/**
	 * **その相手から、下ごしらえ（SDP / ICE）が 1 本でも来たか。**
	 *
	 * **画面なしで入った相手は、1 本も返さない**（`warifu join` に WebRTC は無い）。
	 * **文字は通っているので、これは不具合ではない。**
	 *
	 * 2026-09-25 に実測 ——
	 *
	 * ```text
	 * 送信: 下ごしらえ offer を PEERBAAAAAAA… へ（4563 バイト）
	 * 画面: 15 秒たっても経路がありません。候補 送った 8 / **来た 0**
	 * ```
	 *
	 * **このとき画面は「ふさがっているかもしれません」と案内していた。誤案内である。**
	 * 相手は塞がれていない —— **画面を持っていないだけ**である。
	 */
	返してきた: boolean;
};

/**
 * **相手は画面なしで入っているか。**
 *
 * **1 本も返してこないことが印である** —— 塞がれている相手は、
 * **下ごしらえ（SDP / ICE）は割符の経路で届く**ので、答えだけは返る。
 * **返ってこないのは、答える物を持っていないとき**である。
 */
export function 画面なしで入っているか(場: 場): boolean {
	if (!場.相手が居る) return false;
	if (場.経路 !== 'unknown') return false;
	if (場.返してきた) return false;
	return 場.入ってからの秒 >= 黙っている秒;
}

/**
 * **経路が付かないことを言うか。**
 *
 * 言うのは「**相手は居るのに、待っても経路が付かない**」ときだけ。
 * **相手が居ないのは、誰も来ていないだけ**である（そこで脅かさない）。
 */
export function 経路が付かないと言うか(場: 場): boolean {
	if (!場.相手が居る) return false;
	if (場.経路 !== 'unknown') return false;
	// **画面なしで入った相手を、ふさがりの話にしない**（2026-09-25 に実測）。
	// **そちらは別の言い方をする**（`画面なしで入っているか`）
	if (!場.返してきた) return false;
	return 場.入ってからの秒 >= 黙っている秒;
}

/**
 * **この PC の中の TURN から、relay の候補が 1 本も出ていないか**（2026-09-29）。
 *
 * 経路が付かないとき、ファイアウォールを案内していたが、**原因は違った** ——
 * Windows の機械で、機械の中の TURN（**D125**）から relay を 1 本も出していなかった。
 * ファイアウォールを案内すると、**人は規則を見に行き、足しても直らない**（#11 と同じ形）。
 *
 * **機械の中の TURN が無い（建てられなかった）ときは、この話ではない。**
 */
export function 中継の候補が無いと言うか(場: {
	機械の中のTURNがある: boolean;
	送った種類: ReadonlySet<string>;
}): boolean {
	return 場.機械の中のTURNがある && !場.送った種類.has('relay');
}
