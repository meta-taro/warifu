// **相手が戻ったら、「経路が切れました」を消す**（2026-09-29）。
//
// 入り直してつながったのに、帯に「相手との経路が切れました」が残り、
// **記録には `経路 relayed` と「経路が切れました」が同じ行に出ていた。**
// 切れた知らせを出す所はあったが、**同じ相手が戻ったときに消す所が無かった。**
// 人から見ると「切れているのか、つながっているのか分からない」。

/** 出した「切れた」知らせと、その相手。 */
export interface 切れた知らせ {
  文: string;
  相手: string;
}

/**
 * **入ってきた相手が、切れた知らせの相手なら、その知らせを消すか。**
 *
 * **帯がもう別の知らせに変わっていたら触らない**（ほかの知らせを消さない）。
 */
export function 戻ったら消すか(
  いまの知らせ: string,
  切れた: 切れた知らせ | null,
  入った相手: string,
): boolean {
  return 切れた !== null && 切れた.相手 === 入った相手 && いまの知らせ === 切れた.文;
}
