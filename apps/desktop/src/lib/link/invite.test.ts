import { describe, expect, it } from 'vitest';
import { 拾うリンク } from './invite';

describe('起き上がって、待っていたリンクを拾う（#25）', () => {
  // **7cc4ecb で「直した」が、一度も動いていなかった**（2026-09-25 に mini で再現）。
  //
  // 画面の `誘われた鍵` は **`''` で始まる**のに、拾う側は **`=== null`** を見ていた。
  // **`'' === null` は偽**なので、リンクで起動した回は拾いに行かず、
  // **「入りますか？」が画面のどこにも出なかった**（`room_status` は「待っている 1 本」）。

  it('**何も尋ねていない（空の文字）なら、いちばん古い 1 本を拾う**', () => {
    expect(拾うリンク('', ['WARIFU1-A', 'WARIFU1-B'])).toBe('WARIFU1-A');
  });

  it('何も尋ねていない（null）でも拾う', () => {
    expect(拾うリンク(null, ['WARIFU1-A'])).toBe('WARIFU1-A');
  });

  it('**もう尋ねているなら、上書きしない**（知らせで先に来た 1 本を消さない）', () => {
    expect(拾うリンク('WARIFU1-X', ['WARIFU1-A'])).toBeNull();
  });

  it('待っているものが無ければ、何も拾わない', () => {
    expect(拾うリンク('', [])).toBeNull();
  });
});
