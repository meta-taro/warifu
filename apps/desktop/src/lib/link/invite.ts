// **聞き手が居ない間に来たリンクを、画面が起き上がってから拾う**（**#25**）。
//
// リンクでアプリが起動した回は、`warifu://link` の知らせが画面より先に飛んで落ちる。
// **だから画面から取りに行く**（`pending_links`）。
//
// **7cc4ecb の拾い方は、一度も動いていなかった** ——
// `誘われた鍵` は `''` で始まるのに、`=== null` を見ていた（2026-09-25）。
// **「まだ尋ねていないか」は、空の文字も null も同じに読む。**

/**
 * 画面が起き上がったときに、どの鍵を尋ねるか。
 *
 * @param いまの鍵 すでに尋ねている鍵（無ければ `''` か `null`）
 * @param 待ち 後ろが溜めている鍵（古い順）
 * @returns 尋ねる鍵。**すでに尋ねているなら上書きしない**ので `null`
 */
export function 拾うリンク(いまの鍵: string | null, 待ち: readonly string[]): string | null {
	if (いまの鍵) return null;
	return 待ち[0] ?? null;
}
