import { describe, expect, it } from 'vitest';
import { 右の下限, 左に残す, 幅を収める, 引いた幅, 覚えた幅を読む } from './divider';

describe('仕切りの幅', () => {
  it('左へ引くと、右の列が広がる', () => {
    expect(引いた幅(300, 1000, 900, 1600)).toBe(400);
  });

  it('右へ引くと、右の列が狭まる', () => {
    expect(引いた幅(400, 900, 960, 1600)).toBe(340);
  });

  it('下限より細くしない', () => {
    expect(引いた幅(300, 900, 1500, 1600)).toBe(右の下限);
  });

  it('左を潰すほどは広げない', () => {
    expect(引いた幅(300, 1000, 0, 1600)).toBe(1600 - 左に残す);
  });

  it('左に残す幅は、面ごとに変えられる', () => {
    // 連絡帳は左に一覧と相手の欄の 2 列があるので、多めに残す
    expect(引いた幅(300, 1000, 0, 1600, 640)).toBe(1600 - 640);
  });

  it('枠が狭くても、下限は守る', () => {
    // **左に残すより、会話が読めることを先にする**
    expect(幅を収める(500, 500)).toBe(右の下限);
  });
});

describe('覚えた幅', () => {
  it('数なら、その幅で出す', () => {
    expect(覚えた幅を読む('512')).toBe(512);
  });

  it('無い・壊れている・細すぎるなら、初めの幅に任せる', () => {
    expect(覚えた幅を読む(null)).toBeNull();
    expect(覚えた幅を読む('abc')).toBeNull();
    expect(覚えた幅を読む('10')).toBeNull();
  });
});
