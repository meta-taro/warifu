// **受信箱の並び**（0.1.45）。仕分けの札（`warifu-read` の `仕分ける`）ごとにまとめ、
// **人が見るべきものを先に**出す。決めるのは並びだけで、札はヘッダから割符の本体が決める。

/** 画面へ来る 1 通（本文は入らない）。 */
export type メールの行 = {
  /** どの受信箱か（控えたアドレス）。 */
  user: string;
  uid: number;
  /** 差出人の番地。 */
  差出人: string;
  /** 差出人の表示名（相手の申告）。 */
  名: string | null;
  /** 件名（相手の申告）。 */
  件名: string;
  /** サーバが受け取った時刻（epoch 秒）。 */
  届いた: number | null;
  既読: boolean;
  /** 仕分けの札。 */
  札: string;
  /** なぜその札か。 */
  理由: string[];
};

/**
 * 札の並び。**なりすまし疑いがいちばん上**（気づかずに開くと危ない）。
 * 受注・問い合わせ・未分類は人が返事をするもの。知らせ・広告・迷惑は後で見ればよい。
 */
export const 札の並び = ['なりすまし疑い', '受注', '問い合わせ', '未分類', '請求', '知らせ', '広告', '迷惑'] as const;

/** 畳んで出す札（開けば見える。消さない）。 */
export function 畳む札か(札: string): boolean {
  return 札 === '知らせ' || 札 === '広告' || 札 === '迷惑';
}

export type 札の組 = { 札: (typeof 札の並び)[number]; 行たち: メールの行[] };

/** 札ごとにまとめ、札の中は新しい順。**知らない札は未分類へ**（黙って落とさない）。 */
export function 並べる(行たち: readonly メールの行[]): 札の組[] {
  const 棚 = new Map<string, メールの行[]>();
  for (const 行 of 行たち) {
    const 札 = (札の並び as readonly string[]).includes(行.札) ? 行.札 : '未分類';
    棚.set(札, [...(棚.get(札) ?? []), 行]);
  }
  return 札の並び
    .filter((札) => 棚.has(札))
    .map((札) => ({
      札,
      行たち: [...(棚.get(札) ?? [])].sort((a, b) => (b.届いた ?? -Infinity) - (a.届いた ?? -Infinity))
    }));
}
