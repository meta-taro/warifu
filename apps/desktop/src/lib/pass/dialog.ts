// **札の頼みの窓**（0.1.57）。人が Enter で押す既定の許しと、窓に出す頼みを決める。
//
// 頼みは前は画面の上の細い帯で、人が気づかずに席が止まった。窓（ポップアップ）にして、
// Enter でいちばん手間の少ない許しが通るようにした（何度も聞かれない側）。

/** 既定で押す許し。取り消すまで出せる動作はそれ、ほかは 24 時間。 */
export type 既定の許し = '取り消すまで' | '24時間';

/**
 * **Enter で通る許し**を決める。取り消すまで出せるのは本体が許した動作だけ（メールを読む札）で、
 * それ以外は 24 時間が最長（本体がそれより長くは出さない）。
 */
export function 既定の許しを選ぶ(動作: string, 取り消すまで出せる札: readonly string[]): 既定の許し {
  return 取り消すまで出せる札.includes(動作) ? '取り消すまで' : '24時間';
}

/** 窓に出す頼み（いちばん古いもの）と、後ろに待っている数。 */
export function 窓に出す頼み<T>(待ちたち: readonly T[]): { いま: T | null; ほか: number } {
  return { いま: 待ちたち[0] ?? null, ほか: Math.max(0, 待ちたち.length - 1) };
}
