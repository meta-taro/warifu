// **通話の棚**（11-12）。相手ごとに通話は 1 つだけ。
//
// 入り直しでは古い通話を閉じてから作り直すが、閉じてから棚に置くまでの間に待ち（await）が挟まる。
// 同じ相手の「入った」が続けて届くと、先に作った通話が棚から押し出され、**閉じられないまま残った**。
// 1 つの通話は、この機械の網の出口ごとに UDP の口を開ける。残った通話の口が溜まり、
// 1 日で 200 近くになっていた（ルーターが新しい通信を落とし始めたのと時期が重なる）。

/** 閉じられるもの（`webrtc/session.ts` の `Call`）。 */
export interface 閉じられる {
  close(): void;
}

/** **棚に置く。**同じ相手の別の通話が棚にあれば、先に閉じる（閉じずに上書きしない）。 */
export function 通話を置く<T extends 閉じられる>(棚: Map<string, T>, 相手: string, 通話: T): void {
  const 前 = 棚.get(相手);
  if (前 && 前 !== 通話) 前.close();
  棚.set(相手, 通話);
}
