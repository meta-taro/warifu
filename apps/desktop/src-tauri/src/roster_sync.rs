//! **ゲストの名簿を、主催の名簿に合わせる**（0.1.39・2026-10-23）。
//!
//! ルームは星形で、ゲストどうしは主催を介して話す。ところが**ゲストの名簿は、
//! 自分と直接つながった相手しか増えなかった**（`Join` は線の向こうの相手として受けるので、
//! 主催が配り直しても主催の入り直しにしか見えない）。網を越えて直接つながれない相手は、
//! **発言は主催ごしに届くのに、見出しの人数にも届く先にも出なかった**（10-23、2 台で報告）。
//!
//! 主催は名簿が動いたら（入った・抜けた）、**いまの名簿をゲスト全員へ配る**（`Notice::Invite`）。
//! ゲストは**主催から来た名簿だけ**を信じ、自分の名簿との差を足し引きする。
//! 古い版のゲストは知っている部屋あての `Invite` を捨てるだけなので、混ざっていても壊れない。

/// 主催の名簿と自分の名簿の差。**（足す, 外す）**を返す。
///
/// - 足す …… 主催の名簿に居て、自分の名簿に居ない相手（自分は除く）
/// - 外す …… 自分の名簿に居て、主催の名簿に居ない相手（自分と主催は除く。先頭は外せない）
#[must_use]
pub fn 名簿の差<T: PartialEq + Copy>(
    自分の名簿: &[T],
    主催の名簿: &[T],
    自分: &T,
    主催: &T,
) -> (Vec<T>, Vec<T>) {
    let 足す = 主催の名簿
        .iter()
        .copied()
        .filter(|k| k != 自分 && !自分の名簿.contains(k))
        .collect();
    let 外す = 自分の名簿
        .iter()
        .copied()
        .filter(|k| k != 自分 && k != 主催 && !主催の名簿.contains(k))
        .collect();
    (足す, 外す)
}

/// **線の相手と差出人が違う発言を通すか**（0.1.39）。
///
/// 主催は聞いた発言をほかの客へそのまま配る（D48・差出人は書き換えない）。ところが受ける側は
/// 「差出人と線の相手が違う」と捨てていた —— **主催ごしの発言は、直接つながっていない相手からは
/// 1 通も届かなかった**（この機械の記録に「捨てた」が 44 回）。
/// 通すのは**線の相手がその部屋の主催のときだけ**。自分を名乗る発言は通さない。
#[must_use]
pub fn 配られた発言を通すか<T: PartialEq>(差出人: &T, 線の相手: &T, 自分: &T, 主催: Option<&T>) -> bool {
    if 差出人 == 線の相手 {
        return true;
    }
    差出人 != 自分 && 主催 == Some(線の相手)
}

/// 主催が、名簿をゲストへ配り直すか。**名簿が動いたときだけ**（入った・抜けた）。
#[must_use]
pub fn 名簿を配るか(主催か: bool, events: &[warifu_app::Event]) -> bool {
    主催か
        && events
            .iter()
            .any(|e| matches!(e, warifu_app::Event::Joined(_) | warifu_app::Event::Left(_)))
}

#[cfg(test)]
mod tests {
    use super::*;

    const 主催: u8 = 1;
    const 自分: u8 = 2;
    const 直接: u8 = 3;
    const 遠い: u8 = 4;

    #[test]
    fn 主催の名簿に居て_自分の名簿に居ない相手を足す() {
        // 網を越えて直接つながれない相手。発言は主催ごしに届くのに、名簿に居なかった
        let (足す, 外す) = 名簿の差(&[自分, 主催, 直接], &[主催, 自分, 直接, 遠い], &自分, &主催);
        assert_eq!(足す, vec![遠い]);
        assert!(外す.is_empty());
    }

    #[test]
    fn 主催の名簿から消えた相手を外す_自分と主催は外さない() {
        let (足す, 外す) = 名簿の差(&[自分, 主催, 直接, 遠い], &[主催, 自分], &自分, &主催);
        assert!(足す.is_empty());
        assert_eq!(外す, vec![直接, 遠い]);
    }

    #[test]
    fn 同じなら何もしない() {
        let (足す, 外す) = 名簿の差(&[自分, 主催, 直接], &[主催, 直接, 自分], &自分, &主催);
        assert!(足す.is_empty());
        assert!(外す.is_empty());
    }

    #[test]
    fn 主催ごしの発言は通し_それ以外の名乗りは通さない() {
        // 直接つながった相手の発言
        assert!(配られた発言を通すか(&直接, &直接, &自分, Some(&主催)));
        // 主催が配った、直接つながっていない相手の発言
        assert!(配られた発言を通すか(&遠い, &主催, &自分, Some(&主催)));
        // 主催でない相手が、他人を名乗って送ってきた
        assert!(!配られた発言を通すか(&遠い, &直接, &自分, Some(&主催)));
        // 主催を覚えていない部屋では、線の相手の分だけ
        assert!(!配られた発言を通すか(&遠い, &主催, &自分, None));
        // 自分を名乗る発言は通さない
        assert!(!配られた発言を通すか(&自分, &主催, &自分, Some(&主催)));
    }

    #[test]
    fn 配るのは主催だけ_名簿が動いたときだけ() {
        use warifu_app::Event;
        let 鍵 = warifu_core::Seed::from_bytes([7u8; 32])
            .profile("Personal")
            .device("PC")
            .public_key();
        assert!(名簿を配るか(true, &[Event::Joined(鍵)]));
        assert!(名簿を配るか(true, &[Event::Left(鍵)]));
        assert!(!名簿を配るか(false, &[Event::Joined(鍵)]));
        assert!(!名簿を配るか(true, &[]));
    }
}
