//! 机 —— **同じ PC のエージェントが、人と同じ会話に着く口。**
//!
//! ```text
//!   人（この画面）──┐
//!                   ├── 同じ会話 ── iroh P2P ── 相手の PC
//!   AI（warifu mcp）─┘
//!         ↑ ここが机（同じ機械の中だけ。網には出ない）
//! ```
//!
//! **これが「エージェント同士でチャットし、人がそれを見て入れる」の実体。**
//! エージェントに `warifu join` を叩かせる形は、実際に許可プロンプトで
//! 3 回とも止まった（2026-09-06・Mac Air の報告）。MCP の口なら止まらない。
//!
//! # ここで守ること
//!
//! - **繋いできた側は差出人を名乗れない。**誰が言ったかはここで刻む
//! - **机は同じ機械の中だけ。**口の権限は `warifu-desk` が持つ（Unix は 0600）
//! - **届いた文字は相手の言い分。**ここは運ぶだけで、解釈しない

use std::collections::BTreeMap;
use std::sync::Mutex;
use std::sync::atomic::{AtomicU64, Ordering};

use tauri::{AppHandle, Emitter, Manager};
use tokio::sync::broadcast;
use warifu_desk::{FromDesk, ToDesk, 受け口, 口, 机の場所};

use crate::{Bridge, EVENT_DESK, EVENT_DESK_SEATS};

/// 机に着いている相手へ配る溜め。
///
/// **溜めきれない相手を待たない。**追いつけない客は取りこぼすが、
/// 会話そのものは止めない（止めると人の画面まで止まる）。
pub const 配る溜め: usize = 128;

/// 机に着いた人に振る番号。
///
/// **自分の発言を自分に返さないため**に要る。返すと、
/// エージェントは `chat_read` で自分が言ったことを「誰かの発言」として読む。
static 次の番号: AtomicU64 = AtomicU64::new(1);

/// 席ごとの呼び方。**誰が着いているかを画面へ出すため。**
///
/// 1 行にまとめると、**どれが喋ったのか分からない**だけでなく、
/// **どれが着いているのかも分からない**（2026-09-08 オーナー指摘）。
/// **まとめて 1 人ではない。それぞれが 1 人である。**
static 席たち: Mutex<BTreeMap<u64, String>> = Mutex::new(BTreeMap::new());

/// 机の外から出た発言（相手から届いた文字・人が打った行）に使う番号。
///
/// **机の誰とも一致しない**ので、全員へ配られる。
pub const 机の外: u64 = 0;

/// いまの時刻（`HH:MM`）。**秒は出さない。**
///
/// 無いと、あとから読み返せない（2026-09-06 の「何時に投稿したかわからないです」）。
fn いま時刻() -> String {
    chrono::Local::now().format("%H:%M").to_string()
}

/// 机を開く。**開けなくても画面は止めない。**
///
/// 机が無くても人どうしの会話は成り立つ。
/// **開かなかったことは記録に残す**（黙って落とすと、
/// エージェントが繋がらない理由が誰にも分からない）。
pub fn 開く(app: AppHandle) {
    tauri::async_runtime::spawn(async move {
        let 場所 = 机の場所();
        let mut 待ち = match 受け口::開く(&場所).await {
            Ok(待ち) => {
                記録!("机を開きました: {}", 場所.display());
                待ち
            }
            Err(e) => {
                記録!("机を開けませんでした（{}）: {e}", 場所.display());
                return;
            }
        };
        loop {
            match 待ち.受ける().await {
                Ok(一本) => {
                    記録!("机に 1 人着きました");
                    座らせる(app.clone(), 一本);
                }
                Err(e) => {
                    記録!("机の口が壊れました: {e}");
                    return;
                }
            }
        }
    });
}

/// 机に着いた 1 人の面倒を見る。
fn 座らせる(app: AppHandle, 一本: impl warifu_desk::一本) {
    tauri::async_runtime::spawn(async move {
        let 自分 = 次の番号.fetch_add(1, Ordering::Relaxed);
        // **どこで動いているか。**`Listen` で名乗ってくるまでは分からない
        let mut 名乗り: Option<String> = None;
        let mut 口 = 口::新しく(一本);
        let mut 聞く = app.state::<Bridge>().desk.subscribe();
        // **人数が変わったことを画面へ伝える。**伝えないと、
        // AI が居るのに「入ってきたら送れます」と出たままになる
        席たち
            .lock()
            .expect("毒されていない")
            .insert(自分, 呼び方(None));
        席の数を伝える(&app);
        loop {
            tokio::select! {
                来た = 口.受ける() => {
                    let Ok(Some(行)) = 来た else { break };
                    if 応じる(&app, &行, &mut 口, 自分, &mut 名乗り)
                        .await
                        .is_err()
                    {
                        break;
                    }
                }
                配られた = 聞く.recv() => {
                    match 配られた {
                        // **自分が言ったことは自分に返さない。**返すと、
                        // エージェントは自分の発言を「誰かの発言」として読む。
                        // 宛先つきなら、**その席だけが受ける**
                        Ok((出所, _)) if !自分あてか(出所, 自分) => continue,
                        Ok((_, 一つ)) => {
                            if 口.送る(&一つ.書く()).await.is_err() {
                                break;
                            }
                        }
                        // 追いつけずに落ちた分がある。**会話は止めない**
                        Err(broadcast::error::RecvError::Lagged(_)) => continue,
                        Err(broadcast::error::RecvError::Closed) => break,
                    }
                }
            }
        }
        記録!("机から 1 人抜けました");
        席たち.lock().expect("毒されていない").remove(&自分);
        // subscribe を落としてから数える。**落とす前だと自分を数えてしまう**
        drop(聞く);
        席の数を伝える(&app);
    });
}

/// 机に何人着いているかを、画面へ伝える。
///
/// **「相手が居ない」と「話し相手が 1 人も居ない」は違う。**
/// 会議に人が居なくても、同じ席の AI が居るなら人は話しかけられる。
pub fn 席の数を伝える(app: &AppHandle) {
    let _ = app.emit(EVENT_DESK_SEATS, 着いている顔ぶれ());
}

/// いま机に着いている顔ぶれ。**呼び方の並び。**
///
/// 数だけでは「どれが着いているのか」が分からない。
#[must_use]
pub fn 着いている顔ぶれ() -> Vec<String> {
    席たち
        .lock()
        .expect("毒されていない")
        .values()
        .cloned()
        .collect()
}

/// いま机に何人着いているか。
#[must_use]
pub fn 席の数(bridge: &Bridge) -> usize {
    bridge.desk.receiver_count()
}

/// 机から来た 1 行に応じる。
async fn 応じる(
    app: &AppHandle,
    行: &str,
    口: &mut 口<impl warifu_desk::一本>,
    自分: u64,
    名乗り: &mut Option<String>,
) -> Result<(), ()> {
    let 中身 = match ToDesk::読む(行) {
        Ok(中身) => 中身,
        Err(e) => {
            // **読めなかったことを、断ったことと混ぜない**
            let _ = 口
                .送る(&FromDesk::Denied { why: e.to_string() }.書く())
                .await;
            return Ok(());
        }
    };
    match 中身 {
        // 「聞く」は名乗りだけ。**過去は残していない**ので、返すものが無い（`issues/010`）。
        // **どこで動いているかを覚える** —— 1 台の PC で複数のエージェントが
        // 同じ机に着くので、覚えないとどれが喋ったのか人に分からない（2026-09-08）
        ToDesk::Listen { 場所 } => {
            if let Some(名) = 場所 {
                記録!("机: {名} から着きました");
                *名乗り = Some(名.clone());
                席たち
                    .lock()
                    .expect("毒されていない")
                    .insert(自分, 呼び方(Some(&名)));
                席の数を伝える(app);
            }
            Ok(())
        }
        // **自分の席のプロフィールを書く**（オーナー・2026-09-08
        // 「エージェント自身にプロフィールをかけるようにしておくと、楽だとおもいます」）。
        //
        // **どの席かは、この口で決まる。**行の中に「誰の」は書けない ——
        // 書けると、**同じ机の別のエージェントに化けられる。**
        ToDesk::Profile { 名前, 紹介 } => {
            let 返事 = match 名乗り.as_deref() {
                // **名乗っていない席は、席が決まらない。**
                // どこで動いているか分からないものに、名前だけ付けさせない
                None => FromDesk::Denied {
                    why: "先に名乗ってください（--as か、起動した場所）".to_owned(),
                },
                Some(名) => match crate::profile::席の名乗りを書く(app, 名, &名前, &紹介) {
                    Ok(()) => FromDesk::Wrote { who: 呼び方(Some(名)) },
                    Err(訳) => FromDesk::Denied { why: 訳 },
                },
            };
            let _ = 口.送る(&返事.書く()).await;
            Ok(())
        }
        ToDesk::Say { body } => {
            // **必ず返事をする。**返さないと、言った側は待ち続ける（**D49**）
            let 返事 = match 流す(app, &body, 自分, 呼び方(名乗り.as_deref())).await {
                Ok(人数) => FromDesk::Sent { to: 人数 },
                Err(訳) => {
                    記録!("机からの発言を流せませんでした: {訳}");
                    // 相手が居ないのと、会議そのものが無いのは違う。**混ぜない**
                    if 訳 == 誰も居ない {
                        FromDesk::Nobody
                    } else {
                        FromDesk::Denied { why: 訳 }
                    }
                }
            };
            let _ = 口.送る(&返事.書く()).await;
            Ok(())
        }
    }
}

/// 相手が 1 人も居ないときの言い分。**判定に使うので、1 か所に置く。**
///
/// **この画面からは、もう出ない。**この PC の人がいつでも聞いているためである
/// （2026-09-08・`流す` の注記）。机の作りが変わったときのために残してある。
const 誰も居ない: &str = "まだ誰も居ません";

/// 机から来た発言を、会話へ流す。**届いた人数を返す。**
///
/// **人の画面にも、繋がっている相手にも、同じ 1 行が出る。**
/// 片方にしか出ないと、見ている人と話している人がずれる。
///
/// # 画面は「届いた先」に数える
///
/// **「会議ありきのチャットじゃない」**（オーナー・2026-09-06 / **D55**）。
/// 会議の相手だけを数えていたので、**この PC の人には出ているのに
/// エージェントには「誰にも届いていません」と返っていた**
/// （2026-09-08 に実物で踏んだ）。返された側は言い直すか、諦める。
async fn 流す(
    app: &AppHandle, body: &str, 出所: u64, 呼び方: String
) -> Result<usize, String> {
    let bridge = app.state::<Bridge>();
    let 自分 = bridge.device.public_key();

    // **先に人の画面へ出す。**会議が無くても、この PC の人には見える
    let _ = app.emit(EVENT_DESK, (呼び方.clone(), body.to_owned(), いま時刻()));
    // **同じ席の AI が喋ったことにも気づけるようにする。**
    // 窓が前に居るときは鳴らないので、うるさくならない
    crate::notify::届いたと知らせる(app, &呼び方);
    // 机に着いている**他の**エージェントにも同じ行を見せる（言った本人には返さない）
    let _ = bridge.desk.send((
        出所,
        FromDesk::Heard {
            from: 呼び方.clone(),
            body: body.to_owned(),
            at: いま時刻(),
        },
    ));

    // **この PC の画面 1 つ ＋ 机に着いている他の席。**
    // 画面はいつでも居る（机が開いているなら、窓も開いている）
    let 机の他の席 = 席たち
        .lock()
        .expect("毒されていない")
        .keys()
        .filter(|席| **席 != 出所)
        .count();
    let この端末で見る人 = 1 + 机の他の席;

    let Some(meeting) = crate::いま見ている部屋(&bridge.いまの部屋).await else {
        // 会議が無くても、**この PC の人には届いている。**失敗にしない
        return Ok(この端末で見る人);
    };

    // **その部屋に居る相手だけへ。**全員へ配ると、別の部屋の人にも届く
    let 送り先 = crate::その部屋の相手(&bridge.conferences, &bridge.outbound, meeting, 自分).await;
    for tx in &送り先 {
        // 届かない相手が居ても止めない。**送る側を待たせない**
        let _ = tx
            .send(warifu_meeting::Notice::Text {
                meeting,
                // **席の持ち主は自分**（D48）。AI は自分の席から喋っている
                from: 自分,
                // **その席の誰が言ったかを、線の向こうへも運ぶ**（2026-09-08）。
                // 載せないと、相手の画面では人が打ったのと区別が付かない。
                // **名乗っていれば名前も載せる**（`図面くん（zumen）`・**D75**）——
                // ただし**どこの席かは落とさない**（落とすと取り違えられる）
                話し手: Some(crate::profile::席の名札(&呼び方)),
                body: body.to_owned(),
            })
            .await;
    }
    Ok(この端末で見る人 + 送り先.len())
}

/// 会話に出たことを、机に着いている全員へ配る。
///
/// **人が打った行も、相手から届いた行も、ここを通す。**
/// 通さないと、エージェントは人の発言が見えないまま返事をすることになる。
pub fn 配る(bridge: &Bridge, 中身: FromDesk) {
    // 誰も着いていなければ落ちる。**それは失敗ではない**
    let _ = bridge.desk.send((机の外, 中身));
}

/// **その席にだけ渡す。**宛先が着いていなければ `false`。
///
/// 3 つも 4 つも机に着いていると、**zumen だけに聞きたくても全員に飛ぶ** ——
/// それでは 1 対 1 が成り立たない（2026-09-08 オーナー指摘
/// 「このPC上でやりとりが円滑にできない以上は別端末なんてもっとむずかしい」）。
///
/// **配る仕組みは 1 つのまま。**宛先の席以外が捨てる形にする ——
/// 席ごとに別の口を張ると、**誰に届いたかを数える所が 2 つになる。**
pub fn 席へ配る(bridge: &Bridge, 宛先: &str, 中身: FromDesk) -> bool {
    let 番号 = 席たち
        .lock()
        .expect("毒されていない")
        .iter()
        .find(|(_, 呼び方)| 呼び方.as_str() == 宛先)
        .map(|(n, _)| *n);
    let Some(番号) = 番号 else {
        // **着いていない相手へ送ったことにしない**
        return false;
    };
    let _ = bridge.desk.send((宛先の印(番号), 中身));
    true
}

/// **その席に「止まれ」と言う。**着いていなければ `false`。
///
/// 常駐（`warifu agent`）は人が居ない間も動く。
/// **落とすしか止め方が無い状態にしない**（`issues/014`）。
///
/// **相手のプロセスを殺さない。**受けた側が自分で降りる ——
/// 割符が他人の機械の中まで手を伸ばさない、という線はここでも引く。
pub fn 席を止める(bridge: &Bridge, 宛先: &str) -> bool {
    席へ配る(bridge, 宛先, FromDesk::Stop)
}

/// 宛先つきで配るときの出所。
///
/// 出所は「**返さない相手**」を指す番号なので、
/// **宛先の席だけが受け取るように、それ以外を指す**形にはできない。
/// だから宛先は別の帯で運ぶ —— 上の 1 桁を立てて「これは宛先つき」と示し、
/// 受ける側が自分あてかどうかを見る。
#[must_use]
const fn 宛先の印(席: u64) -> u64 {
    席 | 宛先の帯
}

/// 「これは宛先つき」を示す帯。**席の番号とぶつからない所に置く。**
const 宛先の帯: u64 = 1 << 63;

/// 配られたものが、自分あてか（宛先つきなら宛先の席だけが受ける）。
#[must_use]
const fn 自分あてか(出所: u64, 自分: u64) -> bool {
    if 出所 & 宛先の帯 == 0 {
        // 宛先なし。**言った本人以外へ配る**
        return 出所 != 自分;
    }
    出所 & !宛先の帯 == 自分
}

/// 会話に出た文字を、机へ配る形にする。
#[must_use]
pub fn 聞いた(from: &str, body: &str) -> FromDesk {
    FromDesk::Heard {
        from: from.to_owned(),
        body: body.to_owned(),
        at: いま時刻(),
    }
}

/// **机が呼び方を刻む。**エージェントは「どこで動いているか」しか名乗れない。
///
/// 名乗りをそのまま出さないのは、**人の発言と見分けが付かなくなる**のを避けるため
/// （`ToDesk::Say` に差出人が無いのと同じ約束）。
/// 「◯◯ の AI」という形に包むので、名乗りが何であれ**AI だと分かる。**
#[must_use]
pub fn 呼び方(名乗り: Option<&str>) -> String {
    match 名乗り {
        // **「AI」ではなく「エージェント」と呼ぶ**（オーナー・2026-09-08）。
        // 「この PC の AI」だと 1 人に見えるが、**着いているのは 1 人ずつのエージェント**である
        Some(名) => format!("{名} のエージェント"),
        // 名乗らなかった。**どこか分からないことを、分かるように見せない**
        None => "名乗りのないエージェント".to_owned(),
    }
}
