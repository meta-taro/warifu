//! **窓を、いま見えている画面の中に置く**（2026-09-30）。
//!
//! ノートの機械では、つないでいる画面が起動のたびに変わる。
//! Windows で、窓が**いまは無い画面の位置**に開き、動いているのに見えなかった
//! （裏では相手とつながっていた）。**起動したのに見えない窓は、起動していないのと同じ**である。

use tauri::{Manager as _, Runtime};

/// 画面の中の四角（物理ピクセル）。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 四角 {
    pub x: i32,
    pub y: i32,
    pub 幅: u32,
    pub 高さ: u32,
}

/// 窓の**つまめる所**（左上から、この幅と高さ）が画面に入っていれば、見えているとみなす。
///
/// 全部が入っている必要はない —— 人が少しはみ出して置いた窓まで動かすと、かえって邪魔になる。
/// **題字の帯がつまめれば、人は自分で動かせる。**
const つまめる幅: i32 = 120;
const つまめる高さ: i32 = 40;

/// **窓のつまめる所が、どれかの画面に入っているか。**
#[must_use]
pub fn 見えているか(窓: 四角, 画面たち: &[四角]) -> bool {
    let (x0, y0) = (窓.x, 窓.y);
    let (x1, y1) = (x0 + つまめる幅, y0 + つまめる高さ);
    画面たち.iter().any(|画面| {
        let 右 = 画面.x + i32::try_from(画面.幅).unwrap_or(i32::MAX);
        let 下 = 画面.y + i32::try_from(画面.高さ).unwrap_or(i32::MAX);
        x0 >= 画面.x && y0 >= 画面.y && x1 <= 右 && y1 <= 下
    })
}

/// **起動したときに一度だけ見る。**見えていなければ、主の画面の真ん中へ戻す。
pub fn 見える所へ<R: Runtime>(app: &tauri::AppHandle<R>) {
    let Some(窓) = app.get_webview_window("main") else {
        return;
    };
    let (Ok(位置), Ok(大きさ), Ok(画面たち)) = (
        窓.outer_position(),
        窓.outer_size(),
        窓.available_monitors(),
    ) else {
        return;
    };
    let 画面たち: Vec<四角> = 画面たち
        .iter()
        .map(|m| 四角 {
            x: m.position().x,
            y: m.position().y,
            幅: m.size().width,
            高さ: m.size().height,
        })
        .collect();
    let いま = 四角 {
        x: 位置.x,
        y: 位置.y,
        幅: 大きさ.width,
        高さ: 大きさ.height,
    };
    if 画面たち.is_empty() || 見えているか(いま, &画面たち) {
        return;
    }
    記録!(
        "窓: いま無い画面の位置に開いていたので、主の画面の真ん中へ戻しました（画面 {} 枚）",
        画面たち.len()
    );
    // 戻せなくても起動は続ける（人は窓の一覧から出せる）
    let _ = 窓.center();
}

#[cfg(test)]
mod 試験 {
    use super::*;

    const 内蔵: 四角 = 四角 {
        x: 0,
        y: 0,
        幅: 1920,
        高さ: 1200,
    };

    #[test]
    fn 画面の中なら_見えている() {
        let 窓 = 四角 {
            x: 26,
            y: 26,
            幅: 1116,
            高さ: 729,
        };
        assert!(見えているか(窓, &[内蔵]));
    }

    #[test]
    fn 外した画面の位置なら_見えていない() {
        // 右につないでいた画面の位置（いまは外してある）
        let 窓 = 四角 {
            x: 2200,
            y: 100,
            幅: 1116,
            高さ: 729,
        };
        assert!(!見えているか(窓, &[内蔵]));
    }

    #[test]
    fn 少しはみ出していても_つまめれば動かさない() {
        let 窓 = 四角 {
            x: 1500,
            y: 300,
            幅: 1116,
            高さ: 729,
        };
        assert!(見えているか(窓, &[内蔵]));
    }

    #[test]
    fn 左や上の画面も_見えている() {
        let 左 = 四角 {
            x: -1920,
            y: 0,
            幅: 1920,
            高さ: 1080,
        };
        let 窓 = 四角 {
            x: -1800,
            y: 50,
            幅: 1116,
            高さ: 729,
        };
        assert!(見えているか(窓, &[内蔵, 左]));
    }

    #[test]
    fn 題字の帯が画面の上にはみ出していたら_見えていない() {
        let 窓 = 四角 {
            x: 100,
            y: -30,
            幅: 1116,
            高さ: 729,
        };
        assert!(!見えているか(窓, &[内蔵]));
    }
}
